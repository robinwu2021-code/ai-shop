/** 订单库存追溯：当前状态、事件投递和实物出入账事实。 */
export interface MerchantInventoryTrace {
  /** Order identifier whose inventory lifecycle is being audited. */
  orderNo: string;
  /** Inventory synchronization events associated with this order. */
  syncEvents: Array<{
    /** Event aggregate that produced this synchronization. */
    aggregateId: string;
    /** Inventory or order event type. */
    eventType: string;
    /** System that requested or handled the synchronization. */
    source: string;
    /** Delivery state of the synchronization event. */
    status: InventorySyncEventState;
    /** Outbox implementation that persisted the event. */
    outboxMode: InventoryOutboxMode;
  }>;
  /** Physical stock reservations associated with this order. */
  reservations: Array<{
    /** Inventory reservation identifier. */
    reservationId: string;
    /** Business owner identifier for the reservation. */
    ownerId: string;
    /** Current lifecycle state of the reservation. */
    status: string;
    /** Version used to detect concurrent lifecycle updates. */
    lifecycleVersion: number | null;
    /** Outbound document that issued the reserved stock, if issued. */
    outboundNo: string | null;
    /** Reservation creation time. */
    createdAt: string | null;
    /** Per-item quantities and issue/return history. */
    lines: Array<{
      /** Line number within the reservation. */
      lineNo: number;
      /** Fulfillment reference linked to this reservation line, if present. */
      fulfillmentRef: string | null;
      /** Inventory item identifier. */
      itemId: string;
      /** Physical location identifier. */
      locationId: string;
      /** Quantity originally reserved. */
      reservedQty: number;
      /** Quantity issued to fulfillment. */
      issuedQty: number;
      /** Quantity released without being issued. */
      releasedQty: number;
      /** Outbound document identifier for issued quantity. */
      outboundNo: string | null;
      /** Time the reservation line was issued, if issued. */
      issuedAt: string | null;
      /** Staff or process that last updated the issue record. */
      updatedBy: string | null;
      /** Immutable inventory ledger rows generated by issuing this line. */
      issueLedger: Array<{
        /** Inventory ledger row identifier. */
        id: number;
        /** Inventory document that recorded the quantity change. */
        docNo: string;
        /** Business reason code for the quantity change. */
        reasonCode: string;
        /** Signed quantity change recorded by the ledger. */
        qtyDelta: number;
        /** Stock balance before applying this ledger entry. */
        balanceBefore: number;
        /** Stock balance after applying this ledger entry. */
        balanceAfter: number;
        /** Human-readable operator name, if available. */
        operator: string | null;
        /** Creator identifier, if available. */
        createdBy: string | null;
        /** Business occurrence time of the ledger entry. */
        occurredAt: string;
      }>;
      /** Returns received against this reservation line. */
      returns: Array<{
        /** Inventory receipt identifier. */
        receiptNo: string;
        /** After-sale case associated with the return. */
        afterSaleNo: string;
        /** Returned quantity received into inventory. */
        qty: number;
        /** Quality classification recorded at receipt. */
        quality: string;
        /** Physical location that received the return. */
        locationId: string;
        /** Inbound document generated for the return. */
        inboundNo: string;
        /** Staff or process that created the receipt. */
        createdBy: string | null;
        /** Receipt creation time. */
        createdAt: string;
      }>;
    }>;
  }>;
}

