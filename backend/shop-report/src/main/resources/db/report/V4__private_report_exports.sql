-- Private on-demand exports; no business database foreign keys or polling cron.
CREATE TABLE rpt_export_task (
    id BIGINT NOT NULL AUTO_INCREMENT,
    tenant_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(64) NOT NULL,
    actor_no VARCHAR(64) NOT NULL,
    export_no VARCHAR(32) NOT NULL,
    authorized_store_nos JSON NOT NULL,
    scope_hash CHAR(64) NOT NULL,
    request_key VARCHAR(128) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    query_snapshot JSON NOT NULL,
    query_hash CHAR(64) NOT NULL,
    build_refs JSON NOT NULL,
    format VARCHAR(16) NOT NULL,
    status VARCHAR(24) NOT NULL,
    attempt_no BIGINT NOT NULL DEFAULT 0,
    lease_owner VARCHAR(64) NULL,
    lease_until DATETIME(6) NULL,
    object_ref VARCHAR(512) NULL,
    retired_objects JSON NOT NULL,
    checksum CHAR(64) NULL,
    row_count BIGINT NULL,
    expires_at DATETIME(6) NOT NULL,
    job_run_id VARCHAR(64) NULL,
    execution_ref VARCHAR(64) NULL,
    error_code VARCHAR(64) NULL,
    last_cleanup_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_rpt_export_no (export_no),
    UNIQUE KEY uk_rpt_export_request (tenant_no,entity_no,actor_no,request_key),
    KEY idx_rpt_export_maintenance (tenant_no,entity_no,status,expires_at,last_cleanup_at),
    KEY idx_rpt_export_recovery (tenant_no,entity_no,status,lease_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
