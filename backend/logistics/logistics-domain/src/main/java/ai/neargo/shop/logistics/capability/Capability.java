package ai.neargo.shop.logistics.capability;

/**
 * 物流渠道的能力。一家渠道会什么不一样：快递100 是聚合（什么承运商都覆盖），圆通直连只覆盖圆通单，
 * 微信只能查状态、不把轨迹节点给我们。所以抽象的单位是**能力**，每家实现自己会的那几个，
 * 路由按能力分别选渠道（TDD-物流模块 §2.1.1）。
 */
public enum Capability {
    /** 订阅：此后渠道把轨迹推给我们 */
    SUBSCRIBE,
    /** 推送接收：验签、解析渠道推来的轨迹 */
    PUSH,
    /** 主动探测：查一次状态 / 节点 */
    PROBE
}
