package ai.neargo.shop.spi.trade;

/**
 * 各域 → trade：这个价位的商品，买了之后能不能极速退。
 *
 * <p><b>为什么商品域要问它</b>：详情页上那条「极速退款」是对外承诺，而它成不成立
 * 取决于售后规则里的金额上限与总开关（运营可调）。商品域自己拿一个常量比金额，
 * 就是端上那份 ¥50 常量的翻版 —— 页面写着承诺、后端按另一个数执行
 * （TDD-C 端商品详情页·内容丰富度 §3.1）。
 *
 * <p>规则在 trade 域，商品域不能直接依赖它的 Service（ArchUnit 第 1 条），所以走这道口。
 */
public interface AfterSaleRulePort {

    /**
     * 这个金额在极速退的覆盖范围内吗（开关开着、且不超上限）。
     *
     * <p><b>不判「下单 N 小时内」</b>：那一条要有订单才谈得上，而这里问的是「买之前」。
     * 所以详情页上的承诺是必要条件 —— 真到申请时还要过那一关，两处判据因此不完全相同，
     * 而这正是对的：商品页不能替一笔还不存在的订单打包票。
     *
     * @param amountMinor 商品价（分）
     */
    boolean instantRefundCovers(long amountMinor);
}
