package ai.neargo.shop.spi.trade;

/**
 * 「这个人还有没有没走完的单」—— 给<b>注销账号</b>那道闸用。
 *
 * <p>为什么必须问：注销之后手机号与 openid 都解绑了，<b>没有任何人能再联系到他</b>，
 * 而这时候货可能正在路上、款可能还没退。让这种账号注销掉，
 * 损失落在两边：他收不到货也找不回入口，客服连人都对不上。
 *
 * <p>走 Port 而不是让用户域直接读订单表：交易域的表结构变了不该让注销链路跟着炸，
 * 而这里真正需要的只是一个布尔值。
 */
public interface OpenOrderPort {

    /**
     * 是否还有未走完的订单或售后。
     *
     * <p>「未走完」= 待付款 / 已付款待履约 / 履约中 / 售后处理中。
     * 已完成、已取消、已退款都不算 —— 那些是终态，注销不影响任何人。
     */
    boolean hasOpenOrders(String userNo);
}
