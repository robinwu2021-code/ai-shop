package ai.neargo.shop.common;

/**
 * 手机号的**格式判据**，一处定义。
 *
 * <p><b>为什么不是「11 位数字」</b>：只查位数会放行 {@code 00000000000} 与
 * {@code 12345678901} —— 它们进得了库、进得了订单快照，而问题要到履约那一端才暴露：
 * 骑手打不通、自提点核销不了，且那时已经查不出是谁在哪一步填错的。
 * 第二位限定 3–9 是大陆号段的现行事实（1 后面接 0/1/2 的号段不发给个人）。
 *
 * <p>与端上 {@code @shared/utils/validate} 的 {@code isPhone} 是**同一条正则**。
 * 两处都要有：端上拦是为了当场给提示，后端拦是因为端上那道拦不住直接打接口的调用方。
 *
 * <p><b>加在哪、不加在哪</b>：只加在「新写一个号进来」的入口（收货人电话、商家给会员建档）。
 * 登录与发码链路上的号码<b>不加</b> —— 存量里已经有格式不对的账号，
 * 在那里收紧等于让这些人当场登不进来，而他们并没有做错什么。
 * 那几处要动，得先数清楚生产库里有多少条，见 usr_identity。
 */
public final class Phones {

    /** 中国大陆手机号。用于 {@code @Pattern(regexp = Phones.CN_MOBILE)}。 */
    public static final String CN_MOBILE = "^1[3-9]\\d{9}$";

    /** 拒绝时的提示。**要点名字段** —— 只说「参数错误」的话，用户改哪儿全靠猜。 */
    public static final String MESSAGE = "手机号格式不对，应为 11 位大陆手机号";

    private Phones() {
    }
}
