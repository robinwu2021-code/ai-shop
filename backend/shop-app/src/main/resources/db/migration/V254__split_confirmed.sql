-- 分账「指令已发出」与「资金已划转」拆开。
--
-- ## 为什么
--
-- `stl_bill.status = 'SPLIT'` 今天**同时表示这两件事**，而底下调的是
-- `StubSplitGateway`（类注释自己写着「接微信支付分账前的临时物」）——
-- **账面显示已分账，一分钱都没有真的动过**，而商家看着以为钱在路上。
--
-- ## 这一列记什么
--
-- 回执确认到账的时刻。与 `split_at`（**指令发出**的时刻）分开 ——
-- 两个时点之间的间隔正是「分账轴对账」要盯的东西：
-- 发出很久而迟不确认的，就是那条轴要捞的差异（工单第 6 步）。
--
-- ⚠️ **这一列只能由通道回执写**，不给人工入口。
-- 与 `stl_withdraw` 的 `APPROVED → PAID` 刻意不给人工入口是同一条规矩：
-- 让人手动把单子做平，之后对账差额永远说不清是「通道慢了」还是「有人点早了」。
--
-- ## 不改变任何存量行为
--
-- 存量的 `SPLIT` 行**保持 SPLIT 不动**，这一列留空。
-- 它们是桩时代产生的，本来就不知道到没到账 —— 回填一个 confirmed 时间
-- 等于凭空断言那些钱到了。接通真分账之后，由对账去认领它们。
ALTER TABLE stl_bill ADD COLUMN split_confirmed_at BIGINT DEFAULT NULL
    COMMENT '分账回执确认到账的时刻。与 split_at（指令发出）分开 —— 两者的间隔是对账要盯的。只能由回执写';
