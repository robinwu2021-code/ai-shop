-- 小微收款额度（落地清单 P2-3 / P2-4）。
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 为什么现在要做
-- ─────────────────────────────────────────────────────────────────────────────
-- F-6 与准入矩阵落地之后，小微商户从「纸面上的一档」变成了系统真支持的一档：
-- 能进来、能上架、能成交。而围绕小微的三个坑随之同时变活 ——
-- 支付能力、开票能力、**收款额度**。
--
-- 微信对小微商户的收款有累计额度，超了之后**收款直接失败**。
-- 系统此前既不知道额度是多少，也不知道用掉了多少：
-- 于是它只会在某个买家付款的那一刻表现为「支付失败」，
-- 而那时候平台既解释不清、也补救不了。
--
-- ⚠️ **额度阈值故意留空（0 = 不限）**：具体数值与统计周期要由服务商确认，
-- 写一个猜的数比不写更危险 —— 它会让人以为这件事已经核对过了。
ALTER TABLE mch_payment_merchant ADD COLUMN quota_limit_minor BIGINT(20) NOT NULL DEFAULT 0
    COMMENT '收款额度上限（分）；0 = 不限。**需服务商确认后由运营填写**';
ALTER TABLE mch_payment_merchant ADD COLUMN quota_used_minor BIGINT(20) NOT NULL DEFAULT 0
    COMMENT '本周期已用额度（分），支付成功时累加';
ALTER TABLE mch_payment_merchant ADD COLUMN quota_period VARCHAR(16) DEFAULT NULL
    COMMENT '当前统计周期标识，如 2026 或 2026-08；换周期时清零重算';
