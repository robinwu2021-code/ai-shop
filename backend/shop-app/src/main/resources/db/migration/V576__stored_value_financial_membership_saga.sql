-- P6 organization coordination only. No balance transfers, copied accounts or historical replay.
CREATE TABLE mch_brand_financial_change (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_no VARCHAR(32) NOT NULL,
 change_no VARCHAR(64) NOT NULL,
 management_no VARCHAR(64) NOT NULL,
 store_no VARCHAR(64) NOT NULL,
 from_brand_no VARCHAR(64) NULL,
 to_brand_no VARCHAR(64) NULL,
 original_actor_no VARCHAR(64) NOT NULL,
 command_key VARCHAR(64) NOT NULL,
 command_hash CHAR(64) NOT NULL,
 source_snapshot JSON NOT NULL,
 pay_prepare_snapshot JSON NULL,
 status VARCHAR(32) NOT NULL,
 active_store_no VARCHAR(64) GENERATED ALWAYS AS (CASE WHEN status IN ('PREPARING','PAY_PREPARED') THEN store_no ELSE NULL END) STORED,
 version BIGINT NOT NULL DEFAULT 0,
 deleted TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL,
 updated_at DATETIME(3) NOT NULL,
 created_by VARCHAR(64) NOT NULL,
 updated_by VARCHAR(64) NOT NULL,
 UNIQUE KEY uk_brand_financial_change(tenant_no,change_no),
 UNIQUE KEY uk_brand_financial_change_command(tenant_no,original_actor_no,command_key),
 UNIQUE KEY uk_brand_financial_change_store(tenant_no,active_store_no),
 CHECK (status IN ('PREPARING','PAY_PREPARED','COMPLETED','REJECTED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_520_ci;
CREATE TABLE sv_financial_membership_change (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_no VARCHAR(32) NOT NULL,
 change_no VARCHAR(64) NOT NULL,
 issuer_no VARCHAR(64) NOT NULL,
 store_no VARCHAR(64) NOT NULL,
 operating_entity_no VARCHAR(64) NOT NULL,
 direction VARCHAR(16) NOT NULL,
 old_binding_no VARCHAR(64) NULL,
 new_binding_no VARCHAR(64) NULL,
 old_revision BIGINT NOT NULL,
 new_revision BIGINT NOT NULL,
 command_hash CHAR(64) NOT NULL,
 source_snapshot JSON NOT NULL,
 status VARCHAR(32) NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 deleted TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL,
 updated_at DATETIME(3) NOT NULL,
 created_by VARCHAR(64) NOT NULL,
 updated_by VARCHAR(64) NOT NULL,
 UNIQUE KEY uk_sv_membership_change(tenant_no,change_no,issuer_no),
 KEY ix_sv_membership_store(tenant_no,issuer_no,store_no,status),
 CHECK (direction IN ('LEAVE','JOIN')),
 CHECK (status IN ('PREPARED','ACTIVE')),
 CHECK (new_revision>old_revision)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_520_ci;
