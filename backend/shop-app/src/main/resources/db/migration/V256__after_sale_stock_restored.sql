-- 退货退款后把货加回库存 —— 补上一条**从来没有实现过**的路径。
--
-- AfterSaleServiceImpl.doRefund 的注释写着「③ 子单转 REFUNDED，发事件（下游据此回补库存、
-- 调整评分）」，事件 OrderEvents.AfterSaleRefunded 也确实发了 —— 但全仓对它的引用只在
-- trade 自己和一个测试里，**商品域一个消费者都没有**。全仓 stockPort.release 只出现在
-- 「用户取消」与「超时关单」两处，都是未支付路径；退款路径一处都没有。
--
-- 后果按售后类型分三种，而 ord_after_sale.type 早就把它们分开了：
--   REFUND_ONLY   仅退款   货没回来 → 不该回补（今天的行为正确）
--   RETURN_REFUND 退货退款 货回来了 → **该回补，而今天不补**：库里当它卖掉了，
--                                      于是这一件会被再卖一次，且要等到发货那天才发现
--   EXCHANGE      换货     一出一入，净变动为零 → 平台侧没有库存流水，这一期不动
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 这一列是干什么的：幂等
-- ─────────────────────────────────────────────────────────────────────────────
-- 退款本身靠「状态早退」幂等（REFUNDED 直接返回），但回补库存与状态落库之间有一道窄窗口：
-- 回补成功而状态没写进去的话，重试会再补一次 —— 而库存多出来的那几件不会有任何地方报错。
--
-- 所以用一个一次性置位的标记，**与回补在同一个事务里写**：置过就不再补。
-- 等真相源切到进销存之后这一列可以退役 —— 那时幂等由库存流水的唯一键
-- (doc_no, line_no) 天然兜住，不需要在业务表上挂标记。
ALTER TABLE ord_after_sale
    ADD COLUMN stock_restored TINYINT NOT NULL DEFAULT 0
        COMMENT '1=已回补过库存。仅 RETURN_REFUND 会置位；与回补同事务，防重试补两次';
