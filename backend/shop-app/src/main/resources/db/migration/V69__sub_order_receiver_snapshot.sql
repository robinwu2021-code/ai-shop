-- 子订单上的收件人快照（B-11.4.7 自送 / B-11.4.2 发货）。
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 缺的是什么
-- ─────────────────────────────────────────────────────────────────────────────
-- 「商家自送」这条链路做到了「待配送列表 + 一键已送达」，**唯独没有送到哪里**：
-- 子单上只有 address_id，OrderVO 里连字段都没有，b-app 配送页也没渲染过。
-- 也就是说**所有角色**（含店主自己）都看不到地址 —— 这不是权限收窄，是能力缺失。
-- 2026-08-12 做配送员视图裁剪时才发现：裁剪的是金额，而他本来就没拿到过地址。
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 为什么是快照，不是查 address_id
-- ─────────────────────────────────────────────────────────────────────────────
-- usr_address **是可改可删的**：买家下完单把地址改成新家、或者删掉，
-- 商家这边看到的就跟着变了 —— 而货已经按旧地址在路上。删掉的话更糟：查不到，
-- 页面上是一片空白，没有任何提示说「这单原本有地址」。
--
-- 与同一段代码里 pickup_name 的处理一致（「自提点改名不该影响历史订单」）。
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 手机号：存完整，**下发时按履约方式脱敏**
-- ─────────────────────────────────────────────────────────────────────────────
-- 库里存完整号 —— 它是这张单自己的数据，不存的话事后无法补救。
-- 但下发口径分两档（见 MerchantOrderServiceImpl）：
--   · MERCHANT_DELIVERY（商家自送）→ **完整号**。送不到门口就得打电话，
--     给后四位等于让配送员站在楼下干瞪眼。2026-08-12 产品确认放开这一档
--   · 其余履约方式 → 脱敏。B12 的原判断不变：商家不需要能打给每一个买家
-- 也就是说 B12 从「一律不给」收窄成「只有自送给」，理由是那一档真的要用它。
ALTER TABLE ord_sub_order
    ADD COLUMN IF NOT EXISTS receiver_name VARCHAR(64) DEFAULT NULL
        COMMENT '收件人姓名快照。下单时固化 —— 买家改地址不该影响已经在路上的单',
    ADD COLUMN IF NOT EXISTS receiver_phone VARCHAR(32) DEFAULT NULL
        COMMENT '收件人手机号快照，**存完整号**。下发按履约方式脱敏：自送给完整，其余给后四位',
    ADD COLUMN IF NOT EXISTS receiver_address VARCHAR(255) DEFAULT NULL
        COMMENT '收货地址快照（省市区 + 详细）。自送与快递都要，自提单为空';

-- 存量回填：有 address_id 的单按当前地址补一次。
--
-- **这不是完美的**——买家如果已经改过地址，补进来的是改后的值。但两害相权：
-- 不回填的话，所有历史的自送单在新页面上都是「地址：—」，
-- 而商家会以为是系统坏了，而不是「这单太老了」。
UPDATE ord_sub_order s
    JOIN usr_address a ON a.address_id = s.address_id
SET s.receiver_name = a.name,
    s.receiver_phone = a.phone,
    s.receiver_address = CONCAT(IFNULL(a.province, ''), IFNULL(a.city, ''),
                                IFNULL(a.district, ''), IFNULL(a.detail, ''))
WHERE s.address_id IS NOT NULL AND s.receiver_name IS NULL;
