    valid_to DATETIME(3) NULL COMMENT '结束',
    status VARCHAR(24) NOT NULL COMMENT 'ACTIVE或INACTIVE',
    public_visible TINYINT NOT NULL COMMENT '对客展示',
    level_code VARCHAR(32) NULL COMMENT '本店业务等级',
    sort_order INT NOT NULL COMMENT '展示顺序',
    PRIMARY KEY (id),
    UNIQUE KEY uk_mch_personnel_store_1 (tenant_no, entity_no, assignment_no),
    KEY idx_mch_personnel_store_1 (tenant_no, entity_no, store_no, status, personnel_no),
