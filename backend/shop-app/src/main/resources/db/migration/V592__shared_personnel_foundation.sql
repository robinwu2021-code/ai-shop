-- Shared personnel: login membership and permission roles remain unchanged.
-- Snapshot schema from approved personnel design; future write workflows enforce cross-row invariants.

CREATE TABLE mch_personnel (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '物理自增主键，不对外',
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN' COMMENT '沿当前租户上下文；不另启租户体系',
    entity_no VARCHAR(32) NOT NULL COMMENT '商家主体范围；不等于租户',
    created_at DATETIME(3) NOT NULL COMMENT '创建时刻',
    created_by VARCHAR(64) NULL COMMENT '实际操作者业务引用',
    updated_at DATETIME(3) NOT NULL COMMENT '更新时间',
    updated_by VARCHAR(64) NULL COMMENT '更新操作者',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '乐观锁',
    deleted INT NOT NULL DEFAULT 0 COMMENT '沿BaseEntity；事实表禁止删除或软删覆盖',
    personnel_no VARCHAR(32) NOT NULL COMMENT '稳定业务人员号',
    name VARCHAR(64) NOT NULL COMMENT '业务姓名',
    avatar_ref VARCHAR(64) NULL COMMENT '媒体引用',
    status VARCHAR(24) NOT NULL COMMENT 'ACTIVE或SUSPENDED或LEFT',
    contact_ref VARCHAR(64) NULL COMMENT '受控联系资料引用',
    PRIMARY KEY (id),
    UNIQUE KEY uk_mch_personnel_1 (tenant_no, entity_no, personnel_no),
    KEY idx_mch_personnel_1 (tenant_no, entity_no, status, id),
    CONSTRAINT ck_mch_personnel_1 CHECK (version >= 0),
    CONSTRAINT ck_mch_personnel_2 CHECK (deleted IN (0,1)),
    CONSTRAINT ck_mch_personnel_3 CHECK (status IN ('ACTIVE','SUSPENDED','LEFT'))
) ENGINE=InnoDB COMMENT='共用业务人员主档';

