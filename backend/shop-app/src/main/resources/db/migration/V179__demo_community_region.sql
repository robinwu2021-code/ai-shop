-- 演示社区补上行政区划归属。
--
-- 「选自提点」要先选区域，而区域列表是**从社区身上聚合出来的** ——
-- 只列有已开通社区的区，否则用户在 2978 个区县里挑一个，十有八九是空的。
-- 这两个演示社区的 region_code 一直是 NULL，于是区域列表恒为空，
-- 整条「按区域找」的路在演示数据上根本走不出来。
--
-- 330106 = 杭州市西湖区（与它们地址里写的「杭州市西湖区文一西路」一致）。
-- 只补 NULL 的：运营已经挂过的不覆盖。
UPDATE cmt_community
SET region_code = '330106',
    city_code   = '3301'
WHERE community_no IN ('C0001', 'C0002')
  AND region_code IS NULL;
