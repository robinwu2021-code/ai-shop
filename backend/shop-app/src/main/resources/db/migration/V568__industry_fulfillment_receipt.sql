-- Original pickup verification metadata; financial and inventory truth remain in their existing owners.
CREATE TABLE ord_industry_fulfillment (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL,
    fulfillment_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    order_no VARCHAR(32) NOT NULL,
    sub_order_no VARCHAR(32) NOT NULL,
    source_system VARCHAR(32) NOT NULL,
    source_type VARCHAR(32) NOT NULL,
    source_no VARCHAR(32) NOT NULL,
    source_version BIGINT NOT NULL,
    source_hash CHAR(64) NOT NULL,
    actor_no VARCHAR(32) NOT NULL,
    operation_key CHAR(64) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    verify_code_hash CHAR(64) NOT NULL,
    expected_sub_version BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL,
    inventory_receipt_json LONGTEXT NULL,
    error_code VARCHAR(64) NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    created_by VARCHAR(32) NOT NULL,
    updated_by VARCHAR(32) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    UNIQUE KEY uk_industry_fulfillment_no (fulfillment_no),
    UNIQUE KEY uk_industry_fulfillment_sub (tenant_no,sub_order_no),
    UNIQUE KEY uk_industry_fulfillment_key (tenant_no,entity_no,store_no,operation_key),
    KEY ix_industry_fulfillment_recovery (tenant_no,status,updated_at,id)
) ENGINE=InnoDB;
