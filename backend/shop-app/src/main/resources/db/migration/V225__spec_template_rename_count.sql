-- 老规格模板里那条叫「规格」的，改叫「数量」。
--
-- V174 播的 6 条平台种子里，SPT_SEED_NORMAL_COUNT 的组名是「规格」，
-- 而它的四个选项是 单件 / 2件装 / 5件装 / 整箱 —— 讲的分明是**数量**。
-- 同一批的兄弟条目都叫得很准：「重量」「包装」「时长」「人数」，只有这条没起对名。
--
-- 为什么这不只是难看：建品页上每个规格组前面都标着组名，于是商家看到的是
-- 「规格：单件 / 2件装 …」—— 而整页要填的东西都叫规格，这个组名等于没说。
-- 商家分不清它和旁边的「包装」有什么区别，只好两个都不选。
--
-- 这条种子今天仍在下发：类目一旦配了规格库就以新库为准（V195），
-- 但**没配规格库的类目还会拿到品类兜底**，兜底走的正是这张老表。
--
-- 只改 name，不动 template_no 与选项 —— 引用它的商品按 template_no 走，改名不影响。
UPDATE prd_spec_template
SET name = '数量', updated_at = NOW(), updated_by = 'SYSTEM'
WHERE template_no = 'SPT_SEED_NORMAL_COUNT' AND name = '规格';
