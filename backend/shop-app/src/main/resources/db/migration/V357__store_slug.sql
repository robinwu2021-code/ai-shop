-- 门店代码：店主自己定的那一串，用在对外链接 /s/<代码> 上（TDD-店铺码与分享 §3.6）。
--
-- **不动 store_code。** V298 的注释把理由写死了：「已经印出去的码不作废」。
-- store_code 是物料上那一串（6 位随机大写，生产实况 SMTBA2 / V9VTDW），
-- 改它等于让店里贴的那张纸失效。两列并存、解析时都认，新链接优先用 slug。
--
-- **不回填**：默认值由店主在 B 端确认（端上按店名给一个拼音建议，他可以改）。
-- 后端替他生成一个拼音默认值有两个问题：拼音库不在离线仓库里装不上，
-- 而且「虹选鲜果·福田店」自动转出来的那一串未必是他想印在名片上的。
-- 没设过就为空，链接回落 store_code —— 与今天的行为一致。

ALTER TABLE mch_store
    ADD COLUMN slug VARCHAR(32) DEFAULT NULL COMMENT '门店代码：店主自定义，小写字母/数字/连字符，3-32 位。对外链接 /s/<slug> 优先用它；为空则回落 store_code';

-- 唯一：它是 URL 的一段，两家店同一个代码的话，/s/ 落到哪家取决于查询顺序。
-- 索引名带表名前缀 —— H2 会把重名索引合并掉（迁移在真库副本上跑过才算数）。
ALTER TABLE mch_store
    ADD UNIQUE KEY uk_mch_store_slug (slug);
