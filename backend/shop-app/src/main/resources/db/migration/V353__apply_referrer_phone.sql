-- 入驻申请记下推荐人（TDD-C 端裂变与商家招募 §8.3）。
--
-- 为什么只是一列而不是一整套邀励：小程序里出现「邀请商家入驻得 X 元」是拉人头 + 奖励，
-- 会被判平台型经营而整包驳（§3.3）。所以奖励规则只在官网与企微里出现，
-- 端内只留这一个中性字段 —— 审核时本来就要知道这家店哪来的。
--
-- 可空：绝大多数申请没有推荐人，存量一行都不用补。
-- 存手机号而不是 user_no：推荐人可能还不是平台用户（官网/企微看到规则的人），
-- 而手机号是这两种人都有的东西。发奖时由运营按号找人。

ALTER TABLE mch_entity_apply
    ADD COLUMN referrer_phone VARCHAR(32) DEFAULT NULL COMMENT '推荐人手机号（选填）。奖励由运营人工发，端内不展示规则';
