-- 快递公司。**与运单号成对**，两者缺一微信发货信息录入就拒（268485226 / 268485227）。
--
-- 为什么此前没有：b 端发货只让填运单号，界面上也没有这一项 ——
-- 在接微信之前这看不出问题（买家自己会去快递官网查），
-- 而接上之后它是硬缺口：**快递单一笔都报不上去，那些订单的货款一直冻在微信那边**。
--
-- 存的是**微信的 delivery_id**，不是我们自己编的码：
-- 上报时原样发过去，中间再做一次映射就会多一处会错的地方。
-- 取值见 ExpressCompanies（2026-09-20 用 get_delivery_list 全量表逐个核验过）。
--
-- 可空：存量单没有这一列，补不出来（当时根本没收集）。
-- 不给 DEFAULT 也是有意的 —— 默认成某一家快递，微信会收下
-- （它不校验公司与单号是否匹配），而买家点「查看物流」查到的是别家的单号。
ALTER TABLE ord_sub_order
    ADD COLUMN express_company VARCHAR(32) DEFAULT NULL COMMENT '快递公司（微信 delivery_id，如 SF/ZTO）。与 express_no 成对';
