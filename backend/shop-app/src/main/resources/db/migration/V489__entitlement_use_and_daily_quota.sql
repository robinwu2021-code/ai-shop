-- Pay-owned use intents, allocations and service-day counters. No legacy coupon changes.

CREATE TABLE IF NOT EXISTS ent_period_bucket (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    instance_no VARCHAR(64) NOT NULL COMMENT '权益实例',
    period_key VARCHAR(32) NOT NULL COMMENT '实例有效期窗口标识',
    service_day DATE NOT NULL COMMENT '市场时区服务日',
    limit_units INT NOT NULL COMMENT '本日上限',
    reserved_units INT NOT NULL DEFAULT 0 COMMENT '本日预占',
    used_units INT NOT NULL DEFAULT 0 COMMENT '本日已用',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity，账务事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新',
    created_by VARCHAR(64) NOT NULL COMMENT '操作者或系统任务',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_bucket (tenant_no,instance_no,period_key,service_day),
    CHECK (limit_units>0 AND reserved_units>=0 AND used_units>=0 AND reserved_units+used_units<=limit_units)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='服务日额度计数，跨日释放回原bucket';

CREATE TABLE IF NOT EXISTS ent_use_intent (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    operation_no VARCHAR(64) NOT NULL COMMENT '核销操作号即hold引用',
    source_key CHAR(64) NOT NULL COMMENT '订单/兑换/服务行使用意图唯一',
    active_source_key CHAR(64) NULL COMMENT '同源修订互斥，只有释放才能重建',
    source_snapshot JSON NOT NULL COMMENT '源订单版本/服务日等',
    settled_source_key CHAR(64) NULL COMMENT '成功订单支付维度唯一，改价重建仍一笔',
    user_no VARCHAR(64) NOT NULL COMMENT '使用者',
    entity_no VARCHAR(64) NOT NULL COMMENT '承担主体',
    store_no VARCHAR(64) NOT NULL COMMENT '核销门店',
    asset_kind VARCHAR(24) NOT NULL COMMENT 'ORDER_COUPON/STORE_EXCHANGE/PAID_CARD/STORED_VALUE',
    authorization_ref VARCHAR(64) NOT NULL COMMENT '可信源本人确认/原有兑换核对凭证',
    command_snapshot JSON NOT NULL COMMENT '冻结的核销命令与源事实',
    payload_hash CHAR(64) NOT NULL COMMENT '重试内容检查',
    status VARCHAR(24) NOT NULL COMMENT 'HELD/COMMITTED/RELEASED/EXCEPTION',
    service_day DATE NULL COMMENT '服务日期',
    source_decision_no VARCHAR(64) NULL COMMENT '源成功或取消决策',
    expires_at DATETIME(3) NOT NULL COMMENT '超时核查时刻',
    committed_at DATETIME(3) NULL COMMENT '成功核销时间',
    usage_no VARCHAR(64) NULL COMMENT '成功记录引用',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity，账务事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新',
    created_by VARCHAR(64) NOT NULL COMMENT '操作者或系统任务',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_operation (tenant_no,operation_no),
    UNIQUE KEY uk_use_source (tenant_no,source_key),
    UNIQUE KEY uk_use_active_source (tenant_no,active_source_key),
    UNIQUE KEY uk_settled_source (tenant_no,settled_source_key),
    KEY ix_use_pending (tenant_no,status,expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='统一权益使用意图，储值和券卡共用状态头';

CREATE TABLE IF NOT EXISTS ent_use_allocation (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    operation_no VARCHAR(64) NOT NULL COMMENT '意图',
    instance_no VARCHAR(64) NOT NULL COMMENT '实例',
    period_key VARCHAR(32) NOT NULL COMMENT '非周期固定NONE',
    service_day DATE NOT NULL COMMENT '实际使用服务日',
    units INT NOT NULL COMMENT '本次预占次数',
    discount_minor BIGINT NOT NULL DEFAULT 0 COMMENT '订单券本次折扣',
    currency VARCHAR(8) NOT NULL COMMENT '折扣币种',
    items_allocation JSON NOT NULL COMMENT '商品/服务行分摊快照',
    reversed_units INT NOT NULL DEFAULT 0 COMMENT '累计恢复次数，条件不超原units',
    reversed_discount_minor BIGINT NOT NULL DEFAULT 0 COMMENT '累计回补折扣，条件不超原discount',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity，账务事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新',
    created_by VARCHAR(64) NOT NULL COMMENT '操作者或系统任务',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_ent_alloc (tenant_no,operation_no,instance_no,period_key,service_day),
    CHECK (units>0 AND discount_minor>=0),
    CHECK (reversed_units>=0 AND reversed_units<=units AND reversed_discount_minor>=0 AND reversed_discount_minor<=discount_minor)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='券卡预占分配，金额折扣分摊不是金额余额';

CREATE TABLE IF NOT EXISTS ent_usage (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    usage_no VARCHAR(64) NOT NULL COMMENT '核销记录号',
    operation_no VARCHAR(64) NOT NULL COMMENT '原意图',
    user_no VARCHAR(64) NOT NULL COMMENT '本人',
    entity_no VARCHAR(64) NOT NULL COMMENT '主体',
    store_no VARCHAR(64) NOT NULL COMMENT '门店',
    store_name VARCHAR(100) NOT NULL COMMENT '发生时门店名',
    asset_kind VARCHAR(24) NOT NULL COMMENT '资产类别',
    title VARCHAR(100) NOT NULL COMMENT '项目摘要',
    units INT NULL COMMENT '核销次数',
    amount_minor BIGINT NULL COMMENT '储值支付额或订单券优惠额',
    currency VARCHAR(8) NULL COMMENT '对应金额币种',
    items_snapshot JSON NOT NULL COMMENT '服务/商品明细',
    service_staff_name VARCHAR(64) NULL COMMENT '服务人员',
    source_order_no VARCHAR(64) NULL COMMENT '源订单',
    operator_no VARCHAR(64) NOT NULL COMMENT '经办者',
    status VARCHAR(16) NOT NULL COMMENT 'COMMITTED，回补另记反向账',
    occurred_at DATETIME(3) NOT NULL COMMENT '业务成功时间',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity，账务事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新',
    created_by VARCHAR(64) NOT NULL COMMENT '操作者或系统任务',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_usage (tenant_no,usage_no),
    UNIQUE KEY uk_usage_op (tenant_no,operation_no),
    KEY ix_user_usage (tenant_no,user_no,store_no,asset_kind,occurred_at DESC,usage_no DESC),
    KEY ix_store_usage (tenant_no,entity_no,store_no,occurred_at DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='核销成功事实，消费者简明查询源';

CREATE TABLE IF NOT EXISTS ent_use_proposal (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    proposal_no VARCHAR(64) NOT NULL COMMENT '预览或报价引用',
    proposal_kind VARCHAR(16) NOT NULL COMMENT 'PREVIEW或QUOTE',
    user_no VARCHAR(64) NOT NULL COMMENT '权益持有人',
    entity_no VARCHAR(64) NOT NULL COMMENT '归属主体',
    payload_snapshot JSON NOT NULL COMMENT '不可变预览及报价绑定',
    snapshot_hash CHAR(64) NOT NULL COMMENT '本人确认的选择摘要',
    expires_at DATETIME(3) NOT NULL COMMENT '只限制新增预占',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '不可物理删除账务相关事实',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC',
    created_by VARCHAR(64) NOT NULL COMMENT '经办者',
    updated_by VARCHAR(64) NOT NULL COMMENT '经办者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_use_proposal (tenant_no,proposal_no),
    KEY ix_proposal_expiry (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='核销预览及报价，创建不扣减资产';
