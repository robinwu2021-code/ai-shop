-- 商品生命周期：草稿态 + 图文详情（商品域-优化总方案 批 D）。
--
-- ① **保存即提审**是当下最贵的一条默认行为：商家填一半点保存，那件半成品
--    立刻进了运营的待审队列。队列里混着半成品，运营分不出哪些真要审 ——
--    而商家那边看到的是「审核中」，他既不敢改也不知道在等什么。
--
-- ② 商品到今天只有轮播图，**没有「详情描述」那一段**。生鲜要写产地与保存方式、
--    服务要写包含项与不包含项，现在只能塞进副标题（一行 30 字）或者不写。

-- ── 1. 草稿态 ─────────────────────────────────────────────────
--
-- 只改注释与默认值，**不回填存量**：把已有的 AUDITING 刷成 DRAFT 会让
-- 运营队列里那些真的在等审的商品凭空消失，而商家还在等结论。
ALTER TABLE prd_goods
    MODIFY COLUMN audit_status VARCHAR(16) NOT NULL DEFAULT 'DRAFT'
        COMMENT 'DRAFT 草稿（不进待审队列）/ AUDITING 待审 / APPROVED 已过审 / REJECTED 已驳回';

-- ── 2. 图文详情 ───────────────────────────────────────────────
--
-- 存**纯文本**，不存 HTML：商家侧是手机端输入，富文本编辑器在小程序里做不出
-- 像样的体验；而收 HTML 就要在三端各做一次消毒，漏一处就是 XSS。
-- 图片仍走 images 那一列的轮播 —— 图文混排要等真有商家提这个需求再说。
ALTER TABLE prd_goods
    ADD COLUMN detail TEXT DEFAULT NULL
        COMMENT '图文详情正文（纯文本）。轮播图仍在 images 列' AFTER images;
