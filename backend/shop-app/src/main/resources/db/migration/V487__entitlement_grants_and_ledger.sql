-- Immutable grant preparations and issued rights share the payment transaction and source identity.
CREATE TABLE ent_grant (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    grant_no VARCHAR(64) NOT NULL COMMENT '发放操作号',
    batch_no VARCHAR(64) NULL COMMENT '批次',
    source_key CHAR(64) NOT NULL COMMENT '来源业务行利益项唯一键',
    source_snapshot JSON NOT NULL COMMENT '原始sourceRef，含订单行/单件序号策略',
    template_version_no VARCHAR(64) NOT NULL COMMENT '固定版本',
    user_no VARCHAR(64) NOT NULL COMMENT '受益人',
    entity_no VARCHAR(64) NOT NULL COMMENT '权益承担主体',
    reservation_no VARCHAR(64) NULL COMMENT 'core参与凭证',
    paid_fact_ref VARCHAR(64) NULL COMMENT '付费购卡支付事实',
    quantity INT NOT NULL COMMENT '本次发放实例数',
    payload_hash CHAR(64) NOT NULL COMMENT '同键异参检测',
    prepared_snapshot JSON NOT NULL COMMENT '原命令/规则/支付时刻/授权敞口',
    status VARCHAR(16) NOT NULL COMMENT 'PREPARED/COMMITTED/ABORTED/EXCEPTION',
    source_decision_no VARCHAR(64) NULL COMMENT '提交或终止持久决策',
    committed_at DATETIME(3) NULL COMMENT '实际发放时间',
    reason_code VARCHAR(64) NULL COMMENT '单项跳过或明确失败原因',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity，账务事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新',
    created_by VARCHAR(64) NOT NULL COMMENT '操作者或系统任务',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_grant (tenant_no,grant_no),
    UNIQUE KEY uk_grant_source (tenant_no,source_key),
    KEY ix_grant_recovery (tenant_no,status,updated_at),
    CHECK (quantity>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='单受益人发放操作及跨域幂等';

CREATE TABLE ent_instance (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    instance_no VARCHAR(64) NOT NULL COMMENT '用户权益号',
    template_version_no VARCHAR(64) NOT NULL COMMENT '原版本',
    grant_no VARCHAR(64) NOT NULL COMMENT '原发放',
    unit_index INT NOT NULL COMMENT '本次发放第几件，从1起',
    source_unit_key CHAR(64) NOT NULL COMMENT '源订单行加单件序号或发放单件唯一',
    user_no VARCHAR(64) NOT NULL COMMENT '所有者',
    entity_no VARCHAR(64) NOT NULL COMMENT '主体',
    kind VARCHAR(24) NOT NULL COMMENT '三类权益',
    status VARCHAR(24) NOT NULL COMMENT 'PENDING_ACTIVATION/ACTIVE/FROZEN/EXHAUSTED/EXPIRED/REVOKED',
    total_units INT NULL COMMENT '总次模式',
    remaining_units INT NULL COMMENT '剩余总次',
    reserved_units INT NOT NULL DEFAULT 0 COMMENT '冻结总次',
    effective_from DATETIME(3) NULL COMMENT '实际起算，首用激活前NULL',
    effective_until DATETIME(3) NULL COMMENT '实际截止开区间',
    activation_at DATETIME(3) NULL COMMENT '激活时刻',
    source_paid_at DATETIME(3) NULL COMMENT '权威支付成功时间',
    rule_snapshot JSON NOT NULL COMMENT '已获权益完整规则',
    asset_seq BIGINT NOT NULL DEFAULT 0 COMMENT '单权益记账序号',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity，账务事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新',
    created_by VARCHAR(64) NOT NULL COMMENT '操作者或系统任务',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_instance (tenant_no,instance_no),
    UNIQUE KEY uk_grant_unit (tenant_no,grant_no,unit_index),
    UNIQUE KEY uk_source_unit (tenant_no,source_unit_key),
    KEY ix_wallet (tenant_no,user_no,kind,status,id),
    CHECK (unit_index>0 AND reserved_units>=0),
    CHECK (remaining_units IS NULL OR remaining_units>=reserved_units)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户实际权益和总次数余额';

CREATE TABLE ent_ledger (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    entry_no VARCHAR(64) NOT NULL COMMENT '分录号',
    instance_no VARCHAR(64) NOT NULL COMMENT '实例',
    asset_seq BIGINT NOT NULL COMMENT '有序账序',
    biz_type VARCHAR(24) NOT NULL COMMENT 'GRANT/HOLD/USE/RELEASE/REVERSE/EXPIRE/FREEZE',
    biz_key VARCHAR(128) NOT NULL COMMENT '每动作分录稳定键',
    units_delta INT NOT NULL COMMENT '总次余额变化',
    reserved_delta INT NOT NULL COMMENT '冻结变化',
    after_units INT NULL COMMENT '总次模式账后余次',
    after_reserved INT NOT NULL COMMENT '账后冻结',
    bucket_key VARCHAR(64) NULL COMMENT '每日计数分配引用',
    origin_entry_no VARCHAR(64) NULL COMMENT '受限内部回补原引用',
    occurred_at DATETIME(3) NOT NULL COMMENT '发生时间',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity，账务事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新',
    created_by VARCHAR(64) NOT NULL COMMENT '操作者或系统任务',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_ent_entry (tenant_no,entry_no),
    UNIQUE KEY uk_asset_seq (tenant_no,instance_no,asset_seq),
    UNIQUE KEY uk_ledger_biz (tenant_no,instance_no,biz_key),
    CHECK (after_reserved>=0),
    CHECK (after_units IS NULL OR after_units>=after_reserved)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='权益次数不可变分录，预占变更也留痕';
