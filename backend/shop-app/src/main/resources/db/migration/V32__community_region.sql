-- 社区挂到行政区划下（ADR-013 阶段一的最后一块）。
--
-- **社区不是行政层级**，是平台的运营单元（一个小区）。但它必须挂在区划下，
-- 否则「按区/按市覆盖」命中不了它 —— 那正是 ADR-013 要做的事：
-- 商家勾一个「西湖区」，展开成该区下的全部社区。
--
-- ── 关于既有的 city_code ────────────────────────────────────────────
--
-- 它的列注释写着「scope=CITY 的商家靠它判定可达」，而**那件事从来没发生过**：
-- MerchantServiceImpl 有两处明确写着「一期只有一个城市，先不按 city_code 收紧」，
-- 且开发库里这一列全是 NULL。它被声明、被塞进 CommunityVO，然后没有任何逻辑读它。
--
-- 所以这不是「替换一个能用的列」，是补上一个一直缺位的关联。
--
-- **仍然保留 city_code，不在这一版删**：我只验证过开发库里它是空的，
-- 别的环境未必。删列不可逆，而留着的代价只是一列噪音 —— 这个不对称值得保守。
-- 等确认所有环境都没有值、且没人再读它，另起一版删掉。

ALTER TABLE cmt_community
    ADD COLUMN region_code VARCHAR(12) DEFAULT NULL
        COMMENT '所属区划（sys_region.region_code）。**建议挂到街道级**：挂区县也能用，但挂街道之后「按街道覆盖」才有意义。空 = 尚未归属，运营端可补' AFTER city_code;

-- 反查索引：「这个区/街道下有哪些社区」是展开覆盖范围时的高频查询，
-- 没有索引的话每次展开都要全表扫社区表
CREATE INDEX idx_cmt_community_region ON cmt_community (region_code);
