-- Pay-owned received credit ledger; no merchant collection/public entry until its source is integrated.
CREATE TABLE sv_account (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    account_no VARCHAR(64) NOT NULL COMMENT '账户号',
    user_no VARCHAR(64) NOT NULL COMMENT '本人',
    entity_no VARCHAR(64) NOT NULL COMMENT '主体',
    currency VARCHAR(8) NOT NULL COMMENT '币种',
    status VARCHAR(16) NOT NULL COMMENT 'ACTIVE/FROZEN',
    principal_minor BIGINT NOT NULL DEFAULT 0 COMMENT '内部本金余额',
    bonus_minor BIGINT NOT NULL DEFAULT 0 COMMENT '内部赠金余额',
    held_principal_minor BIGINT NOT NULL DEFAULT 0 COMMENT '本金冻结',
    held_bonus_minor BIGINT NOT NULL DEFAULT 0 COMMENT '赠金冻结',
    account_seq BIGINT NOT NULL DEFAULT 0 COMMENT '账序',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity，账务事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新',
    created_by VARCHAR(64) NOT NULL COMMENT '操作者或系统任务',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_sv_account (tenant_no,account_no),
    UNIQUE KEY uk_sv_owner (tenant_no,user_no,entity_no,currency),
    CHECK (status IN ('ACTIVE','FROZEN')),
    CHECK (principal_minor>=held_principal_minor AND held_principal_minor>=0 AND bonus_minor>=held_bonus_minor AND held_bonus_minor>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='金额储值账户，不持有活动预算';

CREATE TABLE sv_recharge (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    recharge_no VARCHAR(64) NOT NULL COMMENT '充值号',
    request_id VARCHAR(64) NOT NULL COMMENT '创建幂等键',
    payload_hash CHAR(64) NOT NULL COMMENT '内容摘要',
    reservation_no VARCHAR(64) NOT NULL COMMENT 'core参与凭证',
    activity_no VARCHAR(64) NOT NULL COMMENT 'core活动号',
    activity_version_no VARCHAR(64) NOT NULL COMMENT '固定活动版本',
    user_no VARCHAR(64) NOT NULL COMMENT '受益人',
    entity_no VARCHAR(64) NOT NULL COMMENT '主体',
    store_no VARCHAR(64) NOT NULL COMMENT '实际充值店',
    store_name VARCHAR(100) NOT NULL COMMENT '门店快照',
    currency VARCHAR(8) NOT NULL COMMENT '币种',
    principal_minor BIGINT NOT NULL COMMENT '应实收本金',
    bonus_minor BIGINT NOT NULL COMMENT '赠金快照',
    status VARCHAR(24) NOT NULL COMMENT 'WAIT_COLLECTION/SUBMITTED/RECEIVED/CREDITED/CANCELLED/REJECTED',
    collection_method VARCHAR(16) NULL COMMENT 'CASH/TRANSFER',
    actual_amount_minor BIGINT NULL COMMENT '人工实际收款',
    receipt_ref VARCHAR(128) NULL COMMENT '私有凭据',
    receipt_digest CHAR(64) NULL COMMENT '凭据摘要',
    operator_no VARCHAR(64) NOT NULL COMMENT '经办人',
    received_by VARCHAR(64) NULL COMMENT '有权确认人',
    received_at DATETIME(3) NULL COMMENT '实收确认时间',
    credited_at DATETIME(3) NULL COMMENT '到账时间',
    expires_at DATETIME(3) NOT NULL COMMENT '未实收截止',
    permit_snapshot JSON NOT NULL COMMENT '权威资格与权益范围',
    source_snapshot JSON NOT NULL COMMENT 'core原充值业务来源',
    received_decision_snapshot JSON NULL COMMENT 'pay实收决定，到账只认原记录',
    confirmation_note VARCHAR(500) NULL COMMENT '人工核验备注，不返回消费者',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity，账务事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新',
    created_by VARCHAR(64) NOT NULL COMMENT '操作者或系统任务',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_recharge (tenant_no,recharge_no),
    UNIQUE KEY uk_recharge_request (tenant_no,request_id),
    UNIQUE KEY uk_recharge_permit (tenant_no,reservation_no),
    KEY ix_credit_pending (tenant_no,status,received_at),
    CHECK (principal_minor>0 AND bonus_minor>=0),
    CHECK (status IN ('WAIT_COLLECTION','SUBMITTED','RECEIVED','CREDITED','CANCELLED','REJECTED')),
    CHECK (status NOT IN ('SUBMITTED','RECEIVED','CREDITED') OR
        (collection_method IS NOT NULL AND actual_amount_minor IS NOT NULL
         AND collection_method IN ('CASH','TRANSFER') AND actual_amount_minor=principal_minor
         AND receipt_ref IS NOT NULL AND receipt_digest IS NOT NULL)),
    CHECK (status NOT IN ('RECEIVED','CREDITED') OR
        (received_by IS NOT NULL AND received_at IS NOT NULL AND received_decision_snapshot IS NOT NULL)),
    CHECK ((status='CREDITED' AND credited_at IS NOT NULL) OR (status<>'CREDITED' AND credited_at IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='充值实收与活动凭证快照';

CREATE TABLE sv_lot (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    lot_no VARCHAR(64) NOT NULL COMMENT '批次号',
    account_no VARCHAR(64) NOT NULL COMMENT '账户',
    recharge_no VARCHAR(64) NOT NULL COMMENT '每笔充值唯一',
    activity_version_no VARCHAR(64) NOT NULL COMMENT 'core规则引用',
    principal_minor BIGINT NOT NULL COMMENT '本金余量',
    bonus_minor BIGINT NOT NULL COMMENT '赠金余量',
    held_principal_minor BIGINT NOT NULL DEFAULT 0 COMMENT '本金预占',
    held_bonus_minor BIGINT NOT NULL DEFAULT 0 COMMENT '赠金预占',
    scope_snapshot JSON NOT NULL COMMENT '适用范围不可实时改变',
    credited_at DATETIME(3) NOT NULL COMMENT '入账排序',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity，账务事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新',
    created_by VARCHAR(64) NOT NULL COMMENT '操作者或系统任务',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_sv_lot (tenant_no,lot_no),
    UNIQUE KEY uk_lot_recharge (tenant_no,recharge_no),
    KEY ix_sv_allocate (tenant_no,account_no,credited_at,lot_no),
    CHECK (principal_minor>=held_principal_minor AND held_principal_minor>=0 AND bonus_minor>=held_bonus_minor AND held_bonus_minor>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='金额充值批次与历史使用约定';

