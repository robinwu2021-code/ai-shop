-- Shared platform printing owns delivery only. UNKNOWN is never an automatic paper retry.
CREATE TABLE prn_device (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    device_no VARCHAR(32) NOT NULL,
    vendor VARCHAR(32) NOT NULL,
    connection_type VARCHAR(16) NOT NULL,
    credential_ref VARCHAR(64) NOT NULL,
    bridge_actor_no VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL,
    capabilities LONGTEXT NOT NULL,
    last_seen_at DATETIME(3) NULL,
    online TINYINT NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    created_by VARCHAR(32) NULL,
    updated_by VARCHAR(32) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    deleted TINYINT NOT NULL DEFAULT 0,
    UNIQUE KEY uk_prn_device_no (device_no),
    CONSTRAINT ck_prn_device_caps CHECK (JSON_VALID(capabilities))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE prn_template (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    template_no VARCHAR(32) NOT NULL,
    template_code VARCHAR(32) NOT NULL,
    revision INT NOT NULL,
    scene VARCHAR(32) NOT NULL,
    content TEXT NOT NULL,
    status VARCHAR(16) NOT NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    created_by VARCHAR(32) NULL,
    updated_by VARCHAR(32) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    deleted TINYINT NOT NULL DEFAULT 0,
    UNIQUE KEY uk_prn_template_no (template_no),
    UNIQUE KEY uk_prn_template_revision (tenant_no, entity_no, store_no, template_code, revision),
    CONSTRAINT ck_prn_template_revision CHECK (revision > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE prn_route (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    route_no VARCHAR(32) NOT NULL,
    scene VARCHAR(32) NOT NULL,
    station_no VARCHAR(32) NOT NULL DEFAULT '',
    device_no VARCHAR(32) NOT NULL,
    template_no VARCHAR(32) NOT NULL,
    copies INT NOT NULL,
    match_rule LONGTEXT NOT NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    created_by VARCHAR(32) NULL,
    updated_by VARCHAR(32) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    deleted TINYINT NOT NULL DEFAULT 0,
    UNIQUE KEY uk_prn_route_no (route_no),
    UNIQUE KEY uk_prn_route_target (tenant_no, entity_no, store_no, scene, station_no, device_no),
    CONSTRAINT ck_prn_route_copies CHECK (copies BETWEEN 1 AND 10),
    CONSTRAINT ck_prn_route_rule CHECK (JSON_VALID(match_rule))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE prn_job (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    job_no VARCHAR(32) NOT NULL,
    source_event_no VARCHAR(64) NOT NULL,
    scene VARCHAR(32) NOT NULL,
    device_no VARCHAR(32) NOT NULL,
    part_no VARCHAR(32) NOT NULL,
    copy_index INT NOT NULL,
    template_no VARCHAR(32) NOT NULL,
    document_snapshot LONGTEXT NOT NULL,
    rendered_content LONGTEXT NOT NULL,
    status VARCHAR(24) NOT NULL,
    original_job_no VARCHAR(32) NULL,
    dedup_key CHAR(64) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    event_root_key CHAR(64) NULL,
    reprint_reason VARCHAR(256) NULL,
    requested_by VARCHAR(32) NOT NULL,
    lease_until DATETIME(3) NULL,
    current_attempt_no VARCHAR(32) NULL,
    lease_token VARCHAR(64) NULL,
    attempt_count INT NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    created_by VARCHAR(32) NULL,
    updated_by VARCHAR(32) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    deleted TINYINT NOT NULL DEFAULT 0,
    UNIQUE KEY uk_prn_job_no (job_no),
    UNIQUE KEY uk_prn_job_dedup (dedup_key),
    UNIQUE KEY uk_prn_event_root (event_root_key),
    KEY idx_prn_job_claim (tenant_no, entity_no, store_no, device_no, status, id),
    CONSTRAINT ck_prn_job_document CHECK (JSON_VALID(document_snapshot))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE prn_attempt (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    attempt_no VARCHAR(32) NOT NULL,
    job_no VARCHAR(32) NOT NULL,
    sequence_no INT NOT NULL,
    channel_job_no VARCHAR(64) NULL,
    status VARCHAR(24) NOT NULL,
    response_code VARCHAR(64) NULL,
    started_at DATETIME(3) NOT NULL,
    finished_at DATETIME(3) NULL,
    lease_token VARCHAR(64) NOT NULL,
    bridge_actor_no VARCHAR(32) NOT NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    created_by VARCHAR(32) NULL,
    updated_by VARCHAR(32) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    deleted TINYINT NOT NULL DEFAULT 0,
    UNIQUE KEY uk_prn_attempt_no (attempt_no),
    UNIQUE KEY uk_prn_attempt_sequence (tenant_no, job_no, sequence_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
