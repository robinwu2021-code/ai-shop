-- Shared weekly schedule foundation; capacity generation and exception approval are separate workflows.
CREATE TABLE mch_schedule_rule (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '物理自增主键，不对外',
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN' COMMENT '沿当前租户上下文',
    entity_no VARCHAR(32) NOT NULL COMMENT '经营主体范围',
    created_at DATETIME(3) NOT NULL COMMENT '创建时刻',
    created_by VARCHAR(64) NULL COMMENT '实际操作者',
    updated_at DATETIME(3) NOT NULL COMMENT '更新时间',
    updated_by VARCHAR(64) NULL COMMENT '更新操作者',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '乐观锁',
    deleted INT NOT NULL DEFAULT 0 COMMENT '沿BaseEntity',
    rule_no VARCHAR(32) NOT NULL COMMENT '规则号',
    resource_no VARCHAR(32) NOT NULL COMMENT '可占资源',
    store_no VARCHAR(32) NOT NULL COMMENT '作业门店',
    timezone VARCHAR(64) NOT NULL COMMENT '业务时区',
    weekday_mask INT NOT NULL COMMENT 'ISO星期一bit0至星期日bit6',
    start_minute INT NOT NULL COMMENT '本地开始分钟',
    end_minute INT NOT NULL COMMENT '结束分钟',
    end_day_offset INT NOT NULL COMMENT '跨午夜偏移',
    valid_from DATE NOT NULL COMMENT '规则首个开始日',
    valid_to DATE NULL COMMENT '规则最后开始日，包含',
    status VARCHAR(24) NOT NULL COMMENT 'ACTIVE或INACTIVE',
    PRIMARY KEY (id),
    UNIQUE KEY uk_mch_schedule_rule_no (tenant_no, entity_no, rule_no),
    KEY idx_mch_schedule_resource (tenant_no, entity_no, resource_no, valid_from),
    KEY idx_mch_schedule_store (tenant_no, entity_no, store_no, status),
    CONSTRAINT ck_mch_schedule_rule_version CHECK (version >= 0),
    CONSTRAINT ck_mch_schedule_rule_deleted CHECK (deleted IN (0,1)),
    CONSTRAINT ck_mch_schedule_rule_days CHECK (weekday_mask BETWEEN 1 AND 127),
    CONSTRAINT ck_mch_schedule_rule_minutes CHECK (start_minute BETWEEN 0 AND 1439 AND end_minute BETWEEN 0 AND 1440),
    CONSTRAINT ck_mch_schedule_rule_offset CHECK (end_day_offset IN (0,1)),
    CONSTRAINT ck_mch_schedule_rule_duration CHECK (end_day_offset*1440+end_minute-start_minute BETWEEN 1 AND 1440),
    CONSTRAINT ck_mch_schedule_rule_dates CHECK (valid_to IS NULL OR valid_to >= valid_from),
    CONSTRAINT ck_mch_schedule_rule_status CHECK (status IN ('ACTIVE','INACTIVE')),
    CONSTRAINT ck_mch_schedule_rule_timezone CHECK (CHAR_LENGTH(TRIM(timezone)) > 0)
) ENGINE=InnoDB COMMENT='资源班表规则';

CREATE TABLE mch_schedule_change_log (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '物理自增主键，不对外',
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN' COMMENT '沿当前租户上下文',
    entity_no VARCHAR(32) NOT NULL COMMENT '经营主体范围',
    created_at DATETIME(3) NOT NULL COMMENT '创建时刻',
    created_by VARCHAR(64) NULL COMMENT '实际操作者',
    updated_at DATETIME(3) NOT NULL COMMENT '更新时间',
    updated_by VARCHAR(64) NULL COMMENT '更新操作者',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '乐观锁',
    deleted INT NOT NULL DEFAULT 0 COMMENT '沿BaseEntity',
    change_no VARCHAR(32) NOT NULL COMMENT '变更号',
    resource_no VARCHAR(32) NOT NULL COMMENT '资源',
    source_ref VARCHAR(64) NOT NULL COMMENT '规则或例外来源',
    before_revision BIGINT NOT NULL COMMENT '原版本',
    after_revision BIGINT NOT NULL COMMENT '新版本',
    affected_refs JSON NOT NULL COMMENT '受影响业务引用快照',
    reason VARCHAR(500) NOT NULL COMMENT '理由',
    PRIMARY KEY (id),
    UNIQUE KEY uk_mch_schedule_change_no (tenant_no, entity_no, change_no),
    KEY idx_mch_schedule_change_resource (tenant_no, entity_no, resource_no, created_at, id),
    CONSTRAINT ck_mch_schedule_change_version CHECK (version >= 0),
    CONSTRAINT ck_mch_schedule_change_deleted CHECK (deleted IN (0,1)),
    CONSTRAINT ck_mch_schedule_change_revision CHECK (before_revision >= 0 AND after_revision > before_revision)
) ENGINE=InnoDB COMMENT='班表调整历史';
