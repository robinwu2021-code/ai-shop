-- 公告的有效期与常用列表。
--
-- 公告是这一屏唯一的高频内容：店主一天可能改两次（早上到货、下午卖完），
-- 而地址、营业时间一年改几次。此前它们并排放在「店铺装修」里，
-- 改一次公告要进设置页、找到那一格、全选删掉、重打一遍。
--
-- 两列各解决一个真实的毛病：
--
--  1. `announcement_until` —— 最常见的故障是「昨天到货」挂了一周。
--     **过期靠读时判断，不靠定时任务**：`until < now()` 就当空。
--     定时任务会在重启、时区、漏跑上出问题，而这件事经不起漏一次
--     （比没有公告更伤信任：买家照着来了，货没有）。空 = 长期有效。
--
--  2. `announcement_recent` —— 店主的公告是在几句话之间轮换，不是每次都写新的。
--     存最近用过的 5 条，点一下即换。JSON 数组，服务端维护（去重 + 按最近使用排序）。
ALTER TABLE mch_store
    ADD COLUMN announcement_until BIGINT(20) NULL COMMENT '公告失效时刻（epoch 毫秒）。空 = 长期。过期由读时判断，不跑定时任务',
    ADD COLUMN announcement_recent VARCHAR(512) NULL COMMENT '最近用过的公告，JSON 数组最多 5 条，按最近使用排序。点一下即换';
