-- 降级单强制买家确认收货（落地清单 F-4）。
--
-- 准入矩阵有一条降级规则：当**供货方就是自提点运营者**时（邻居自己供货、
-- 自己家就是自提点），那道「独立第三方核销」实际上不存在 —— 自己发货、自己核销、
-- 自己证明送到了。此时交付留痕等级要降一级重查矩阵。
--
-- 降级之后落进「⚠️」格的单，**核销不再等于完成**：只剩买家能证明货真的到了手上。
-- 这个标记在下单那一刻算好并落库，而不是核销时现算 —— 现算的话，
-- 商家事后把自提点换个人，历史单的判定就跟着变了。与 business_mode 快照同一个道理。
ALTER TABLE ord_sub_order ADD COLUMN require_buyer_confirm TINYINT(4) NOT NULL DEFAULT 0
    COMMENT '1 = 核销不能直接完成，必须买家确认收货（准入矩阵降级单）';
