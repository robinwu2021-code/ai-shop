-- S14 · 费率按市场分档（原编号 V296，与另一会话撞号后让路）
--
-- 费率的定位键今天是 (通道, 支付方式, 法律形态, 生效时间)，没有市场。
-- 台湾的微信费率与大陆的不是一回事：手续费率不同、单笔最低值是另一种货币，
-- 而 min_fee_minor 存的是「分」—— 它到底是几分钱，取决于哪个市场。
--
-- **现在做是因为这张表还是空的。**（2026-09-02 查过生产：0 行。）
-- 等有了行再加这一列，就要回答「这一行当时指的是哪个市场」——
-- 而那个问题问不出来：默认填 CN 会把一条本该全局通用的费率钉死在大陆，
-- 默认填通配又会让本该只适用大陆的费率漏到别的市场去。
-- 两个方向都错，且错了不报。
--
-- 与 collation 那笔历史欠账同一个道理：趁还便宜的时候做。

ALTER TABLE sys_pay_channel_rate
    ADD COLUMN market VARCHAR(8) NOT NULL DEFAULT '*'
        COMMENT '适用市场；* = 不分市场，与 pay_method / legal_form 的通配同一个哨兵';

-- **不需要另写一句回填。** ADD COLUMN 带 NOT NULL DEFAULT 时，
-- 已有行会被填成默认值 —— 这一点写错过一版：本来跟了一句
-- `UPDATE ... WHERE market IS NULL`，而 NOT NULL 让那个条件永远不成立，
-- 那句 SQL 一行都改不到，却看起来像是在兜底。
-- （生产这张表本来就是 0 行，两种写法结果一样 —— 但一句永远不做事的 SQL
-- 会让下一个人以为存量是被处理过的。）
