-- Native CHANNEL decisions conserve original immutable quote allocations; supplier ACK never closes local funds.
CREATE TABLE ord_channel_after_sale (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    decision_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    admission_no VARCHAR(32) NOT NULL,
    source_system VARCHAR(32) NOT NULL,
    order_no VARCHAR(32) NOT NULL,
    sub_order_no VARCHAR(32) NOT NULL,
    external_case_ref VARCHAR(128) NOT NULL,
    request_key_hash VARCHAR(64) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    source_hash VARCHAR(64) NOT NULL,
    decision_snapshot LONGTEXT NOT NULL,
    action VARCHAR(32) NOT NULL,
    refund_ceiling_minor BIGINT NOT NULL,
    currency VARCHAR(3) NOT NULL,
    funds_status VARCHAR(32) NOT NULL,
    inventory_status VARCHAR(40) NOT NULL,
    inventory_receipt_snapshot LONGTEXT NULL,
    UNIQUE KEY uk_ord_channel_after_sale(tenant_no,decision_no),
    UNIQUE KEY uk_ord_channel_after_sale_case(tenant_no,entity_no,store_no,admission_no,external_case_ref),
    UNIQUE KEY uk_ord_channel_after_sale_request(tenant_no,entity_no,store_no,admission_no,request_key_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE ord_channel_after_sale_line (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    decision_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    admission_no VARCHAR(32) NOT NULL,
    source_line_ref VARCHAR(128) NOT NULL,
    component_ref VARCHAR(64) NOT NULL,
    physical_quantity DECIMAL(24,6) NOT NULL,
    refund_ceiling_minor BIGINT NOT NULL,
    UNIQUE KEY uk_ord_channel_after_sale_line(tenant_no,decision_no,source_line_ref,component_ref),
    KEY idx_ord_channel_after_sale_cumulative(tenant_no,entity_no,store_no,admission_no,component_ref)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
