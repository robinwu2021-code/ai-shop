-- 公告最后一次发布的时刻。
--
-- 买家侧那一行公告现在是**没有时间的一句话**：「今天到了新米」既可能是今早写的，
-- 也可能是上个月忘了撤的。老客分不出来，分不出来就不再照着它跑一趟 ——
-- 而「照着公告来一趟」正是这行字存在的全部理由。
--
-- 为什么单独存一列而不用 updated_at：`mch_store` 的 updated_at 会因为改营业时间、
-- 换收款号、改地址而变。拿它当公告时间，会把一句三周前的公告显示成「刚刚更新」，
-- 那比不显示时间更糟。
--
-- 只在**公告正文真的变了**的时候写它（含审核通过时那一刻），
-- 改有效期、撤下、改别的门面字段都不动它。
ALTER TABLE mch_store
    ADD COLUMN announcement_at BIGINT(20) NULL COMMENT '公告最后一次发布的时刻（epoch 毫秒）。只在正文变化时更新';
