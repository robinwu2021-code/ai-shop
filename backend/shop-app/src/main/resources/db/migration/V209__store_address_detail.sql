-- 门牌号 / 楼栋，与地图给的地址分开存。
--
-- 为什么不合并成一个 address：门店地址现在靠地图选点得到（「广东省深圳市龙华区…招商锦绣观园」），
-- 而买家要照着找门，缺的正是「3 栋 2 单元 501」这一截。此前只有一个输入框，
-- 商家补完门牌号之后**再点一次地图选点，整条就被覆盖**——他补的那一截无声消失，
-- 而他多半不会立刻发现（地址看着还是对的，只是又回到了小区门口）。
--
-- 与 cmt_community 上提报小区时的做法同一形状：地图给的部分可信、不让手改，
-- 手填的部分单独一格，两者拼起来才是买家看到的完整地址。
ALTER TABLE mch_store
    ADD COLUMN address_detail VARCHAR(64) NULL COMMENT '门牌号/楼栋，商家手填。与 address（地图给的）拼接展示';
