CREATE TABLE pmt_sv_release_link (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 tenant_no VARCHAR(32) NOT NULL,
 link_no VARCHAR(64) NOT NULL,
 management_no VARCHAR(64) NOT NULL,
 store_no VARCHAR(64) NOT NULL,
 entity_no VARCHAR(64) NOT NULL,
 activity_no VARCHAR(64) NOT NULL,
 draft_revision_no VARCHAR(64) NOT NULL,
 draft_hash CHAR(64) NOT NULL,
 activity_version_no VARCHAR(64) NULL,
 issuer_no VARCHAR(64) NULL,
 release_no VARCHAR(64) NULL,
 release_hash CHAR(64) NULL,
 publish_command_no VARCHAR(64) NOT NULL,
 state VARCHAR(32) NOT NULL,
 submitted_by VARCHAR(64) NOT NULL,
 submitted_principal VARCHAR(64) NOT NULL,
 scope_snapshot JSON NOT NULL,
 permission_snapshot JSON NOT NULL,
 policy_versions JSON NOT NULL,
 policy_hash CHAR(64) NOT NULL,
 approval_required TINYINT NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 deleted TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME(3) NOT NULL,
 updated_at DATETIME(3) NOT NULL,
 created_by VARCHAR(64) NOT NULL,
 updated_by VARCHAR(64) NOT NULL,
 UNIQUE KEY uk_sv_link_no (tenant_no,link_no),
 UNIQUE KEY uk_sv_link_draft (tenant_no,activity_no,draft_revision_no),
 UNIQUE KEY uk_sv_link_version (tenant_no,activity_version_no),
 UNIQUE KEY uk_sv_link_release (tenant_no,release_no),
 UNIQUE KEY uk_sv_link_command (tenant_no,publish_command_no),
 KEY ix_sv_link_recovery (tenant_no,state,updated_at),
 CONSTRAINT ck_sv_link_state CHECK (state IN ('DRAFT','PENDING_APPROVAL','APPROVED','PREPARING','PAY_READY','ACTIVE','STOP_REQUESTED','STOPPED','STALE','BLOCKED_POLICY','FAILED')),
 CONSTRAINT ck_sv_link_approval CHECK (approval_required IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
