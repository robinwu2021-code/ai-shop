-- 对账差异加「轴」维度：这条差异是哪一类对账发现的。
--
-- ## 为什么需要它
--
-- 资金链路上有四处会对不上，而它们的数据源、判据、**该找谁处置**各不相同：
--
--   收款    用户付了钱而我方没收到回调        → 找支付通道对
--   分账    我方发出了指令而通道迟迟不确认    → 找分账通道对
--   出款    自营应付登记了付款而银行流水对不上 → 找财务对
--   积分池  池子余额与流通中的积分不相等      → 找账不找人
--
-- 混在一张表里而不标轴的话，运营看到一条差异不知道该找谁 ——
-- 而「不知道找谁」的差异最终会变成「没人处置」的差异。
--
-- ## 默认值是 PAYMENT
--
-- 存量差异行全部来自收款自查（一期只有那一个产出方），所以默认值就是真值 ——
-- 不需要回填。**这一点是查过的**：ReconServiceImpl 是唯一写这张表的地方。
ALTER TABLE stl_recon_diff ADD COLUMN axis VARCHAR(16) NOT NULL DEFAULT 'PAYMENT'
    COMMENT '哪条对账轴发现的：PAYMENT 收款 / SPLIT 分账 / PAYOUT 出款 / POINTS_POOL 积分池';
