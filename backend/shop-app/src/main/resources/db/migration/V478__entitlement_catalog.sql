-- Entitlement catalog only: no legacy ownership or consumer balance changes.
CREATE TABLE IF NOT EXISTS ent_template (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    template_no VARCHAR(64) NOT NULL COMMENT '模板号，保留迁移映射',
    entity_no VARCHAR(64) NOT NULL COMMENT '商家或平台主体',
    title VARCHAR(100) NOT NULL COMMENT '标题',
    kind VARCHAR(24) NOT NULL COMMENT 'ORDER_COUPON/STORE_EXCHANGE/PAID_CARD',
    funder VARCHAR(16) NOT NULL COMMENT 'MERCHANT/PLATFORM',
    status VARCHAR(16) NOT NULL COMMENT 'DRAFT/ACTIVE/PAUSED/ENDED',
    current_version_no VARCHAR(64) NULL COMMENT '当前发布版本',
    draft_snapshot JSON NOT NULL COMMENT '可编辑草稿规则，发布时复制为不可变版本',
    archived_at DATETIME(3) NULL COMMENT '归档时间',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity，账务事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新',
    created_by VARCHAR(64) NOT NULL COMMENT '操作者或系统任务',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_template (tenant_no,template_no),
    KEY ix_ent_templates (tenant_no,entity_no,kind,status,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='支付权益模板管理头';

CREATE TABLE IF NOT EXISTS ent_template_version (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    version_no VARCHAR(64) NOT NULL COMMENT '版本号',
    template_no VARCHAR(64) NOT NULL COMMENT '模板头',
    version_index INT NOT NULL COMMENT '版本序号',
    currency VARCHAR(8) NOT NULL COMMENT '金额/商品售价需兼容',
    benefit_mode VARCHAR(24) NOT NULL COMMENT 'CASH/PERCENT/FREE_SHIP/GIFT/SERVICE_UNITS',
    benefit_value BIGINT NULL COMMENT '面额或应付比例bp',
    benefit_cap_minor BIGINT NULL COMMENT '折扣减免上限',
    min_amount_minor BIGINT NULL COMMENT '门槛',
    usage_model VARCHAR(24) NOT NULL COMMENT 'COUNT/PERIOD_COUNT/PERIOD_DAILY',
    total_units INT NULL COMMENT '总次数，不适用NULL',
    daily_units INT NULL COMMENT '每日上限',
    validity_mode VARCHAR(16) NOT NULL COMMENT 'ABSOLUTE/RELATIVE',
    valid_from DATETIME(3) NULL COMMENT '绝对开始',
    valid_until DATETIME(3) NULL COMMENT '绝对结束，开区间',
    valid_days INT NULL COMMENT '滚动天数',
    start_basis VARCHAR(16) NOT NULL COMMENT 'GRANTED/PAID/FIRST_USE',
    period_basis VARCHAR(24) NOT NULL COMMENT 'ROLLING_DAYS/CALENDAR_MONTH',
    market_zone VARCHAR(64) NOT NULL COMMENT '时间窗口计算时区',
    redemption_scope JSON NOT NULL COMMENT '门店/商品/服务范围',
    allowed_issue_modes JSON NOT NULL COMMENT 'CENTER/TARGETED/ACTIVITY/PAID_ORDER',
    policy_snapshot JSON NOT NULL COMMENT '完整规则及尾差/预约限制',
    snapshot_hash CHAR(64) NOT NULL COMMENT '完整性摘要',
    published_by VARCHAR(64) NOT NULL COMMENT '发布人',
    published_at DATETIME(3) NOT NULL COMMENT '发布时间',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity，账务事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新',
    created_by VARCHAR(64) NOT NULL COMMENT '操作者或系统任务',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_ent_version (tenant_no,version_no),
    UNIQUE KEY uk_ent_version_seq (tenant_no,template_no,version_index),
    CHECK (total_units IS NULL OR total_units>0),
    CHECK (daily_units IS NULL OR daily_units>0),
    CHECK (benefit_cap_minor IS NULL OR benefit_cap_minor>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='发布权益不可变版本，券和付费卡都在pay';

CREATE TABLE IF NOT EXISTS pay_ent_command_dedup (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    operation_kind VARCHAR(64) NOT NULL COMMENT '接口/动作命名空间',
    request_key VARCHAR(64) COLLATE utf8mb4_bin NOT NULL COMMENT 'Idempotency-Key',
    payload_hash CHAR(64) NOT NULL COMMENT '同键异参检测',
    resource_no VARCHAR(64) NOT NULL COMMENT '原资源或操作号',
    result_status VARCHAR(24) NOT NULL COMMENT 'PENDING/COMPLETED',
    response_snapshot JSON NULL COMMENT '稳定业务响应，不含敏感token',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity，账务事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新',
    created_by VARCHAR(64) NOT NULL COMMENT '操作者或系统任务',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_command (tenant_no,operation_kind,request_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='写接口幂等结果，与本域业务变更同事务';
