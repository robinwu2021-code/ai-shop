-- Immutable per-unit entitlement definition captured for a paid-card checkout (JB-012).
CREATE TABLE ord_card_sale_snapshot (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Internal primary key',
    tenant_no VARCHAR(32) NOT NULL,
    snapshot_no VARCHAR(64) NOT NULL,
    source_key CHAR(64) NOT NULL,
    order_no VARCHAR(64) NOT NULL,
    sub_order_no VARCHAR(64) NOT NULL,
    order_line_no VARCHAR(64) NOT NULL,
    unit_index INT NOT NULL,
    entitlement_index INT NOT NULL,
    user_no VARCHAR(64) NOT NULL,
    entity_no VARCHAR(64) NOT NULL,
    store_no VARCHAR(64) NOT NULL,
    goods_no VARCHAR(64) NOT NULL,
    sku_no VARCHAR(64) NOT NULL,
    template_version_no VARCHAR(64) NOT NULL,
    unit_price_minor BIGINT NOT NULL,
    currency VARCHAR(8) NOT NULL,
    rule_snapshot JSON NOT NULL,
    snapshot_hash CHAR(64) NOT NULL,
    paid_fact_no VARCHAR(64) NULL,
    paid_at DATETIME(3) NULL,
    version BIGINT NOT NULL DEFAULT 0,
    deleted TINYINT NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    created_by VARCHAR(64) NOT NULL,
    updated_by VARCHAR(64) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_card_sale_snapshot (tenant_no, snapshot_no),
    UNIQUE KEY uk_card_sale_source (tenant_no, source_key),
    UNIQUE KEY uk_card_sale_unit (tenant_no, order_line_no, unit_index, entitlement_index),
    KEY ix_card_sale_order (tenant_no, order_no),
    CHECK (unit_index > 0 AND entitlement_index > 0 AND unit_price_minor >= 0),
    CHECK ((paid_fact_no IS NULL AND paid_at IS NULL) OR (paid_fact_no IS NOT NULL AND paid_at IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Frozen paid-card order-unit entitlement facts';
