-- 资金路径（轴②）：钱先进谁的账户。
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 为什么它必须是独立的一列，不能和 business_mode 合并
-- ─────────────────────────────────────────────────────────────────────────────
-- 两件事：
--   funds_mode      钱先进谁的账户   AGGREGATED 平台户 / DIRECT 商家二级户
--   business_mode   谁是销售主体     SELF_OPERATED 平台 / THIRD_PARTY 商家
--
-- 高度相关，但**不是同一件事**。合成一个枚举之后，
-- 「直连 + 自营」（钱进商家户却说平台是卖方）这种非法组合在类型上就是可表达的，
-- 只能靠运行时校验挡；分成两列，非法组合在语义上不存在。
-- 同型教训见 ADR-013。
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 为什么「要不要补差」看的是这一列
-- ─────────────────────────────────────────────────────────────────────────────
--   钱在商家账户（DIRECT）    → 积分抵扣让他少收 → 平台必须补差进去
--   钱在平台账户（AGGREGATED）→ 平台自己少收     → **无人需要补**
--
-- 判据是「钱在谁手里」，不是「谁是销售主体」。用 business_mode 判，
-- 在两者不一致时会判错 —— 而这个库里恰好有一批这样的单（V23 回填的 54 张）。
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 存量默认 AGGREGATED 为什么是安全的（与 V23 那次不同）
-- ─────────────────────────────────────────────────────────────────────────────
-- 全库 145 家门店都是自营 + 平台收款，默认值与**存量事实一致**。
--
-- V23 那次相反：它给 stl_bill 加 business_mode 时默认 SELF_OPERATED，
-- 而当时库里 54 张单是第三方轨道的（status=PENDING）——
-- 默认值与事实相反，于是那 54 张单的快照全是假的，至今卡死：
-- 进不了自营对账（confirmRecon 要求 PENDING_RECON），也回不去第三方分账。
--
-- **「新增默认最严」是安全设计，「存量默认最严」是生产事故。**
-- 这次可以用默认值，是因为默认值恰好等于事实 —— 不是因为「加列都可以这么写」。
-- 下一个人照抄这个写法前，先确认你的默认值与存量事实是否一致。

ALTER TABLE mch_entity ADD COLUMN funds_mode VARCHAR(16) NOT NULL DEFAULT 'AGGREGATED'
    COMMENT '资金路径：AGGREGATED 归集（用户付给平台户，代销）/ DIRECT 直连（付给商家二级户，分账）。
             **能走哪条由商户类型决定，不是平台自选**（ADR-015 §3.2）：
             自然人开不出票 → 禁归集；自产农产品例外（平台可自开收购发票）';

ALTER TABLE stl_bill ADD COLUMN funds_mode VARCHAR(16) NOT NULL DEFAULT 'AGGREGATED'
    COMMENT '下单时的资金路径**快照**。与 business_mode 是两列，不要合并 ——
             路径改了，历史单的资金性质不跟着改';

ALTER TABLE stl_bill ADD COLUMN points_cost_minor BIGINT(20) NOT NULL DEFAULT 0
    COMMENT '归集路径下平台自己承担的积分成本（分）。**与 subsidy_minor 互斥**：
             后者是直连下真的划进商家账户的一笔钱，前者只是记账（平台少收）。
             混用的后果是读单据的人以为平台补过钱 —— 而归集路径上没有这个动作';

CREATE INDEX idx_bill_funds_mode ON stl_bill (funds_mode);

-- 农业生产者标记 —— **从第五步提前到这里**。
--
-- 没有它就表达不了「自然人禁归集」的那条例外：自产农产品可以走归集，
-- 因为平台能自开农产品收购发票，成本有合法凭证。
-- 缺这个标记的话，校验只能写成「自然人一律禁归集」——
-- 那会把我们花了整节论证要支持的农户场景一起拦掉。
--
-- 与商品侧「自产农产品」品类**两者都满足**才走收购发票分支：
-- 一家合作社卖百货不适用，一家公司卖自产农产品同样适用。
ALTER TABLE mch_entity ADD COLUMN is_agri_producer TINYINT NOT NULL DEFAULT 0
    COMMENT '是否农业生产者（农户/家庭农场/合作社）。为 1 时允许走归集路径 ——
             平台可自开农产品收购发票，成本有凭证。默认 0：新增主体不自动获得这个豁免';
