-- 订单行记下**类目**，为按类目发放积分做准备。
--
-- **为什么不能用已有的 category_type**：它只有三档（标品 / 生鲜 / 服务），
-- 而积分规则要按**二级类目**配 —— 生鲜里蔬菜和水果的毛利就不一样，
-- 用三档表达等于把它们按同一个比例发分。
--
-- **为什么是快照而不是发分时现查商品**：与 title / cover / spec / price /
-- pickup_name / receiver_name / traffic_source 同一条惯例 ——
-- 商品可以改类目，改完不该让历史订单的积分口径跟着变。
-- 事后查「这单当初为什么发 30 分」时，要能原样复现。
--
-- 存量行留空：它们的分早就发完了，回填没有意义，反而会让人以为那些单是按类目算的。
ALTER TABLE ord_item ADD COLUMN category_no VARCHAR(64) DEFAULT NULL
    COMMENT '下单时的二级类目快照。积分按类目发放时读它，不现查商品';
