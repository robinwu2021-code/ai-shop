-- P4 additive policy metadata only. No issuer activation, balance update or legacy backfill.
CREATE TABLE sv_issue_policy (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  tenant_no VARCHAR(32) NOT NULL,
  policy_no VARCHAR(64) NOT NULL,
  management_no VARCHAR(64) NOT NULL,
  target_type VARCHAR(24) NOT NULL,
  target_no VARCHAR(64) NOT NULL,
  currency VARCHAR(8) NOT NULL,
  current_version_no VARCHAR(64) NOT NULL,
  status VARCHAR(24) NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  deleted TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  created_by VARCHAR(64) NOT NULL,
  updated_by VARCHAR(64) NOT NULL,
  UNIQUE KEY uk_sv_policy_no (tenant_no,policy_no),
  UNIQUE KEY uk_sv_policy_target (tenant_no,management_no,target_type,target_no,currency),
  CONSTRAINT ck_sv_policy_target CHECK (target_type IN ('SPACE','BRAND_STORES','STORE')),
  CONSTRAINT ck_sv_policy_status CHECK (status IN ('ACTIVE','INACTIVE')),
  CONSTRAINT ck_sv_policy_space CHECK (target_type <> 'SPACE' OR target_no=management_no),
  CONSTRAINT ck_sv_policy_revision CHECK (version>=0 AND deleted IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE sv_issue_policy_version (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  tenant_no VARCHAR(32) NOT NULL,
  policy_version_no VARCHAR(64) NOT NULL,
  policy_no VARCHAR(64) NOT NULL,
  version_index BIGINT NOT NULL,
  configuration_key VARCHAR(64) NOT NULL,
  allow_issue TINYINT NOT NULL,
  require_approval TINYINT NOT NULL,
  max_bonus_bps INT NOT NULL,
  max_paid_minor BIGINT NOT NULL,
  max_bonus_minor BIGINT NOT NULL,
  max_active_days INT NOT NULL,
  max_outstanding_minor BIGINT NOT NULL,
  effect_mode VARCHAR(24) NOT NULL,
  parent_version_refs JSON NOT NULL,
  content_hash CHAR(64) NOT NULL,
  effective_at DATETIME(3) NOT NULL,
  permission_snapshot JSON NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  deleted TINYINT NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  created_by VARCHAR(64) NOT NULL,
  updated_by VARCHAR(64) NOT NULL,
  UNIQUE KEY uk_sv_policy_version (tenant_no,policy_version_no),
  UNIQUE KEY uk_sv_policy_sequence (tenant_no,policy_no,version_index),
  UNIQUE KEY uk_sv_policy_command (tenant_no,policy_no,configuration_key),
  CONSTRAINT ck_sv_policy_boolean CHECK (allow_issue IN (0,1) AND require_approval IN (0,1)),
  CONSTRAINT ck_sv_policy_amounts CHECK (max_paid_minor>0 AND max_bonus_minor>=0 AND max_outstanding_minor>0),
  CONSTRAINT ck_sv_policy_ratio CHECK (max_bonus_bps>=0 AND max_bonus_bps<=10000),
  CONSTRAINT ck_sv_policy_duration CHECK (max_active_days>0),
  CONSTRAINT ck_sv_policy_effect CHECK (effect_mode='NEW_ISSUANCE_ONLY'),
  CONSTRAINT ck_sv_policy_version_revision CHECK (version_index>0 AND version>=0 AND deleted IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
