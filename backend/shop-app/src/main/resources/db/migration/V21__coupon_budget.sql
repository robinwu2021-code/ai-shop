-- 券预算：**发着发着超支**是这一列要挡的唯一一件事。
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 为什么现在补
-- ─────────────────────────────────────────────────────────────────────────────
-- ops-web 的券模板页上写着一句话：
--   「预算是唯一挡住『发着发着超支』的地方：超预算的发放会被直接拒绝」
-- 而后端**根本没有这一列** —— 那句话是假的，闸门不存在。
--
-- 这种「界面承诺了一个不存在的保护」比没有承诺更坏：运营以为有人兜底，
-- 于是不再自己盯着发放量。与 msg_template 的频控写 0 是同一个形状
-- （见 NotifyQuotaVO 的注释：0 等于没有频控，但界面上看着像配了）。
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 为什么默认 0 表示「不限」，而不是 NULL
-- ─────────────────────────────────────────────────────────────────────────────
-- 存量券一张都没配过预算，任何非零默认值都会让它们**当场超预算而停发**——
-- 一次迁移不该改变已在运行的券的行为。
--
-- 用 0 而不是 NULL：SUM/比较里 NULL 会静默传染（`issued > NULL` 是 NULL，
-- 既不真也不假），而这一列的用途正是比较。0 的语义在代码里显式判断一次即可。
--
-- ⚠️ 「不限预算」不是安全默认，只是**兼容默认**。新建券时该不该强制填，
-- 是产品决定；库这一层只保证「没填 = 与今天行为一致」。
ALTER TABLE mkt_coupon
    ADD COLUMN IF NOT EXISTS budget_minor BIGINT(20) NOT NULL DEFAULT 0
        COMMENT '预算上限（分）。0 = 不限。已发放金额达到它之后领取被拒';
