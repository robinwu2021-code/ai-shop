--
-- ⚠️ 这条原本是 V174，与并行会话的 `V174__spec_template_seed.sql` 撞号 ——
-- **撞号自己让路**（共享工作树的规矩）：它未提交、我已提交，但改我的那一份
-- 不会打断别人。改成 V177 之后它排在 V175/V176 之后，
-- **终态完全相同**：V176 里挂 FOOD 的类目会短暂引用一个停用码，
-- 直到这条把码启用 —— 中间态不对外，最终自洽性由 CategoryGateConsistencyTest 守着。
--
-- 两条都属于同一类故障：**挂了门槛，却没有能通过它的路**。
-- 商家看到的都是「你还没有资质授权」，而去哪申请没人说得出 ——
-- 一个只会拒绝的校验比没有校验更糟，因为它看起来在工作。

-- ── ① PACKAGED_FOOD 门槛回位（V168 的遗漏）─────────────────────
--
-- V168 把三级类目整批归档时，只把 FRESH_VEG / FRESH_FRUIT 上移到了二级
-- （CAT110 蔬菜、CAT120 水果），**漏了 PACKAGED_FOOD**：
-- 带它的三个三级类目（粮油调味/休闲零食/茶叶）一起归档，
-- 而它们的父级 CAT130 预包装食品没有承接这个码。
--
-- 后果不是报错，是**门槛消失**：任何商家都能卖预包装食品，
-- 而「仅销售预包装食品备案」这张证从此没有任何一处会去比对它。
-- 少一个门槛比多一个更难发现 —— 没有人会来投诉「怎么让我卖了」。
UPDATE prd_category
SET required_code = 'PACKAGED_FOOD',
    qualification_required = '["仅销售预包装食品备案"]'
WHERE category_no = 'CAT130'
  AND status = 'ACTIVE'
  AND required_code IS NULL;

-- ── ② 在架类目引用的码必须是启用的 ────────────────────────────
--
-- CAT140 熟食卤味 → FOOD、CAT240 医药健康 → DRUG_RETAIL，
-- 而这两个码在 sys_auth_code 里 enabled=0。授权接口只从**启用码**里挑，
-- 于是运营根本授不出这两个码 → 这两个类目下的商品**永远上不了架**。
--
-- 选择「启用码」而不是「摘掉类目上的门槛」：熟食与药品本来就该有证，
-- 摘门槛等于让谁都能卖 —— 那是把一个「谁都卖不了」的错，
-- 换成一个「谁都能卖」的更大的错。
--
-- 若产品决定一期不做这两类，正确动作是**归档类目**（CAT140/CAT240），
-- 而不是留一个选得到却卖不出去的类目。那是产品决定，不在这条迁移里替它做。
UPDATE sys_auth_code
SET enabled = 1
WHERE code IN ('FOOD', 'DRUG_RETAIL')
  AND enabled = 0;
