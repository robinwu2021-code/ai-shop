-- 「这个主体就是平台自己」—— 一个别处回答不了的问题。
--
-- **为什么不复用已有字段**（这一段是本迁移存在的全部理由）：
--
--   funds_mode = AGGREGATED   它的定义原文是「归集：用户付给平台户，平台是销售主体
--                             （**代销**）」—— 同时盖着平台自营与代销第三方的货。
--   business_mode = SELF_OPERATED  门店级，且 V23 的建表默认值就是它，
--                             每一家新店一出生都是自营。
--
-- 把「自营免证件」挂在这两个字段的任何一个上，都会顺手豁免掉代销的第三方商户 ——
-- 而代销恰恰是 ADR-017 §3.4 要求「平台先担责、再向商家追偿」的那一档，
-- 追偿的前提正是那个第三方被核验过。**且这种放宽没有任何地方会报错。**
--
-- 三个问题三根轴，合并任意两根都会在某一档上判错：
--   funds_mode     钱先进谁的账户
--   business_mode  谁是销售主体
--   self_operated  这个主体是不是平台自己   ← 本列
--
-- **写入口只有一个**：POST /ops/merchants/self-operated。
-- 刻意不提供把它改回来的接口 —— 「这家店是不是平台自己」不是运营日常能翻的开关，
-- 真要改，走迁移并留下记录。

ALTER TABLE mch_entity
    ADD COLUMN self_operated TINYINT NOT NULL DEFAULT 0
    COMMENT '1=平台自营主体（平台自己）。免证件、可由运营建店；0=第三方（含代销）';

-- 存量一律 0。**不按 funds_mode 回填** —— 现网的归集主体里既有自营也有代销，
-- 回填等于把上面那段刚讲完的错误直接写进数据。要标哪几个由人逐个确认。
