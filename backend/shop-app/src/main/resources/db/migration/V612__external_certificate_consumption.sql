-- Original Core completed-business consumption, independent of local entitlement assets and money.
CREATE TABLE ord_external_certificate_use (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    authorization_no VARCHAR(32) NOT NULL,
    original_authorization_no VARCHAR(32) NULL,
    purpose VARCHAR(16) NOT NULL DEFAULT 'USE',
    reversal_ref VARCHAR(32) NULL,
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    sub_order_no VARCHAR(32) NOT NULL,
    order_item_id BIGINT NOT NULL,
    preview_ref VARCHAR(32) NOT NULL,
    preview_hash VARCHAR(64) NOT NULL,
    certificate_identity_hash VARCHAR(64) NOT NULL,
    source_hash VARCHAR(64) NOT NULL,
    source_snapshot LONGTEXT NOT NULL,
    quantity DECIMAL(20,6) NOT NULL,
    unit VARCHAR(32) NOT NULL,
    status VARCHAR(24) NOT NULL,
    expires_at DATETIME(3) NOT NULL,
    decision_ref VARCHAR(32) NULL,
    original_receipt_ref VARCHAR(256) NULL,
    UNIQUE KEY uk_external_certificate_authorization(authorization_no),
    UNIQUE KEY uk_external_certificate_preview(tenant_no,entity_no,store_no,preview_ref),
    UNIQUE KEY uk_external_certificate_reverse(tenant_no,original_authorization_no,reversal_ref),
    KEY ix_external_certificate_source(tenant_no,entity_no,store_no,sub_order_no,order_item_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
