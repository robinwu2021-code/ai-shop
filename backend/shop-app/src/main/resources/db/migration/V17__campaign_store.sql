-- 营销活动分门店。
--
-- `mkt_campaign.entity_no NOT NULL`，没有门店维度 —— 四种活动（满减/特价/买赠/店铺券）
-- 一律全主体生效。「新店开业第一周满减」这种最常见的诉求做不了。
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 为什么现在才做
-- ─────────────────────────────────────────────────────────────────────────────
-- 在 V16 之前，下单落哪家店恒为默认门店 —— 「只对分店生效的活动」建了也必然不命中。
-- 那样这一列就是又一个**有录入没有消费方**的字段：不报错，只是永远不生效，
-- 而商家在界面上看到活动「进行中」。这一轮反复修的正是这个形状。
--
-- V16 把自提点归属到门店、下单按自提点选店之后，门店级活动才有了真实的生效路径。
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 可空是刻意的
-- ─────────────────────────────────────────────────────────────────────────────
--   NULL = 全主体生效（今天所有存量活动都是它，行为逐字不变）
--   有值 = 只对这家店生效
--
-- 「全店满减」与「新店开业满减」都要能表达，所以不能用「必须选一家店」来简化。
-- 也不做「空数组 = 全部」那种约定：JSON 列上判空与判空数组是两件事，
-- 而这里每多一种「看起来像空」的取值，就多一条会写错的分支。
ALTER TABLE mkt_campaign ADD COLUMN store_no VARCHAR(64) DEFAULT NULL
    COMMENT '只对这家门店生效；**NULL = 全主体生效**（存量活动都是它）';

-- 下单算价按 (状态, 时间窗) 捞活动后再按门店筛，门店维度加进这个索引没有意义；
-- 单独一个索引给「这家店有哪些活动」这类 B 端列表用
CREATE INDEX idx_campaign_store ON mkt_campaign (store_no);
