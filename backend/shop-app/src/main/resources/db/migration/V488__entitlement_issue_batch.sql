-- Freeze source-owned recipients and resume each item using its stable grant identity.
CREATE TABLE ent_issue_batch (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    batch_no VARCHAR(64) NOT NULL COMMENT '批次号',
    entity_no VARCHAR(64) NOT NULL COMMENT '商家',
    template_version_no VARCHAR(64) NOT NULL COMMENT '权益版本',
    activity_ref VARCHAR(64) NULL COMMENT 'core活动引用',
    audience_fact_ref VARCHAR(64) NOT NULL COMMENT 'core可信受众快照号',
    planned_count INT NOT NULL COMMENT '计划数量',
    issued_count INT NOT NULL DEFAULT 0 COMMENT '已发',
    skipped_count INT NOT NULL DEFAULT 0 COMMENT '资格跳过',
    failed_count INT NOT NULL DEFAULT 0 COMMENT '明确失败',
    pending_count INT NOT NULL COMMENT '待处理',
    skip_reasons JSON NOT NULL COMMENT '原因分项',
    audience_snapshot JSON NOT NULL COMMENT '可信受众和版本/规则/受益摘要',
    recipient_results JSON NOT NULL COMMENT '逐项结果与原grant号',
    cursor_offset INT NOT NULL DEFAULT 0 COMMENT '已处理稳定受众下标',
    status VARCHAR(24) NOT NULL COMMENT 'PREPARING/PROCESSING/COMPLETED/PARTIAL/FAILED',
    operator_no VARCHAR(64) NOT NULL COMMENT '经办人',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity，账务事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新',
    created_by VARCHAR(64) NOT NULL COMMENT '操作者或系统任务',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_batch (tenant_no,batch_no),
    KEY ix_batches (tenant_no,entity_no,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='发放批次汇总，逐项结果在grant';
