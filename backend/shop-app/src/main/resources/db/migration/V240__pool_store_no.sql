-- 社区池加门店维度（可见性按门店算 · 第 2 步）。
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 这一版**不改行为**
-- ─────────────────────────────────────────────────────────────────────────────
-- 新列可空、唯一键不动。写入口开始记「这一行是哪家店摆的」，
-- C 端仍按 goods_no 去重后展示，与今天逐字相同。
-- 真正切口径（可达按门店算）是第 3 步，那一步才会让一件货在池里出现多行。
--
-- ─────────────────────────────────────────────────────────────────────────────
-- 为什么 store_no 可空
-- ─────────────────────────────────────────────────────────────────────────────
-- 存量行是主体级口径写下的，回填成「该主体的默认店」是我们能给的最诚实的答案：
-- 今天单店商家占绝大多数，默认店就是唯一那家；多门店主体（线上 1 个）的存量行
-- 本来也无法区分是哪家店摆的 —— 它当初就没这个维度。
--
-- 回填不到的（主体没有默认店，理论上不该有）留 NULL，读侧按「未知门店」处理，
-- 不要兜底成任意一家 —— 兜错店的表现是「单发到了没有这件货的店」。
--
-- ─────────────────────────────────────────────────────────────────────────────
-- sort_weight 这一步**不动**
-- ─────────────────────────────────────────────────────────────────────────────
-- 方案里写的是「第 2 步用 sort_weight 装门店到社区的距离」，实施时改到第 3 步：
-- 距离是用来给**平局**排序的（一件货被两家店摆着、两家店都服务同一社区），
-- 而在唯一键还是 (community_no, goods_no) 的这一步，一件货在池里只可能有一行 ——
-- 平局根本不可能出现。现在就写距离，等于给一个没有任何读者的数字写断言。
--
-- 第 3 步换成逐门店建池时它才有意义，那时也才测得到。
ALTER TABLE prd_community_pool
    ADD COLUMN store_no VARCHAR(64) DEFAULT NULL COMMENT '这一行是哪家门店摆的（mch_store.store_no）。空=存量行，口径切换前写下的';

-- 存量回填：各主体的默认店
UPDATE prd_community_pool p
    JOIN mch_store s ON s.entity_no = p.entity_no AND s.is_default = 1 AND s.deleted = 0
SET p.store_no = s.store_no, p.updated_at = NOW()
WHERE p.store_no IS NULL AND p.deleted = 0;

-- 按门店查池（第 3 步的写入口要按 (goods, store) 差集增删）
CREATE INDEX idx_pool_store ON prd_community_pool (store_no);
