  `dim_no` varchar(32) DEFAULT NULL COMMENT '使用的规格维度',
  `usage_type` varchar(16) DEFAULT NULL COMMENT '覆盖维度上的默认用途：SALE / PROP / OPTION；空表示跟维度走',
