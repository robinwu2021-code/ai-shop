  `category_no` varchar(32) DEFAULT NULL COMMENT '适用类目；空表示不限类目（商家全局）',
  `entity_no` varchar(32) DEFAULT NULL COMMENT '适用商家主体；空表示平台在类目下的设定',
  `dim_no` varchar(32) DEFAULT NULL COMMENT '所属规格维度',
  `value_no` varchar(32) DEFAULT NULL COMMENT '规格值编号',
  `enabled` tinyint DEFAULT NULL COMMENT '是否启用：1 用 / 0 本范围不用（停用维度会连带其取值不出现）',
  `label_override` varchar(64) DEFAULT NULL COMMENT '在此范围内的叫法，如 500g 在蔬菜下叫约1斤；空表示用原名',
  `favorite` tinyint DEFAULT NULL COMMENT '是否商家常用取值：1 常用，下次建品排前',
  `sort` int DEFAULT NULL COMMENT '范围内顺序，小的在前；空表示跟平台顺序',
  `deleted` tinyint NOT NULL DEFAULT '0' COMMENT '逻辑删除：0 = 正常，1 = 已删除',
  `version` int NOT NULL DEFAULT '0' COMMENT '乐观锁版本号，每次修改加 1',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  KEY `idx_cat_spec_value` (`category_no`,`dim_no`),
  KEY `uk_cat_spec_value` (`tenant_no`,`category_no`,`dim_no`,`value_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='规格值使用范围：某类目或商家启用哪些值、改叫什么名字';

CREATE TABLE `prd_spec_dim` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `tenant_no` varchar(32) DEFAULT NULL COMMENT '租户号',
  `dim_no` varchar(32) DEFAULT NULL COMMENT '规格维度编号',
  `code` varchar(32) DEFAULT NULL COMMENT '维度语义码，如 COLOR、WEIGHT；值编号与取值编码都以它为前缀',
  `name` varchar(64) DEFAULT NULL COMMENT '维度名，如颜色、份量、辣度、发长',
  `name_i18n` text COMMENT '维度名多语言（JSON），缺的语言回落中文名',
  `value_type` varchar(16) DEFAULT NULL COMMENT '取值类型：ENUM 枚举 / QUANT 数值加单位（取值须有归一量）',
  `unit` varchar(16) DEFAULT NULL COMMENT '数值类维度的单位，如 g、ml、cm、分钟',
  `usage_type` varchar(16) DEFAULT NULL COMMENT '用途：SALE 生成 SKU / PROP 仅作描述 / OPTION 下单选配（如口味、加料）',
  `min_qty` decimal(18,6) DEFAULT NULL COMMENT '选配时本维度最少总选择量',
  `max_qty` decimal(18,6) DEFAULT NULL COMMENT '选配时本维度最多总选择量',
  `selection_rules` json DEFAULT NULL COMMENT '选配取值之间的互斥、依赖约束（按取值编号引用）',
  `universal` tinyint DEFAULT NULL COMMENT '是否通用维度：1 值的含义跨类目一致 / 0 否',
  `scope` varchar(16) DEFAULT NULL COMMENT '归属：PLATFORM 平台预设 / MERCHANT 商家自建（只对自己下发，不参与跨店聚合）',
  `entity_no` varchar(32) DEFAULT NULL COMMENT '商家自建时的归属主体',
  `sort` int DEFAULT NULL COMMENT '展示顺序',
  `status` varchar(10) DEFAULT NULL COMMENT '状态：DRAFT 草稿 / ACTIVE 启用 / ARCHIVED 归档（历史商品仍靠它解释）',
  `deleted` tinyint NOT NULL DEFAULT '0' COMMENT '逻辑删除：0 = 正常，1 = 已删除',
  `version` int NOT NULL DEFAULT '0' COMMENT '乐观锁版本号，每次修改加 1',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  KEY `idx_spec_dim_scope` (`scope`,`entity_no`),
  KEY `uk_spec_dim_code` (`tenant_no`,`code`,`scope`,`entity_no`),
  KEY `uk_spec_dim_no` (`dim_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='规格维度：如“份量”“辣度”“发长”；带用途（生成 SKU / 下单选配）和可选数量上下限。平台预设的常用维度也在这里';

CREATE TABLE `prd_spec_value` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `tenant_no` varchar(32) DEFAULT NULL COMMENT '租户号',
  `value_no` varchar(64) DEFAULT NULL COMMENT '规格值编号，SKU 快照记的就是它',
  `dim_no` varchar(32) DEFAULT NULL COMMENT '所属规格维度',
  `code` varchar(32) DEFAULT NULL COMMENT '维度内唯一的取值码，对外称取值编码',
  `label` varchar(64) DEFAULT NULL COMMENT '展示文案，如微辣、中辣；改了不影响已建商品',
  `label_i18n` text COMMENT '展示文案多语言（JSON）',
  `numeric_value` decimal(14,4) DEFAULT NULL COMMENT '归一量，如 500g、半斤、0.5kg 都记 500，用于排序与比价',
  `numeric_unit` varchar(16) DEFAULT NULL COMMENT '归一量单位，与维度单位同口径',
  `aliases` text COMMENT '别名（JSON 数组），供识别、搜索与自动归一',
  `sku_no` varchar(32) DEFAULT NULL COMMENT '选配加料项对应的可售 SKU，按它计价与扣量；纯口味为空',
  `default_qty` decimal(18,6) DEFAULT NULL COMMENT '选配时默认选择量',
  `min_qty` decimal(18,6) DEFAULT NULL COMMENT '选配时本取值最少选择量',
  `max_qty` decimal(18,6) DEFAULT NULL COMMENT '选配时本取值最多选择量',
  `scope` varchar(16) DEFAULT NULL COMMENT '归属：PLATFORM 平台值 / MERCHANT 商家在维度下自加的值',
  `entity_no` varchar(32) DEFAULT NULL COMMENT '商家自加取值时的归属主体',
  `sort` int DEFAULT NULL COMMENT '维度内顺序',
  `status` varchar(10) DEFAULT NULL COMMENT '状态：ACTIVE 启用 / ARCHIVED 归档 / MERGED 已合并到别的值',
  `merged_into` varchar(64) DEFAULT NULL COMMENT '被合并到哪个值；非空表示已退役',
  `deleted` tinyint NOT NULL DEFAULT '0' COMMENT '逻辑删除：0 = 正常，1 = 已删除',
  `version` int NOT NULL DEFAULT '0' COMMENT '乐观锁版本号，每次修改加 1',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  KEY `idx_spec_value_dim` (`dim_no`,`status`),
  KEY `uk_spec_value_code` (`tenant_no`,`dim_no`,`code`,`scope`,`entity_no`),
  KEY `uk_spec_value_no` (`value_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='规格值：维度下的取值，如“微辣、中辣”；选配的加料项可指向一个 SKU';
