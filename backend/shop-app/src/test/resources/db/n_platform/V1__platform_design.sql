CREATE TABLE `ops_session` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `token_hash` char(64) NOT NULL COMMENT '登录令牌的 SHA-256 摘要，不存原文',
  `user_no` varchar(32) NOT NULL COMMENT '会话所属的运营账号号',
  `subject_kind` varchar(8) NOT NULL COMMENT '会话主体类型，本表恒为 OPS',
  `issued_at` datetime NOT NULL COMMENT '签发时间',
  `expires_at` datetime NOT NULL COMMENT '过期时间',
  `last_seen_at` datetime DEFAULT NULL COMMENT '最后活跃时间',
  `revoked_at` datetime DEFAULT NULL COMMENT '撤销时间',
  `revoke_reason` varchar(32) DEFAULT NULL COMMENT '撤销原因：LOGOUT 主动退出 / KICKED 被踢 / DISABLED 账号停用 / PWD_CHANGED 改密 / EXPIRED 过期',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  KEY `idx_ops_session_expires` (`expires_at`),
  KEY `idx_ops_session_revoked` (`revoked_at`),
  KEY `idx_ops_session_user` (`user_no`, `revoked_at`),
  UNIQUE KEY `uk_ops_session_token` (`token_hash`)
) COMMENT='运营端会话：登录令牌的哈希、属于哪个运营账号、签发与过期、撤销原因。角色与权限每次现读，不存在会话里';

