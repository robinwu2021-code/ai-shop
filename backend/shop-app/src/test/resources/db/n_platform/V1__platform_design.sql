CREATE TABLE `mch_group` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `tenant_no` varchar(32) NOT NULL COMMENT '服务端可信租户号',
  `management_no` varchar(32) NOT NULL COMMENT '商户集团号（沿用原管理空间号），品牌、主体、授权都以它为根',
  `name` varchar(64) NOT NULL COMMENT '集团名称，给老板与运营看的总部名',
  `owner_actor_no` varchar(32) NOT NULL COMMENT '集团的有效所有人（老板）的认证主体号，变更需走审计',
  `status` varchar(10) NOT NULL COMMENT '集团状态：ACTIVE 正常 / SUSPENDED 暂停（暂停后其下授权全部失效）',
  `bootstrap_source_account_no` varchar(32) NOT NULL COMMENT '创建集团时核验过的所有人账号关系号，只证明创建资格，不因此授予其余主体权限',
  `auth_revision` bigint NOT NULL COMMENT '集团授权版本号，每次授予或撤销授权递增，用于判断权限缓存是否过期',
  `deleted` tinyint NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 = 正常，1 = 已删除',
  `version` int NOT NULL DEFAULT 0 COMMENT '乐观锁版本号，每次修改加 1',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_1` (`tenant_no`, `management_no`)
) COMMENT='商户集团：一个老板或总部名下的多个主体、品牌、门店；授权以它为根。它在主体之上，一个集团可以有多个主体，不等于经营主体';

