CREATE TABLE ivc_invoice_delivery (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  tenant_no VARCHAR(32) NOT NULL,
  entity_no VARCHAR(64) NOT NULL,
  store_no VARCHAR(64) NOT NULL,
  delivery_no VARCHAR(64) NOT NULL,
  invoice_no VARCHAR(64) NOT NULL,
  application_no VARCHAR(64) NULL,
  application_revision_no INT NULL,
  export_no VARCHAR(64) NOT NULL,
  parent_delivery_no VARCHAR(64) NULL,
  recipient_secret_ref BIGINT NULL,
  recipient_mask VARCHAR(191) NOT NULL,
  status VARCHAR(24) NOT NULL,
  reason VARCHAR(256) NULL,
  actor_no VARCHAR(64) NOT NULL,
  idempotency_hash CHAR(64) NOT NULL,
  request_hash CHAR(64) NOT NULL,
  template_version VARCHAR(32) NOT NULL,
  content_hash CHAR(64) NULL,
  provider_message_id VARCHAR(256) NULL,
  failure_code VARCHAR(64) NULL,
  token_hash CHAR(64) NULL,
  expires_at DATETIME(3) NOT NULL,
  created_at DATETIME(3) NOT NULL,
  started_at DATETIME(3) NULL,
  finished_at DATETIME(3) NULL,
  opened_at DATETIME(3) NULL,
  UNIQUE KEY uk_ivc_delivery_no (tenant_no, delivery_no),
  UNIQUE KEY uk_ivc_delivery_idem (tenant_no, entity_no, store_no, invoice_no, idempotency_hash),
  UNIQUE KEY uk_ivc_delivery_token (token_hash),
  KEY ix_ivc_delivery_invoice (tenant_no, entity_no, store_no, invoice_no, id),
  KEY ix_ivc_delivery_worker (status, created_at, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
