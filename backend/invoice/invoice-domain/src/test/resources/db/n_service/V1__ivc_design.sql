CREATE TABLE `ivc_regime_profile` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `tenant_no` varchar(32) DEFAULT NULL COMMENT '租户号',
  `entity_no` varchar(32) DEFAULT NULL COMMENT '经营主体号',
  `regime_code` varchar(16) DEFAULT NULL COMMENT '税制代码，如 TW_EGUI 台湾电子发票',
  `seller_tax_id` varchar(32) DEFAULT NULL COMMENT '卖方税号（台湾统一编号 8 位）',
  `seller_name` varchar(128) DEFAULT NULL COMMENT '卖方名称',
  `gateway_code` varchar(32) DEFAULT NULL COMMENT '商家自选的开票服务商；空表示跟随市场默认服务商',
  `environment` varchar(32) DEFAULT NULL COMMENT '当前通道环境：PROD 正式 / SANDBOX 测试',
  `active_account_no` varchar(32) DEFAULT NULL COMMENT '当前使用的开票通道账户号',
  `route_version` bigint DEFAULT NULL COMMENT '通道切换版本号，每切换一次加一，发票上记下开立时的版本',
  `provider_account_code` varchar(64) DEFAULT NULL COMMENT '服务商侧的商家代号（如鲸跃 officeid）',
  `provider_secret_ref` bigint DEFAULT NULL COMMENT '服务商账号与密码在密钥库中的引用，不存明文',
  `qr_key_ref` bigint DEFAULT NULL COMMENT '台湾发票 QR 加密密钥在密钥库中的引用，不存明文',
  `member_carrier_type` varchar(16) DEFAULT NULL COMMENT '向财政部申请的会员载具类别号',
  `auto_issue` tinyint DEFAULT NULL COMMENT '是否付款成功后按预存买方资料自动开票：1 是 / 0 否',
  `status` varchar(10) DEFAULT NULL COMMENT '状态：ACTIVE 启用 / SUSPENDED 暂停',
  `provider_hold_reason` varchar(256) DEFAULT NULL COMMENT '上传被服务商暂停的原因（服务商原文）；空表示未暂停',
  `provider_held_at` datetime(3) DEFAULT NULL COMMENT '被暂停的时刻（UTC）',
  `range_low_water` int DEFAULT NULL COMMENT '本期剩余号码低于此值即提醒或自动领号',
  `auto_fetch_ranges` tinyint DEFAULT NULL COMMENT '余量不足或期末前是否自动向加值中心领号：1 是 / 0 否（仅服务商配号的通道）',
  `range_alert_key` varchar(32) DEFAULT NULL COMMENT '本期余量已提醒到的级别，如 11512:LOW 偏低 / 11512:EMPTY 用尽',
  `next_range_alert_key` varchar(16) DEFAULT NULL COMMENT '已提醒过“下期号段未备”的期别，如 11602',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  KEY `uk_ivc_regime_profile` (`tenant_no`, `entity_no`, `regime_code`)
) COMMENT='主体开通的税制：卖方税号与名称、是否付款后自动开票、会员载具类别，以及当前用哪个通道账户';

