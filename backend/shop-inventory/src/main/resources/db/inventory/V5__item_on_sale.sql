-- 物料带上「商品还在不在架上」。
--
-- **起因是一个查得到的事实**：2026-08-30 线上量到 13 组同名同规格的货，
-- 挑货弹层里三行「金龙鱼调和油 5L · 5L　80」完全一样 —— 同库位、库存都是 80，
-- 商家挑哪一行都不知道自己挑的是什么。
--
-- 追到主库：那三条对应三个**真实存在**的商品（`G0002` 在架，另两个 8-20 建的已下架），
-- 标题恰好一样。所以进销存建三条物料是对的，错的是**它们在界面上无从分辨**。
--
-- 排除过两条更省事的路：
--   · 靠货号区分 —— 线上 396 个 SKU 的 `merchant_sku_code` 全是空的
--     （入口在商品编辑页，那一段默认折叠）；
--   · 把下架的滤掉 —— 下架商品仍可能有库存，商家还要盘点、报损、调拨。
--
-- **可空，且空不等于在架**：存量 209 件都会是 NULL，它们要等下一次商品变更
-- 同步过来才有值。读的一侧必须把 NULL 当「不知道」而不是「在架」——
-- 当成在架就是拿默认值冒充事实。
ALTER TABLE inv_item
    ADD COLUMN source_on_sale TINYINT DEFAULT NULL COMMENT '来源商品是否在架：1 在架 / 0 已下架 / NULL 还没同步过' AFTER data_source;
