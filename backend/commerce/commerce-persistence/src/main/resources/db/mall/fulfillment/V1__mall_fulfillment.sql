  UNIQUE KEY uk_0 (`tenant_no`,`task_no`),
  UNIQUE KEY uk_1 (`tenant_no`,`order_component_no`,`unit_seq`,`task_type`),
  PRIMARY KEY (`id`),
  CHECK (deleted = 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

