CREATE TABLE mall_shipment_item (
  tenant_no VARCHAR(32) NOT NULL,
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  shipment_no VARCHAR(64) NOT NULL,
  line_no INT NOT NULL,
  order_no VARCHAR(64) NOT NULL,
  order_item_no VARCHAR(64) NOT NULL,
  sku_no VARCHAR(64) NOT NULL,
  sku_name_snapshot VARCHAR(128) NOT NULL,
  device_sn VARCHAR(64),
  qty INT NOT NULL,
  status VARCHAR(16) NOT NULL,
  activated_at DATETIME(3),
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  created_by VARCHAR(64),
  updated_by VARCHAR(64),
  version BIGINT NOT NULL,
  deleted TINYINT NOT NULL,
  UNIQUE KEY uk_shipment_line (tenant_no,shipment_no,line_no),
  UNIQUE KEY uk_device_sn (device_sn),
  CHECK (qty>0 AND (device_sn IS NULL OR qty=1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
