-- 进销存独立服务 · 成套行（TDD-进销存独立服务与多业态 §2.6，M7 T7.1）
--
-- 数量附件随上级件走：充电桩的枪线、配件包没有 SN，出库时挂在某一根桩下，
-- 交接出库生成出库池时成为桩那条记录的从属记录，随桩调整 / 撤回 / 签收。
-- 指向的是**上级件的 SN** 而不是行号：同一行逐件物料里可能有多根桩，行号分不出挂在哪一根下。

ALTER TABLE inv_outbound_line ADD COLUMN parent_serial_no VARCHAR(64) DEFAULT NULL COMMENT '成套行：这行数量附件随哪一件上级件（如枪线随桩），须是同一张单上扫到的顶层件';
