-- 物料记下「来源 SKU 退休时，它的位子由谁接了」。
--
-- **起因**：改一次规格，平台侧会逻辑删旧 sku_no、新铸一个（这是对的，
-- 身份不能改派 —— 历史订单里买的就是「无规格」那一条），而进销存这侧
-- 此前没有任何一处知道退休发生了：它长出第二件同名物料，旧那件带着库存搁浅。
-- 2026-09-18 线上香梨：两行同名同规格同库位、库存都是 1，店主挑哪一行都不知道
-- 自己挑的是什么。
--
-- **这一列是线索，不是依据。** 它只在退休时「还活着的 sku 恰好一条」时才有值，
-- 用来告诉店主「这件大概是被那件顶了」。**不据此搬库存** —— 「恰好一条」
-- 并不等于「同一件货」：店主可能是把 10 斤装换成了 20 斤装，而旧物料上那几件
-- 物理上就是 10 斤装。系统分不出这两种，店主一眼就能分，所以这个决定归他。
--
-- 有库存的退休物料**不归档**（归档了商家就再也盘不着那几件，账永远平不了），
-- 靠 status 分不出它们，所以要这一列在。
-- **两列，不是一列。** 只加 succeeded_by 的话，判不出接位者的那一档
-- （多规格矩阵，哪条顶替哪条说不清）会一个标记都没有 —— 而那恰恰是最需要
-- 人去看的一档：有库存、没人认领、界面上与旁边同名的那行完全一样。
-- 「退休了没有」与「谁接的位」是两个问题，各占一列。
ALTER TABLE inv_item
    ADD COLUMN retired_at DATETIME DEFAULT NULL COMMENT '来源 SKU 退休于何时；NULL = 没退休' AFTER source_on_sale,
    ADD COLUMN succeeded_by VARCHAR(40) DEFAULT NULL COMMENT '退休时接位的 sku_no；NULL = 没退休、或退休时判不出接位者' AFTER retired_at;
