-- Beauty appointment resource intent and permanent source fence. Storage only.
-- Frozen V1 remains unchanged; permission and resource authority live in services.

CREATE TABLE `bty_appointment_resource_intent` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '物理自增主键，不对外',
    `tenant_no` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL DEFAULT 'MAIN' COMMENT '沿当前租户上下文；不另启租户体系',
    `entity_no` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT '商家主体范围；不等于租户',
    `created_at` DATETIME(3) NOT NULL COMMENT '创建时刻',
    `created_by` VARCHAR(64) COLLATE utf8mb4_bin NULL COMMENT '实际操作者业务引用',
    `updated_at` DATETIME(3) NOT NULL COMMENT '更新时间',
    `updated_by` VARCHAR(64) COLLATE utf8mb4_bin NULL COMMENT '更新操作者',
    `version` BIGINT NOT NULL DEFAULT 0 COMMENT '乐观锁',
    `deleted` INT NOT NULL DEFAULT 0 COMMENT '沿BaseEntity；事实表禁止删除或软删覆盖',
    `intent_no` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT '意图号',
    `appointment_no` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT '预约根',
    `store_no` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT '门店',
    `command_no` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT '共用命令号',
    `source_revision` BIGINT NOT NULL COMMENT '来源预约版本',
    `action` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT '资源动作',
    `command_hash` CHAR(64) COLLATE utf8mb4_bin NOT NULL COMMENT '完整命令摘要',
    `plan_hash` CHAR(64) COLLATE utf8mb4_bin NOT NULL COMMENT '原始计划字节摘要',
    `frozen_plan` LONGTEXT COLLATE utf8mb4_bin NOT NULL COMMENT '保留原始UTF8字节；不能用JSON列归一化',
    `phase_code` INT NOT NULL COMMENT '0准备1许可2拒绝3已对账',
    `initiated_by` VARCHAR(64) COLLATE utf8mb4_bin NOT NULL COMMENT '发起主体',
    `decision_no` VARCHAR(32) COLLATE utf8mb4_bin NULL COMMENT '来源决定',
    `issued_at` DATETIME(3) NULL COMMENT '许可起始',
    `valid_until` DATETIME(3) NULL COMMENT '许可截止；不是栅栏释放条件',
    `terminal_code` INT NULL COMMENT '1成功2拒绝',
    `terminal_hash` CHAR(64) COLLATE utf8mb4_bin NULL COMMENT '权威终态摘要',
    `reason_code` VARCHAR(64) COLLATE utf8mb4_bin NULL COMMENT '拒绝安全原因；拒绝不携带许可窗口，终态保留原决定',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_bty_appointment_resource_intent_1` (`tenant_no`, `entity_no`, `intent_no`),
    UNIQUE KEY `uk_bty_appointment_resource_intent_2` (`tenant_no`, `entity_no`, `command_no`),
    CONSTRAINT `ck_bty_appointment_resource_intent_1` CHECK (`version` >= 0),
    CONSTRAINT `ck_bty_appointment_resource_intent_2` CHECK (`deleted` IN (0, 1)),
    CONSTRAINT `ck_bty_appointment_resource_intent_3` CHECK (`source_revision` >= 0),
    CONSTRAINT `ck_bty_appointment_resource_intent_4` CHECK (`phase_code` IN (0, 1, 2, 3)),
    CONSTRAINT `ck_bty_appointment_resource_intent_5` CHECK (JSON_VALID(`frozen_plan`) AND OCTET_LENGTH(`frozen_plan`) <= 65536),
    CONSTRAINT `ck_bty_appointment_resource_intent_6` CHECK ((`phase_code` = 0 AND `decision_no` IS NULL AND `reason_code` IS NULL AND `issued_at` IS NULL AND `valid_until` IS NULL) OR (`phase_code` IN (1, 3) AND `decision_no` IS NOT NULL AND `reason_code` IS NULL AND `issued_at` IS NOT NULL AND `valid_until` IS NOT NULL AND `valid_until` > `issued_at`) OR (`phase_code` IN (2, 3) AND `decision_no` IS NOT NULL AND `reason_code` IS NOT NULL AND `issued_at` IS NULL AND `valid_until` IS NULL)),
    CONSTRAINT `ck_bty_appointment_resource_intent_7` CHECK ((`phase_code` IN (0, 1, 2) AND `terminal_code` IS NULL AND `terminal_hash` IS NULL) OR (`phase_code` = 3 AND `terminal_code` IS NOT NULL AND `terminal_code` IN (1, 2) AND `terminal_hash` IS NOT NULL)),
    CONSTRAINT `ck_bty_appointment_resource_intent_8` CHECK (`terminal_code` IS NULL OR `terminal_code` = 2 OR `reason_code` IS NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE `bty_appointment_resource_fence` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '物理自增主键，不对外',
    `tenant_no` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL DEFAULT 'MAIN' COMMENT '沿当前租户上下文；不另启租户体系',
    `entity_no` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT '商家主体范围；不等于租户',
    `created_at` DATETIME(3) NOT NULL COMMENT '创建时刻',
    `created_by` VARCHAR(64) COLLATE utf8mb4_bin NULL COMMENT '实际操作者业务引用',
    `updated_at` DATETIME(3) NOT NULL COMMENT '更新时间',
    `updated_by` VARCHAR(64) COLLATE utf8mb4_bin NULL COMMENT '更新操作者',
    `version` BIGINT NOT NULL DEFAULT 0 COMMENT '乐观锁',
    `deleted` INT NOT NULL DEFAULT 0 COMMENT '沿BaseEntity；事实表禁止删除或软删覆盖',
    `fence_no` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT '栅栏号',
    `appointment_no` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT '永久唯一预约根',
    `store_no` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT '门店',
    `active_intent_no` VARCHAR(32) COLLATE utf8mb4_bin NULL COMMENT '活动意图；显式置空释放，禁止删行释放',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_bty_appointment_resource_fence_1` (`tenant_no`, `entity_no`, `fence_no`),
    UNIQUE KEY `uk_bty_appointment_resource_fence_2` (`tenant_no`, `entity_no`, `appointment_no`),
    UNIQUE KEY `uk_bty_appointment_resource_fence_3` (`tenant_no`, `entity_no`, `active_intent_no`),
    CONSTRAINT `ck_bty_appointment_resource_fence_1` CHECK (`version` >= 0),
    CONSTRAINT `ck_bty_appointment_resource_fence_2` CHECK (`deleted` IN (0, 1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
