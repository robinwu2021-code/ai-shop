-- Beauty reception scope and immutable guest receipts. V1-V4 remain frozen.

CREATE TABLE `bty_reception_operation` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '物理自增主键，不对外',
    `tenant_no` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL DEFAULT 'MAIN' COMMENT '沿当前租户上下文；不另启租户体系',
    `entity_no` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT '商家主体范围；不等于租户',
    `created_at` DATETIME(3) NOT NULL COMMENT '创建时刻',
    `created_by` VARCHAR(64) COLLATE utf8mb4_bin NULL COMMENT '实际操作者业务引用',
    `updated_at` DATETIME(3) NOT NULL COMMENT '更新时间',
    `updated_by` VARCHAR(64) COLLATE utf8mb4_bin NULL COMMENT '更新操作者',
    `version` BIGINT NOT NULL DEFAULT 0 COMMENT '乐观锁',
    `deleted` INT NOT NULL DEFAULT 0 COMMENT '沿BaseEntity；事实表禁止删除或软删覆盖',
    `store_no` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT 'store_no',
    `operation_no` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT 'operation_no',
    `actor_no` VARCHAR(64) COLLATE utf8mb4_bin NOT NULL COMMENT 'actor_no',
    `actor_realm` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT 'actor_realm',
    `actor_kind` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT 'actor_kind',
    `endpoint` VARCHAR(64) COLLATE utf8mb4_bin NOT NULL COMMENT 'endpoint',
    `action` VARCHAR(32) COLLATE utf8mb4_bin NOT NULL COMMENT 'action',
    `key_hash` CHAR(64) COLLATE utf8mb4_bin NOT NULL COMMENT 'key_hash',
    `request_hash` CHAR(64) COLLATE utf8mb4_bin NOT NULL COMMENT 'request_hash',
    `appointment_no` VARCHAR(32) COLLATE utf8mb4_bin NULL COMMENT 'appointment_no',
    `work_order_no` VARCHAR(32) COLLATE utf8mb4_bin NULL COMMENT 'work_order_no',
    `identity_kind` VARCHAR(16) COLLATE utf8mb4_bin NULL COMMENT 'identity_kind',
    `identity_ref` VARCHAR(32) COLLATE utf8mb4_bin NULL COMMENT 'identity_ref',
    `phase` VARCHAR(24) COLLATE utf8mb4_bin NOT NULL COMMENT 'phase',
    `appointment_operation_no` VARCHAR(32) COLLATE utf8mb4_bin NULL COMMENT 'appointment_operation_no',
    `derived_key_hash` CHAR(64) COLLATE utf8mb4_bin NULL COMMENT 'derived_key_hash',
    `frozen_payload` JSON NOT NULL COMMENT 'frozen_payload',
    `result` JSON NULL COMMENT 'result',
    `next_retry_at` DATETIME(3) NULL COMMENT 'next_retry_at',
    `lease_until` DATETIME(3) NULL COMMENT 'lease_until',
    `failure_code` VARCHAR(64) COLLATE utf8mb4_bin NULL COMMENT 'failure_code',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_bty_reception_operation_1` (`tenant_no`, `entity_no`, `operation_no`),
    UNIQUE KEY `uk_bty_reception_operation_2` (`tenant_no`, `entity_no`, `store_no`, `actor_realm`, `actor_kind`, `actor_no`, `endpoint`, `key_hash`),
    KEY `idx_bty_reception_operation_1` (`tenant_no`, `phase`, `next_retry_at`, `lease_until`, `id`),
    KEY `idx_bty_reception_operation_2` (`tenant_no`, `entity_no`, `store_no`, `appointment_no`),
    KEY `idx_bty_reception_operation_3` (`tenant_no`, `entity_no`, `store_no`, `work_order_no`),
    CONSTRAINT `ck_bty_reception_operation_1` CHECK (`version` >= 0),
    CONSTRAINT `ck_bty_reception_operation_2` CHECK (`deleted` = 0),
    CONSTRAINT `ck_bty_reception_operation_3` CHECK (`phase` IN ('RECEIVED','RESOURCE_PENDING','ARRIVAL_PENDING','OPEN_PENDING','SUCCEEDED','REJECTED')),
    CONSTRAINT `ck_bty_reception_operation_4` CHECK ((`identity_kind` IS NULL AND `identity_ref` IS NULL) OR (`identity_kind` IN ('USER','GUEST') AND `identity_ref` IS NOT NULL AND CHAR_LENGTH(`identity_ref`) > 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

