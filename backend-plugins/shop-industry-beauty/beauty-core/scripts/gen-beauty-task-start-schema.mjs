#!/usr/bin/env node
// Beauty-owned pure rendering. No SQL execution and no writes outside this beauty-core module.
import {readFileSync,writeFileSync,readdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
const root=fileURLToPath(new URL('../',import.meta.url));
const source=JSON.parse(readFileSync(resolve(root,'src/main/schema/beauty-task-start-schema.json'),'utf8'));
if(source.platformVersion!==15 || source.owner!=='beauty-core/primary') throw Error('Unexpected START schema');
const folder=resolve(root,'src/main/resources/db/industry/beauty');
const script='V15__beauty_task_start.sql';
const history=readdirSync(folder).filter(n=>/^V\d+__.*\.sql$/.test(n)&&+n.match(/^V(\d+)/)[1]<15).sort((a,b)=>+a.match(/^V(\d+)/)[1]-+b.match(/^V(\d+)/)[1]);
if(history.length!==14 || history.some((n,i)=>!n.startsWith(`V${i+1}__`))) throw Error('Reassign private migration number');
const sql='-- Generated by beauty-core/scripts/gen-beauty-task-start-schema.mjs; do not edit.\n'
 +'-- No old original is rewritten and no Native, stock or task effect is backfilled.\n\n'
 +'ALTER TABLE bty_service_submission\n'+source.columns.map(c=>`    ADD COLUMN ${c.name} ${c.definition}`).join(',\n')
 +`,\n    ADD UNIQUE KEY ${source.index.name} (${source.index.columns.join(', ')}),\n    DROP CHECK ck_bty_task_action,\n`
 +Object.entries(source.checks).map(([n,v])=>`    ADD CONSTRAINT ${n} CHECK (${v})`).join(',\n')+';\n\n'
 +'DELIMITER $$\n'+source.triggers.map(t=>`CREATE TRIGGER ${t.name} BEFORE ${t.event} ON ${t.table}\nFOR EACH ROW\n${t.body}$$`).join('\n\n')+'\nDELIMITER ;\n';
function checksum(value){let crc=0xffffffff; for(const byte of Buffer.from(value.replace(/^\uFEFF/,'').replace(/[\r\n]/g,''),'utf8')){crc^=byte; for(let i=0;i<8;i++)crc=(crc>>>1)^((crc&1)?0xedb88320:0);}return (crc^0xffffffff)|0;}
const descriptor={...source,migrationScript:script,migrationSha256:createHash('sha256').update(sql).digest('hex'),flywayChecksum:checksum(sql),history:history.map(n=>({script:n,checksum:checksum(readFileSync(resolve(folder,n),'utf8'))})).concat({script,checksum:checksum(sql)})};
for(const [file,content] of [[resolve(folder,script),sql],
 [resolve(root,'src/main/resources/META-INF/shop/beauty-task-start-schema.json'),JSON.stringify(descriptor,null,2)+'\n']]) {
 if(process.argv.includes('--check')) {
  if(readFileSync(file,'utf8')!==content) throw Error('Stale frozen START generated file');
 } else writeFileSync(file,content);
}
