-- Nonfinancial buffet allowances and immutable intended banquet plans; original CORE quotes remain financial authority.
CREATE TABLE fnb_service_entitlement (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    entitlement_no VARCHAR(32) NOT NULL,
    form_no VARCHAR(32) NOT NULL,
    attendee_no VARCHAR(32) NOT NULL,
    goods_no VARCHAR(32) NOT NULL,
    sku_no VARCHAR(32) NOT NULL,
    menu_item_no VARCHAR(32) NOT NULL,
    unit VARCHAR(16) NOT NULL,
    granted_qty DECIMAL(24,6) NOT NULL,
    consumed_qty DECIMAL(24,6) NOT NULL DEFAULT 0,
    valid_from DATETIME(3) NOT NULL,
    valid_until DATETIME(3) NOT NULL,
    owner_snapshot LONGTEXT NOT NULL,
    quote_no VARCHAR(32) NOT NULL,
    quote_hash VARCHAR(64) NOT NULL,
    source_hash VARCHAR(64) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    created_by VARCHAR(32) NOT NULL,
    updated_by VARCHAR(32) NOT NULL,
    UNIQUE KEY uk_fnb_service_entitlement_no(entitlement_no),
    UNIQUE KEY uk_fnb_service_entitlement_attendee(entity_no,store_no,form_no,attendee_no,sku_no),
    CHECK (granted_qty>0 AND consumed_qty>=0 AND consumed_qty<=granted_qty),
    CHECK (valid_from<valid_until AND version>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE fnb_service_entitlement_event (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    event_no VARCHAR(32) NOT NULL,
    form_no VARCHAR(32) NOT NULL,
    entitlement_no VARCHAR(32) NULL,
    event_kind VARCHAR(16) NOT NULL,
    quantity DECIMAL(24,6) NOT NULL,
    batch_no VARCHAR(32) NULL,
    food_line_no VARCHAR(32) NULL,
    quote_no VARCHAR(32) NOT NULL,
    quote_hash VARCHAR(64) NOT NULL,
    evidence_snapshot LONGTEXT NOT NULL,
    actor_no VARCHAR(32) NOT NULL,
    reason VARCHAR(255) NOT NULL,
    created_at DATETIME(3) NOT NULL,
    UNIQUE KEY uk_fnb_service_entitlement_event_no(event_no),
    UNIQUE KEY uk_fnb_service_entitlement_original_line(entity_no,store_no,event_kind,batch_no,food_line_no),
    KEY ix_fnb_service_entitlement_form(entity_no,store_no,form_no,id),
    CHECK (event_kind IN ('GRANT','CONSUME','EXTEND') AND quantity>0),
    CHECK ((event_kind='CONSUME' AND entitlement_no IS NOT NULL AND batch_no IS NOT NULL AND food_line_no IS NOT NULL)
        OR (event_kind<>'CONSUME' AND batch_no IS NULL AND food_line_no IS NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE fnb_banquet_plan_revision (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    form_no VARCHAR(32) NOT NULL,
    plan_no VARCHAR(32) NOT NULL,
    revision BIGINT NOT NULL,
    currency VARCHAR(3) NOT NULL,
    intended_budget_minor BIGINT NOT NULL,
    planned_persons INT NOT NULL,
    plan_snapshot LONGTEXT NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    actor_no VARCHAR(32) NOT NULL,
    reason VARCHAR(255) NOT NULL,
    created_at DATETIME(3) NOT NULL,
    UNIQUE KEY uk_fnb_banquet_plan_no(plan_no),
    UNIQUE KEY uk_fnb_banquet_plan_revision(entity_no,store_no,form_no,revision),
    CHECK (revision>0 AND intended_budget_minor>=0 AND planned_persons>0 AND planned_persons<=1000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE fnb_banquet_attendance_confirmation (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    form_no VARCHAR(32) NOT NULL,
    confirmation_no VARCHAR(32) NOT NULL,
    plan_no VARCHAR(32) NOT NULL,
    form_version BIGINT NOT NULL,
    actual_persons INT NOT NULL,
    roster_snapshot LONGTEXT NOT NULL,
    roster_hash VARCHAR(64) NOT NULL,
    quote_no VARCHAR(32) NOT NULL,
    quote_hash VARCHAR(64) NOT NULL,
    quote_snapshot LONGTEXT NOT NULL,
    actor_no VARCHAR(32) NOT NULL,
    reason VARCHAR(255) NOT NULL,
    created_at DATETIME(3) NOT NULL,
    UNIQUE KEY uk_fnb_banquet_attendance_no(confirmation_no),
    UNIQUE KEY uk_fnb_banquet_attendance_plan(entity_no,store_no,form_no,plan_no),
    CHECK (form_version>=0 AND actual_persons>0 AND actual_persons<=1000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
