-- Restaurant device credentials and anonymous party authorizations. Raw credentials are never stored.
CREATE TABLE fnb_dining_device (
 id BIGINT NOT NULL AUTO_INCREMENT,
 tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
 created_at DATETIME(3) NOT NULL,
 created_by VARCHAR(32) NOT NULL,
 updated_at DATETIME(3) NOT NULL,
 updated_by VARCHAR(32) NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 deleted INT NOT NULL DEFAULT 0,
 entity_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
 store_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
 device_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
 display_name VARCHAR(64) NOT NULL,
 status VARCHAR(16) NOT NULL,
 generation BIGINT NOT NULL,
 credential_hash VARBINARY(64) NOT NULL,
 PRIMARY KEY(id), UNIQUE KEY uk_dining_device(entity_no,store_no,device_no)
) ENGINE=InnoDB;
CREATE TABLE fnb_identity_authorization (
 id BIGINT NOT NULL AUTO_INCREMENT,
 tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
 created_at DATETIME(3) NOT NULL,
 created_by VARCHAR(32) NOT NULL,
 updated_at DATETIME(3) NOT NULL,
 updated_by VARCHAR(32) NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 deleted INT NOT NULL DEFAULT 0,
 entity_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
 store_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
 authorization_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
 session_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
 kind VARCHAR(16) NOT NULL,
 device_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
 device_generation BIGINT NOT NULL DEFAULT 0,
 display_name VARCHAR(64) NOT NULL,
 issued_by VARCHAR(32) NOT NULL,
 status VARCHAR(16) NOT NULL,
 PRIMARY KEY(id), UNIQUE KEY uk_identity_session(session_no), UNIQUE KEY uk_identity_authorization(authorization_no),
 KEY ix_identity_device(entity_no,store_no,device_no,status)
) ENGINE=InnoDB;
CREATE TABLE fnb_identity_operation (
 id BIGINT NOT NULL AUTO_INCREMENT,
 tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
 created_at DATETIME(3) NOT NULL,
 created_by VARCHAR(32) NOT NULL,
 updated_at DATETIME(3) NOT NULL,
 updated_by VARCHAR(32) NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 deleted INT NOT NULL DEFAULT 0,
 entity_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
 store_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
 operation_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
 actor_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
 action VARCHAR(32) NOT NULL,
 request_key_hash VARCHAR(64) NOT NULL,
 request_hash VARCHAR(64) NOT NULL,
 result_json MEDIUMTEXT NULL,
 PRIMARY KEY(id), UNIQUE KEY uk_identity_operation(operation_no),
 UNIQUE KEY uk_identity_command(entity_no,store_no,actor_no,action,request_key_hash)
) ENGINE=InnoDB;
