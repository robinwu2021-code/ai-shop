-- Original production events and immutable inventory authority receipts; no stock balance here.

CREATE TABLE `fnb_production_consumption` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT 'BaseEntity自增物理主键，不对外不进URL',
    `tenant_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL DEFAULT 'MAIN' COMMENT '沿用BaseEntity，一期MAIN；不是entity_no，不另启租户体系',
    `entity_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '当前主体或业务发生时主体快照，不等于账号和支付商户号',
    `created_at` DATETIME(3) NOT NULL COMMENT '沿用MetaObjectHandler及现有LocalDateTime持久化约定',
    `created_by` VARCHAR(32) NOT NULL COMMENT '当前认证业务键；按现有填充规则，作业SYSTEM',
    `updated_at` DATETIME(3) NOT NULL COMMENT '沿用公共填充',
    `updated_by` VARCHAR(32) NOT NULL COMMENT '沿用公共填充',
    `version` BIGINT NOT NULL DEFAULT 0 COMMENT 'BaseEntity乐观锁',
    `deleted` INT NOT NULL DEFAULT 0 COMMENT 'BaseEntity逻辑删除；签核和事实表禁止业务归档覆盖历史',
    `consumption_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '耗用操作 Consumption',
    `store_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '门店 Store',
    `source_event_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '制作事件 Source event',
    `purpose` VARCHAR(24) NOT NULL COMMENT 'PRODUCTION / REMAKE / MATERIAL_WASTE / REVERSAL',
    `request_hash` CHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '不可变请求摘要 Request hash',
    `status` VARCHAR(16) NOT NULL COMMENT 'PREPARED / SUBMITTED / UNKNOWN / CONFIRMED / FAILED',
    `inventory_operation_ref` VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL COMMENT '库存权威操作号',
    `original_consumption_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL COMMENT '反向操作引用原耗用',
    `business_date` DATE NOT NULL COMMENT '营业日 Business date',
    `occurred_at` DATETIME(3) NOT NULL COMMENT '原事件真实发生时刻 Occurred at',
    `request_snapshot` JSON NOT NULL COMMENT '不可变原请求/真实库存回执',
    `receipt_snapshot` JSON NULL COMMENT '不可变原请求/真实库存回执',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_food_1` (`consumption_no`),
    UNIQUE KEY `uk_food_2` (`source_event_no`, `purpose`),
    KEY `ix_food_audit` (`entity_no`, `created_at`, `id`),
    KEY `ix_food_store` (`entity_no`, `store_no`, `updated_at`, `id`),
    KEY `ix_food_ref_1` (`entity_no`, `original_consumption_no`, `id`)
) ENGINE=InnoDB COMMENT='制作耗用意图 Production consumption';

CREATE TABLE `fnb_production_consumption_line` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT 'BaseEntity自增物理主键，不对外不进URL',
    `tenant_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL DEFAULT 'MAIN' COMMENT '沿用BaseEntity，一期MAIN；不是entity_no，不另启租户体系',
    `entity_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '当前主体或业务发生时主体快照，不等于账号和支付商户号',
    `created_at` DATETIME(3) NOT NULL COMMENT '沿用MetaObjectHandler及现有LocalDateTime持久化约定',
    `created_by` VARCHAR(32) NOT NULL COMMENT '当前认证业务键；按现有填充规则，作业SYSTEM',
    `updated_at` DATETIME(3) NOT NULL COMMENT '沿用公共填充',
    `updated_by` VARCHAR(32) NOT NULL COMMENT '沿用公共填充',
    `version` BIGINT NOT NULL DEFAULT 0 COMMENT 'BaseEntity乐观锁',
    `deleted` INT NOT NULL DEFAULT 0 COMMENT 'BaseEntity逻辑删除；签核和事实表禁止业务归档覆盖历史',
    `consumption_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '耗用 Consumption',
    `line_no` INT NOT NULL COMMENT '行序号 Line number',
    `component_path` VARCHAR(255) NOT NULL COMMENT '制作实例及组件路径 Instance path',
    `item_ref` VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '进销存物料引用 Material',
