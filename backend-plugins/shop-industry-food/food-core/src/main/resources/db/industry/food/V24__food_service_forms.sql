-- Operational service admissions and original-source bindings; no credit or funds authority.
CREATE TABLE fnb_business_organization (
    id BIGINT NOT NULL AUTO_INCREMENT,
    tenant_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL DEFAULT 'MAIN',
    entity_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    store_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    created_by VARCHAR(32) NOT NULL,
    updated_by VARCHAR(32) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    organization_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    name VARCHAR(128) NOT NULL,
    contact_ref VARCHAR(64) NOT NULL,
    external_ref VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_food_service_organization (organization_no),
    UNIQUE KEY uk_food_service_org_external (entity_no,store_no,external_ref),
    CHECK (status IN ('ACTIVE','DISABLED'))
) ENGINE=InnoDB;

CREATE TABLE fnb_service_form (
    id BIGINT NOT NULL AUTO_INCREMENT,
    tenant_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL DEFAULT 'MAIN',
    entity_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    store_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    created_by VARCHAR(32) NOT NULL,
    updated_by VARCHAR(32) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    form_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    kind VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL,
    reservation_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
    slot_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
    menu_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
    menu_revision_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
    menu_snapshot JSON NULL,
    guaranteed_persons INT NOT NULL,
    actual_persons INT NULL,
    check_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
    active_check_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
    starts_at DATETIME(3) NOT NULL,
    ends_at DATETIME(3) NOT NULL,
    entered_at DATETIME(3) NULL,
    left_at DATETIME(3) NULL,
    organization_no VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL,
    contact_ref VARCHAR(64) NULL,
    max_entries_per_person INT NOT NULL,
    cancel_target VARCHAR(16) NULL,
    cancel_reason VARCHAR(255) NULL,
    source_transition VARCHAR(32) NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_food_service_form (form_no),
    UNIQUE KEY uk_food_service_active_check (entity_no,store_no,active_check_no),
    KEY ix_food_service_reservation (entity_no,store_no,reservation_no),
    CHECK (kind IN ('NORMAL','BUFFET','BANQUET','CORPORATE')),
    CHECK (status IN ('BOOKED','ACTIVE','LEFT','CANCELLING','CANCELLED','NO_SHOW')),
    CHECK (starts_at<ends_at AND guaranteed_persons>0 AND max_entries_per_person>0),
    CHECK ((status='ACTIVE' AND active_check_no=check_no AND actual_persons>0) OR (status<>'ACTIVE' AND active_check_no IS NULL)),
    CHECK (kind<>'CORPORATE' OR organization_no IS NOT NULL),
    CHECK (kind<>'BANQUET' OR reservation_no IS NOT NULL)
) ENGINE=InnoDB;

