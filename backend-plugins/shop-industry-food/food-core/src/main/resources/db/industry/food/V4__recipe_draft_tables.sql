-- Recipe drafts only; preserve V1-V3. No stock execution or conversion authority.

CREATE TABLE `fnb_recipe` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT 'BaseEntity自增物理主键，不对外不进URL',
    `tenant_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL DEFAULT 'MAIN' COMMENT '沿用BaseEntity，一期MAIN；不是entity_no，不另启租户体系',
    `entity_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '当前主体或业务发生时主体快照，不等于账号和支付商户号',
    `created_at` DATETIME(3) NOT NULL COMMENT '沿用MetaObjectHandler及现有LocalDateTime持久化约定',
    `created_by` VARCHAR(32) NOT NULL COMMENT '当前认证业务键；按现有填充规则，作业SYSTEM',
    `updated_at` DATETIME(3) NOT NULL COMMENT '沿用公共填充',
    `updated_by` VARCHAR(32) NOT NULL COMMENT '沿用公共填充',
    `version` BIGINT NOT NULL DEFAULT 0 COMMENT 'BaseEntity乐观锁',
    `deleted` INT NOT NULL DEFAULT 0 COMMENT 'BaseEntity逻辑删除；签核和事实表禁止业务归档覆盖历史',
    `recipe_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '配方编号 Recipe',
    `store_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '门店 Store',
    `sku_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '销售规格 SKU',
    `recipe_code` VARCHAR(32) NOT NULL COMMENT 'DEFAULT或受控配方变体 Variant',
    `yield_qty` DECIMAL(18,6) NOT NULL COMMENT '基准产出 Positive yield',
    `yield_unit` VARCHAR(16) NOT NULL COMMENT '产出单位 Controlled unit',
    `config_version` BIGINT NOT NULL COMMENT '配方内容版本 Configuration version',
    `published_revision_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL COMMENT '冻结修订 Published revision',
    `status` VARCHAR(16) NOT NULL COMMENT 'DRAFT / ACTIVE / DISABLED',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_food_1` (`recipe_no`),
    UNIQUE KEY `uk_food_2` (`store_no`, `sku_no`, `recipe_code`),
    KEY `ix_food_audit` (`entity_no`, `created_at`, `id`),
    KEY `ix_food_store` (`entity_no`, `store_no`, `updated_at`, `id`),
    KEY `ix_food_ref_1` (`entity_no`, `published_revision_no`, `id`),
    CHECK (`yield_qty` > 0)
) ENGINE=InnoDB COMMENT='SKU配方工作头 SKU recipe';

CREATE TABLE `fnb_recipe_line` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT 'BaseEntity自增物理主键，不对外不进URL',
    `tenant_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL DEFAULT 'MAIN' COMMENT '沿用BaseEntity，一期MAIN；不是entity_no，不另启租户体系',
    `entity_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '当前主体或业务发生时主体快照，不等于账号和支付商户号',
    `created_at` DATETIME(3) NOT NULL COMMENT '沿用MetaObjectHandler及现有LocalDateTime持久化约定',
    `created_by` VARCHAR(32) NOT NULL COMMENT '当前认证业务键；按现有填充规则，作业SYSTEM',
    `updated_at` DATETIME(3) NOT NULL COMMENT '沿用公共填充',
    `updated_by` VARCHAR(32) NOT NULL COMMENT '沿用公共填充',
    `version` BIGINT NOT NULL DEFAULT 0 COMMENT 'BaseEntity乐观锁',
    `deleted` INT NOT NULL DEFAULT 0 COMMENT 'BaseEntity逻辑删除；签核和事实表禁止业务归档覆盖历史',
    `line_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '物料行编号 Recipe line',
    `recipe_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '配方 Recipe',
    `item_ref` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '进销存物料引用 Inventory item',
    `qty` DECIMAL(18,6) NOT NULL COMMENT '每基准产出净用量 Net requirement',
    `unit` VARCHAR(16) NOT NULL COMMENT '权威物料单位 Material unit',
    `conversion_ref` VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL COMMENT '保留真实换算引用；本批NULL Reserved true conversion reference',
    `loss_rate` DECIMAL(12,6) NOT NULL COMMENT '投入损失比例 0<=rate<1',
    `material_definition_hash` VARCHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT '物料定义内容摘要 Material definition hash (not CAS/conversion)',
    `sort_no` INT NOT NULL COMMENT '草稿行顺序 Draft line order',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_food_1` (`line_no`),
    UNIQUE KEY `uk_food_2` (`recipe_no`, `line_no`),
    KEY `ix_food_audit` (`entity_no`, `created_at`, `id`),
    CHECK (`qty` > 0),
    CHECK (`loss_rate` >= 0 AND `loss_rate` < 1)
) ENGINE=InnoDB COMMENT='配方物料行 Recipe material line';
