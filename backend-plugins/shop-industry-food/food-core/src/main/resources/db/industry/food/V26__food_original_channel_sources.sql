-- Genuine external transaction parties and original restaurant import sources; no local user, guest token or paid flag.
CREATE TABLE fnb_channel_party (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    created_at DATETIME(3) NOT NULL,
    created_by VARCHAR(32) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    updated_by VARCHAR(32) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    party_no VARCHAR(32) NOT NULL,
    channel_store_key VARCHAR(64) NOT NULL,
    party_key VARCHAR(64) NOT NULL,
    external_customer_ref VARCHAR(128) NULL,
    original_external_order_ref VARCHAR(128) NOT NULL,
    display_name VARCHAR(256) NULL,
    UNIQUE KEY uk_fnb_channel_party_no(party_no),
    UNIQUE KEY uk_fnb_channel_party_identity(tenant_no,entity_no,store_no,channel_store_key,party_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE fnb_channel_order_source (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    created_at DATETIME(3) NOT NULL,
    created_by VARCHAR(32) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    updated_by VARCHAR(32) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    source_no VARCHAR(32) NOT NULL,
    import_no VARCHAR(32) NOT NULL,
    channel_store_key VARCHAR(64) NOT NULL,
    external_order_key VARCHAR(64) NOT NULL,
    external_order_ref VARCHAR(128) NOT NULL,
    original_document_hash VARCHAR(64) NOT NULL,
    original_financial_hash VARCHAR(64) NOT NULL,
    connection_no VARCHAR(32) NOT NULL,
    connection_revision_no VARCHAR(32) NOT NULL,
    external_snapshot_no VARCHAR(32) NOT NULL,
    party_no VARCHAR(32) NOT NULL,
    cart_no VARCHAR(32) NOT NULL,
    batch_no VARCHAR(32) NOT NULL,
    source_version BIGINT NOT NULL,
    source_hash VARCHAR(64) NOT NULL,
    source_snapshot LONGTEXT NOT NULL,
    envelope_snapshot LONGTEXT NOT NULL,
    status VARCHAR(32) NOT NULL,
    core_order_no VARCHAR(32) NULL,
    core_sub_order_no VARCHAR(32) NULL,
    core_acceptance_receipt_ref VARCHAR(128) NULL,
    acceptance_receipt_ref VARCHAR(128) NULL,
    cancellation_receipt_ref VARCHAR(128) NULL,
    fence BIGINT NOT NULL DEFAULT 0,
    lease_until DATETIME(3) NULL,
    next_recovery_at DATETIME(3) NULL,
    last_error_code VARCHAR(64) NULL,
    UNIQUE KEY uk_fnb_channel_source_no(source_no),
    UNIQUE KEY uk_fnb_channel_source_import(tenant_no,entity_no,store_no,import_no),
    UNIQUE KEY uk_fnb_channel_source_external(tenant_no,channel_store_key,external_order_key),
    UNIQUE KEY uk_fnb_channel_source_cart(cart_no),
    UNIQUE KEY uk_fnb_channel_source_batch(batch_no),
    KEY ix_fnb_channel_source_recovery(status,next_recovery_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
