-- Business responsibility over immutable original amounts; no core receivable or payment authority.
CREATE TABLE `fnb_business_share_plan` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT 'BaseEntity physical primary key',
    `tenant_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL DEFAULT 'MAIN',
    `entity_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    `created_at` DATETIME(3) NOT NULL,
    `created_by` VARCHAR(32) NOT NULL,
    `updated_at` DATETIME(3) NOT NULL,
    `updated_by` VARCHAR(32) NOT NULL,
    `version` BIGINT NOT NULL DEFAULT 0,
    `deleted` INT NOT NULL DEFAULT 0,
    `store_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    `check_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    `plan_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    `active_check_no` VARCHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NULL COMMENT 'Local plan slot only',
    `request_key` CHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Hashed original creation key',
    `request_hash` CHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    `status` VARCHAR(32) NOT NULL COMMENT 'DRAFT_BUSINESS_ONLY/CONFIRMED_BUSINESS_ONLY/CANCELLED_BUSINESS_ONLY',
    `mode` VARCHAR(16) NOT NULL COMMENT 'BY_PERSON/BY_AMOUNT/BY_LINE',
    `currency` CHAR(3) NOT NULL,
    `original_amount_minor` BIGINT NOT NULL COMMENT 'Original order amount, never current outstanding',
    `source_hash` CHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    `plan_hash` CHAR(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL,
    `source_snapshot` JSON NOT NULL,
    `division_snapshot` JSON NOT NULL,
    `definition_snapshot` JSON NOT NULL,
    `reason` VARCHAR(255) NOT NULL,
    `confirmed_by` VARCHAR(32) NULL,
    `cancelled_by` VARCHAR(32) NULL,
    `cancellation_reason` VARCHAR(255) NULL,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_food_share_plan` (`plan_no`),
    UNIQUE KEY `uk_food_share_request` (`entity_no`,`store_no`,`request_key`),
    UNIQUE KEY `uk_food_share_active` (`entity_no`,`store_no`,`active_check_no`),
    KEY `ix_food_share_check` (`entity_no`,`store_no`,`check_no`,`created_at`,`id`),
    CHECK (`original_amount_minor` >= 0),
    CHECK (`active_check_no` IS NULL OR `active_check_no` = `check_no`),
    CHECK ((`status` IN ('DRAFT_BUSINESS_ONLY','CONFIRMED_BUSINESS_ONLY') AND `active_check_no` IS NOT NULL)
        OR (`status` = 'CANCELLED_BUSINESS_ONLY' AND `active_check_no` IS NULL))
) ENGINE=InnoDB COMMENT='Business responsibility plan, no settlement authority';
