-- Authorization intent and evidence only; V1 remains frozen.
ALTER TABLE cim_account ADD COLUMN active_operation_no VARCHAR(32) NULL;

CREATE TABLE cim_authorization_revision (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    authorization_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    account_no VARCHAR(32) NOT NULL,
    revision_no BIGINT NOT NULL,
    credential_ref VARCHAR(128) NOT NULL,
    granted_scopes LONGTEXT NOT NULL,
    capability_hash CHAR(64) NOT NULL,
    authorized_at DATETIME(3) NOT NULL,
    expires_at DATETIME(3) NULL,
    status VARCHAR(24) NOT NULL,
    evidence_ref VARCHAR(256) NOT NULL,
    UNIQUE KEY uk_cim_authorization_no(authorization_no),
    UNIQUE KEY uk_cim_authorization_revision(account_no,
    revision_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE cim_operation (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    operation_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NULL,
    connection_no VARCHAR(32) NULL,
    destination VARCHAR(24) NOT NULL,
    operation_type VARCHAR(48) NOT NULL,
    business_ref VARCHAR(128) NOT NULL,
    business_revision VARCHAR(128) NOT NULL,
    semantic_key CHAR(64) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    request_ref VARCHAR(256) NOT NULL,
    status VARCHAR(24) NOT NULL,
    current_attempt_no BIGINT NOT NULL,
    fence BIGINT NOT NULL,
    lease_until DATETIME(3) NULL,
    next_recovery_at DATETIME(3) NULL,
    original_evidence_ref VARCHAR(256) NULL,
    account_no VARCHAR(32) NOT NULL,
    profile_no VARCHAR(32) NOT NULL,
    target_scope_kind VARCHAR(24) NOT NULL,
    target_scope_key CHAR(64) NOT NULL,
    callback_state_hash CHAR(64) NULL,
    expires_at DATETIME(3) NULL,
    callback_consumed_at DATETIME(3) NULL,
    callback_request_hash CHAR(64) NULL,
    authorization_url LONGTEXT NULL,
    return_target_code VARCHAR(32) NULL,
    reason_code VARCHAR(64) NULL,
    reason VARCHAR(256) NULL,
    UNIQUE KEY uk_cim_operation_no(operation_no),
    UNIQUE KEY uk_cim_operation_semantic(target_scope_key,
    destination,
    semantic_key),
    UNIQUE KEY uk_cim_operation_state(callback_state_hash),
    KEY ix_cim_operation_recovery(status,
    next_recovery_at,
    id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE cim_operation_attempt (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    attempt_ref VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    operation_no VARCHAR(32) NOT NULL,
    attempt_no BIGINT NOT NULL,
    fence BIGINT NOT NULL,
    attempt_kind VARCHAR(24) NOT NULL,
    provider_request_ref VARCHAR(128) NULL,
    provider_task_ref VARCHAR(128) NULL,
    started_at DATETIME(3) NOT NULL,
    finished_at DATETIME(3) NULL,
    outcome VARCHAR(24) NOT NULL,
    response_ref VARCHAR(256) NULL,
    error_code VARCHAR(64) NULL,
    UNIQUE KEY uk_cim_attempt_ref(attempt_ref),
    UNIQUE KEY uk_cim_attempt_seq(operation_no,
    attempt_no),
    KEY ix_cim_attempt_task(provider_task_ref)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
