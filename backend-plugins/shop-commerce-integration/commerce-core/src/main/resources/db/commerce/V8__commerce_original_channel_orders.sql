-- Immutable original platform revisions and a separate resumable import workflow.
CREATE TABLE cim_order_link (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    channel_order_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    connection_no VARCHAR(32) NOT NULL,
    channel_store_key VARCHAR(64) NOT NULL,
    external_order_ref VARCHAR(128) NOT NULL,
    ordered_at DATETIME(3) NOT NULL,
    external_order_key VARCHAR(64) NOT NULL,
    source_owner VARCHAR(24) NOT NULL,
    connection_revision_no VARCHAR(32) NOT NULL,
    active_revision_no VARCHAR(32) NOT NULL,
    import_ref VARCHAR(32) NOT NULL,
    source_order_ref VARCHAR(64) NULL,
    core_order_ref VARCHAR(64) NULL,
    import_status VARCHAR(24) NOT NULL,
    acceptance_status VARCHAR(24) NOT NULL,
    platform_status VARCHAR(64) NOT NULL,
    fulfillment_status VARCHAR(32) NOT NULL,
    financial_evidence_status VARCHAR(32) NOT NULL,
    import_snapshot LONGTEXT NULL,
    preparation_receipt_ref VARCHAR(256) NULL,
    acceptance_receipt_ref VARCHAR(256) NULL,
    decision_operation_no VARCHAR(32) NULL,
    platform_acceptance_receipt_ref VARCHAR(256) NULL,
    attempt_no BIGINT NOT NULL DEFAULT 0,
    fence BIGINT NOT NULL DEFAULT 0,
    lease_until DATETIME(3) NULL,
    next_attempt_at DATETIME(3) NULL,
    UNIQUE KEY uk_cim_order_link_no(channel_order_no),
    UNIQUE KEY uk_cim_order_link_external(channel_store_key,external_order_key),
    KEY ix_cim_order_link_store(entity_no,store_no,created_at,id),
    KEY ix_cim_order_link_due(import_status,next_attempt_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE cim_order_revision (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    revision_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    channel_order_no VARCHAR(32) NOT NULL,
    external_revision VARCHAR(128) NOT NULL,
    external_sequence BIGINT NULL,
    source_event_no VARCHAR(32) NULL,
    normalized_snapshot_ref VARCHAR(256) NOT NULL,
    normalized_snapshot LONGTEXT NOT NULL,
    raw_receipt_ref VARCHAR(32) NULL,
    original_receipt_ref VARCHAR(256) NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    catalog_hash VARCHAR(64) NOT NULL,
    currency VARCHAR(8) NOT NULL,
    captured_at DATETIME(3) NOT NULL,
    UNIQUE KEY uk_cim_order_revision_no(revision_no),
    UNIQUE KEY uk_cim_order_revision_hash(channel_order_no,content_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
