-- Opaque original owner references and confirmed allocations; not reconstructed product/order prices.
CREATE TABLE cim_order_line_link (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    link_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    channel_order_no VARCHAR(32) NOT NULL,
    order_revision_no VARCHAR(32) NOT NULL,
    external_line_ref VARCHAR(128) NOT NULL,
    parent_external_line_ref VARCHAR(128) NULL,
    component_kind VARCHAR(24) NOT NULL,
    component_ref VARCHAR(128) NOT NULL,
    source_line_ref VARCHAR(128) NOT NULL,
    core_order_ref VARCHAR(64) NOT NULL,
    core_item_ref VARCHAR(64) NOT NULL,
    sale_quantity DECIMAL(20,6) NOT NULL,
    quantity_unit VARCHAR(16) NOT NULL,
    amount_minor BIGINT NOT NULL,
    currency VARCHAR(8) NOT NULL,
    allocation_evidence_ref VARCHAR(256) NOT NULL,
    UNIQUE KEY uk_cim_order_line_link_no(link_no),
    UNIQUE KEY uk_cim_order_line_allocation(order_revision_no,external_line_ref,component_ref,core_order_ref,core_item_ref),
    KEY ix_cim_order_line_order(entity_no,channel_order_no,order_revision_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
