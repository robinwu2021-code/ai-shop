-- Signature verification precedes trusted scope persistence. Raw bytes use base64 to preserve exact original data.
CREATE TABLE cim_inbound_event (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    event_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    connection_no VARCHAR(32) NOT NULL,
    connection_revision_no VARCHAR(32) NOT NULL,
    dedupe_key CHAR(64) NOT NULL,
    provider_event_ref VARCHAR(128) NULL,
    event_type VARCHAR(64) NOT NULL,
    payload_hash CHAR(64) NOT NULL,
    original_receipt_no VARCHAR(32) NOT NULL,
    occurred_at DATETIME(3) NULL,
    status VARCHAR(24) NOT NULL,
    attempt_no BIGINT NOT NULL DEFAULT 0,
    fence BIGINT NOT NULL DEFAULT 0,
    lease_until DATETIME(3) NULL,
    next_attempt_at DATETIME(3) NULL,
    result_ref VARCHAR(128) NULL,
    external_order_ref VARCHAR(128) NULL,
    external_revision VARCHAR(128) NULL,
    authorization_no VARCHAR(32) NOT NULL,
    verification_evidence_ref VARCHAR(256) NOT NULL,
    UNIQUE KEY uk_cim_inbound_event_no(event_no),
    UNIQUE KEY uk_cim_inbound_event_identity(connection_no,dedupe_key),
    KEY ix_cim_inbound_event_due(status,next_attempt_at,id),
    KEY ix_cim_inbound_event_store(entity_no,store_no,created_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE cim_inbound_receipt (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    receipt_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    connection_no VARCHAR(32) NOT NULL,
    event_no VARCHAR(32) NOT NULL,
    received_at DATETIME(3) NOT NULL,
    payload_ref VARCHAR(256) NOT NULL,
    payload_hash CHAR(64) NOT NULL,
    signature_result VARCHAR(24) NOT NULL,
    classification VARCHAR(24) NOT NULL,
    retention_until DATETIME(3) NOT NULL,
    payload_base64 LONGTEXT NOT NULL,
    authorization_no VARCHAR(32) NOT NULL,
    verification_evidence_ref VARCHAR(256) NOT NULL,
    UNIQUE KEY uk_cim_inbound_receipt_no(receipt_no),
    KEY ix_cim_inbound_receipt_event(event_no,classification),
    KEY ix_cim_inbound_receipt_store(connection_no,received_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
