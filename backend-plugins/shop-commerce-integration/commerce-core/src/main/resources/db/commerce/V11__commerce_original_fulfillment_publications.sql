-- Original business fulfillment and immutable supplier publications; no independent stock ledger.
CREATE TABLE cim_fulfillment_link (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    link_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    channel_order_no VARCHAR(32) NOT NULL,
    source_owner VARCHAR(24) NOT NULL,
    source_fulfillment_ref VARCHAR(128) NOT NULL,
    source_revision VARCHAR(128) NOT NULL,
    fulfillment_type VARCHAR(24) NOT NULL,
    stage VARCHAR(24) NOT NULL,
    external_fulfillment_ref VARCHAR(128) NULL,
    tracking_evidence_ref VARCHAR(256) NULL,
    operation_no VARCHAR(32) NOT NULL,
    status VARCHAR(24) NOT NULL,
    source_hash VARCHAR(64) NOT NULL,
    source_snapshot LONGTEXT NOT NULL,
    payload_json LONGTEXT NOT NULL,
    connection_revision_no VARCHAR(32) NOT NULL,
    UNIQUE KEY uk_cim_fulfillment_link_no(link_no),
    UNIQUE KEY uk_cim_fulfillment_source(channel_order_no,source_owner,source_fulfillment_ref,source_revision),
    UNIQUE KEY uk_cim_fulfillment_operation(operation_no),
    KEY ix_cim_fulfillment_order(entity_no,channel_order_no,created_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE cim_fulfillment_line_link (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    link_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    fulfillment_link_no VARCHAR(32) NOT NULL,
    order_line_link_no VARCHAR(32) NOT NULL,
    quantity DECIMAL(20,6) NOT NULL,
    unit VARCHAR(16) NOT NULL,
    source_receipt_ref VARCHAR(256) NOT NULL,
    UNIQUE KEY uk_cim_fulfillment_line_no(link_no),
    UNIQUE KEY uk_cim_fulfillment_line(fulfillment_link_no,order_line_link_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
