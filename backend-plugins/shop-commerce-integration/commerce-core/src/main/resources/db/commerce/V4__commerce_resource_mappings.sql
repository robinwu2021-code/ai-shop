-- Immutable mapping drafts and verified historical revisions; V1-V3 are frozen.
CREATE TABLE cim_resource_mapping (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    mapping_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    connection_no VARCHAR(32) NOT NULL,
    object_type VARCHAR(32) NOT NULL,
    external_ref VARCHAR(128) NOT NULL,
    external_identity_hash CHAR(64) NOT NULL,
    external_identity_json LONGTEXT NOT NULL,
    active_revision_no VARCHAR(32) NULL,
    latest_revision_no VARCHAR(32) NOT NULL,
    verification_operation_no VARCHAR(32) NULL,
    verification_lease_until DATETIME(3) NULL,
    next_verification_at DATETIME(3) NULL,
    UNIQUE KEY uk_cim_mapping_no(mapping_no),
    UNIQUE KEY uk_cim_mapping_identity(connection_no,object_type,external_identity_hash),
    KEY ix_cim_mapping_store(entity_no,store_no,id),
    KEY ix_cim_mapping_due(next_verification_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE cim_resource_mapping_revision (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    revision_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    mapping_no VARCHAR(32) NOT NULL,
    revision BIGINT NOT NULL,
    source_owner VARCHAR(24) NOT NULL,
    source_ref VARCHAR(128) NOT NULL,
    source_revision_ref VARCHAR(128) NOT NULL,
    sales_offer_ref VARCHAR(128) NULL,
    mapping_snapshot LONGTEXT NOT NULL,
    content_hash CHAR(64) NOT NULL,
    effective_at DATETIME(3) NULL,
    validation_receipt_ref VARCHAR(128) NULL,
    external_evidence_ref VARCHAR(256) NULL,
    mapping_origin VARCHAR(24) NOT NULL,
    validation_status VARCHAR(24) NOT NULL,
    source_content_hash CHAR(64) NULL,
    validation_expires_at DATETIME(3) NULL,
    connection_revision_no VARCHAR(32) NOT NULL,
    authorization_no VARCHAR(32) NULL,
    reason VARCHAR(256) NOT NULL,
    UNIQUE KEY uk_cim_mapping_revision_no(revision_no),
    UNIQUE KEY uk_cim_mapping_revision(mapping_no,revision),
    KEY ix_cim_mapping_revision_source(source_ref,mapping_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
