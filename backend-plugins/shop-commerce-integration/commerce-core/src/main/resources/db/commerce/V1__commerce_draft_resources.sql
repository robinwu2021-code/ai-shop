CREATE TABLE cim_request_journal (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    request_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NULL,
    endpoint_key VARCHAR(96) NOT NULL,
    key_hash CHAR(64) NOT NULL,
    actor_no VARCHAR(32) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    status VARCHAR(24) NOT NULL,
    result_ref VARCHAR(128) NULL,
    result_snapshot LONGTEXT NULL,
    scope_kind VARCHAR(24) NOT NULL,
    scope_key CHAR(64) NOT NULL,
    UNIQUE KEY uk_cim_request_no(request_no),
    UNIQUE KEY uk_cim_request_key(tenant_no,
    scope_kind,
    scope_key,
    endpoint_key,
    key_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
