-- C0 draft resources only. No credentials or external platform activation.
CREATE TABLE cim_provider (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    provider_no VARCHAR(32) NOT NULL,
    provider_code VARCHAR(32) NOT NULL,
    name VARCHAR(128) NOT NULL,
    status VARCHAR(24) NOT NULL,
    UNIQUE KEY uk_cim_provider_no(provider_no),
    UNIQUE KEY uk_cim_provider_code(provider_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE cim_product_profile (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    profile_no VARCHAR(32) NOT NULL,
    provider_no VARCHAR(32) NOT NULL,
    product_code VARCHAR(32) NOT NULL,
    market VARCHAR(8) NOT NULL,
    protocol_code VARCHAR(64) NOT NULL,
    capability_definition JSON NOT NULL,
    identity_schema_version INT NOT NULL,
    identity_namespace VARCHAR(128) NOT NULL,
    store_identity_scope VARCHAR(24) NOT NULL,
    status VARCHAR(24) NOT NULL,
    UNIQUE KEY uk_cim_profile_no(profile_no),
    UNIQUE KEY uk_cim_profile_product(provider_no,
    product_code,
    market,
    protocol_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE cim_account (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    account_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    profile_no VARCHAR(32) NOT NULL,
    external_account_ref VARCHAR(128) NOT NULL,
    active_authorization_no VARCHAR(32) NULL,
    status VARCHAR(24) NOT NULL,
    UNIQUE KEY uk_cim_account_no(account_no),
    UNIQUE KEY uk_cim_account_external(entity_no,
    profile_no,
    external_account_ref)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;

CREATE TABLE cim_store_connection (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    connection_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    profile_no VARCHAR(32) NOT NULL,
    account_no VARCHAR(32) NOT NULL,
    external_store_ref VARCHAR(128) NOT NULL,
    channel_store_key CHAR(64) NOT NULL,
    identity_receipt_ref VARCHAR(128) NOT NULL,
    identity_verified_at DATETIME(3) NOT NULL,
    identity_valid_until DATETIME(3) NOT NULL,
