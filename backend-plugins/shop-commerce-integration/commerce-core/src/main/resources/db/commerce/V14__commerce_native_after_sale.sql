-- Supplier case revisions/decisions remain separate from original business, independent inventory and local funds.
CREATE TABLE cim_after_sale_link (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    case_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NOT NULL,
    connection_no VARCHAR(32) NOT NULL,
    channel_order_no VARCHAR(32) NOT NULL,
    external_case_key VARCHAR(64) NOT NULL,
    external_case_ref VARCHAR(128) NOT NULL,
    active_revision_no VARCHAR(32) NOT NULL,
    supplier_state VARCHAR(32) NOT NULL,
    type VARCHAR(32) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    merchant_refund_minor BIGINT NOT NULL,
    requested_at DATETIME(3) NOT NULL,
    decision_status VARCHAR(40) NOT NULL,
    source_decision_ref VARCHAR(32) NULL,
    source_revision VARCHAR(128) NULL,
    source_decision_hash VARCHAR(64) NULL,
    source_decision_snapshot LONGTEXT NULL,
    local_funds_status VARCHAR(64) NOT NULL,
    local_inventory_status VARCHAR(64) NOT NULL,
    operation_no VARCHAR(32) NULL,
    payload_json LONGTEXT NULL,
    connection_revision_no VARCHAR(32) NOT NULL,
    UNIQUE KEY uk_cim_after_sale(tenant_no,case_no),
    UNIQUE KEY uk_cim_after_sale_external(tenant_no,entity_no,store_no,channel_order_no,external_case_key),
    KEY idx_cim_after_sale_list(tenant_no,entity_no,store_no,requested_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE cim_after_sale_revision (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    revision_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    case_no VARCHAR(32) NOT NULL,
    external_revision VARCHAR(128) NOT NULL,
    external_sequence BIGINT NOT NULL,
    content_hash VARCHAR(64) NOT NULL,
    payload_json LONGTEXT NOT NULL,
    original_receipt_ref VARCHAR(256) NOT NULL,
    origin_event_no VARCHAR(32) NOT NULL,
    UNIQUE KEY uk_cim_after_sale_revision(tenant_no,revision_no),
    UNIQUE KEY uk_cim_after_sale_revision_contents(tenant_no,case_no,external_revision,content_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE cim_after_sale_line_link (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    link_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    case_no VARCHAR(32) NOT NULL,
    order_line_link_no VARCHAR(32) NOT NULL,
    source_line_ref VARCHAR(128) NOT NULL,
    component_ref VARCHAR(64) NOT NULL,
    core_item_ref VARCHAR(128) NOT NULL,
    quantity DECIMAL(24,6) NOT NULL,
    unit VARCHAR(16) NOT NULL,
    refund_ceiling_minor BIGINT NOT NULL,
    allocation_evidence_ref VARCHAR(256) NOT NULL,
    UNIQUE KEY uk_cim_after_sale_line(tenant_no,case_no,order_line_link_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
