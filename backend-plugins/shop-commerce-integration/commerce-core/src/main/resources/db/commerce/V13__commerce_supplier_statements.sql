-- Supplier evidence only: no local payment, receivable or treasury ledger.
CREATE TABLE cim_statement (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    statement_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    account_no VARCHAR(32) NOT NULL,
    profile_no VARCHAR(32) NOT NULL,
    statement_ref VARCHAR(128) NOT NULL,
    source_revision VARCHAR(128) NOT NULL,
    expected_hash VARCHAR(64) NOT NULL,
    document_hash VARCHAR(64) NULL,
    payload_json LONGTEXT NULL,
    lookup_json LONGTEXT NOT NULL,
    currency VARCHAR(3) NULL,
    period_start DATETIME(3) NULL,
    period_end DATETIME(3) NULL,
    status VARCHAR(32) NOT NULL,
    operation_no VARCHAR(32) NOT NULL,
    original_receipt_ref VARCHAR(256) NULL,
    UNIQUE KEY uk_cim_statement_no(statement_no),
    UNIQUE KEY uk_cim_statement_original(entity_no,account_no,statement_ref,source_revision),
    UNIQUE KEY uk_cim_statement_operation(operation_no),
    KEY ix_cim_statement_account(entity_no,account_no,created_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE cim_statement_line (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    tenant_no VARCHAR(32) NOT NULL DEFAULT 'MAIN',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    created_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_by VARCHAR(32) NOT NULL DEFAULT 'SYSTEM',
    version BIGINT NOT NULL DEFAULT 0,
    deleted INT NOT NULL DEFAULT 0,
    line_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    statement_no VARCHAR(32) NOT NULL,
    account_no VARCHAR(32) NOT NULL,
    store_no VARCHAR(32) NULL,
    connection_no VARCHAR(32) NULL,
    line_ref VARCHAR(128) NOT NULL,
    kind VARCHAR(32) NOT NULL,
    external_store_ref VARCHAR(128) NULL,
    external_order_ref VARCHAR(128) NULL,
    external_after_sale_ref VARCHAR(128) NULL,
    currency VARCHAR(3) NOT NULL,
    difference_code VARCHAR(32) NOT NULL,
    amounts_json LONGTEXT NOT NULL,
    UNIQUE KEY uk_cim_statement_line_no(line_no),
    UNIQUE KEY uk_cim_statement_line_original(statement_no,line_ref),
    KEY ix_cim_statement_store(entity_no,store_no,statement_no,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
