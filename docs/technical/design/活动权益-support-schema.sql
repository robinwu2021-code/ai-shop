CREATE TABLE ord_ent_authorization (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    authorization_no VARCHAR(64) NOT NULL COMMENT '本人授权引用',
    request_key VARCHAR(64) COLLATE utf8mb4_bin NOT NULL COMMENT '本人确认幂等键',
    payload_hash CHAR(64) NOT NULL COMMENT 'owner重算请求指纹',
    source_key CHAR(64) NOT NULL COMMENT '含修订号的使用意图键',
    source_snapshot JSON NOT NULL COMMENT '完整SourceRef及原订单定位',
    source_revision BIGINT NOT NULL COMMENT '源意图修订',
    user_no VARCHAR(64) NOT NULL COMMENT '本人消费者',
    entity_no VARCHAR(64) NOT NULL COMMENT '资产承担主体',
    store_no VARCHAR(64) NOT NULL COMMENT '真实履约门店',
    quote_ref VARCHAR(64) NULL COMMENT 'pay短期报价或预览引用',
    selection_digest CHAR(64) NOT NULL COMMENT '绑定资产及版本金额次数服务日',
    order_snapshot_hash CHAR(64) NOT NULL COMMENT '可信源价格明细摘要',
    amount_minor BIGINT NOT NULL COMMENT '本次确认金额可为零',
    currency VARCHAR(8) NOT NULL COMMENT '币种',
    status VARCHAR(16) NOT NULL COMMENT 'AUTHORIZED/CANCELLED/EXPIRED',
    authorized_at DATETIME(3) NOT NULL COMMENT '真实本人确认时刻',
    expires_at DATETIME(3) NOT NULL COMMENT '授权截止半开区间',
    version BIGINT NOT NULL DEFAULT 0 COMMENT 'BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建时间',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新时间',
    created_by VARCHAR(64) NOT NULL COMMENT '可信操作者',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_order_auth (tenant_no,authorization_no),
    UNIQUE KEY uk_order_auth_request (tenant_no,user_no,request_key),
    KEY ix_order_auth_source (tenant_no,source_key,user_no,status),
    CHECK (source_revision>=0 AND amount_minor>=0),
    CHECK (expires_at>authorized_at),
    CHECK (status IN ('AUTHORIZED','CANCELLED','EXPIRED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='core本人授权；改价或换选择后源事务取消旧授权';

CREATE TABLE ord_ent_source_decision (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    decision_no VARCHAR(64) NOT NULL COMMENT '持久源决策引用',
    purpose VARCHAR(16) NOT NULL COMMENT 'USE/GRANT/REVERSE',
    source_key CHAR(64) NOT NULL COMMENT 'USE用useIntentKey；发放用grantKey',
    source_snapshot JSON NOT NULL COMMENT '完整SourceRef',
    settled_source_key CHAR(64) NULL COMMENT '仅成功时写稳定成功键，取消为NULL',
    source_revision BIGINT NOT NULL COMMENT '本次决策源修订',
    decision_type VARCHAR(24) NOT NULL COMMENT 'GRANT_COMMIT/GRANT_ABORT/USE_COMMIT/USE_CANCEL/ORDER_REVERSE',
    status VARCHAR(16) NOT NULL COMMENT 'COMMITTED/CANCELLED',
    authorization_ref VARCHAR(64) NULL COMMENT '使用决策绑定原本人授权',
    paid_fact_ref VARCHAR(64) NULL COMMENT '售卡真实付款事实引用',
    user_no VARCHAR(64) NOT NULL COMMENT '受益或使用本人',
    entity_no VARCHAR(64) NOT NULL COMMENT '资产主体',
    store_no VARCHAR(64) NULL COMMENT '真实门店',
    currency VARCHAR(8) NOT NULL COMMENT '币种',
    amount_minor BIGINT NOT NULL COMMENT '源真实金额非客户端报价',
    snapshot_hash CHAR(64) NOT NULL COMMENT '被冻结源事实摘要',
    occurred_at DATETIME(3) NOT NULL COMMENT '真实成功或取消时刻',
    version BIGINT NOT NULL DEFAULT 0 COMMENT 'BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建时间',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新时间',
    created_by VARCHAR(64) NOT NULL COMMENT '可信操作者',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_source_decision (tenant_no,decision_no),
    UNIQUE KEY uk_source_intent (tenant_no,purpose,source_key),
    UNIQUE KEY uk_source_settled (tenant_no,purpose,settled_source_key),
    CHECK (source_revision>=0 AND amount_minor>=0),
    CHECK ((status='CANCELLED' AND settled_source_key IS NULL
        AND ((purpose='USE' AND decision_type='USE_CANCEL') OR (purpose='GRANT' AND decision_type='GRANT_ABORT')))
        OR (status='COMMITTED' AND settled_source_key IS NOT NULL
        AND ((purpose='USE' AND decision_type='USE_COMMIT') OR (purpose='GRANT' AND decision_type='GRANT_COMMIT')
        OR (purpose='REVERSE' AND decision_type='ORDER_REVERSE'))))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='core成功取消唯一决策；同成功源跨修订不重复承诺';

CREATE TABLE ord_card_sale_snapshot (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    snapshot_no VARCHAR(64) NOT NULL COMMENT '单件权益快照号',
    source_key CHAR(64) NOT NULL COMMENT 'SourceRef.grantKey',
    order_no VARCHAR(64) NOT NULL COMMENT '主订单',
    sub_order_no VARCHAR(64) NOT NULL COMMENT '本主体子单',
    order_line_no VARCHAR(64) NOT NULL COMMENT '原订单行',
    unit_index INT NOT NULL COMMENT '从1开始的单件序号',
    entitlement_index INT NOT NULL COMMENT '从1开始的件内权益序号',
    user_no VARCHAR(64) NOT NULL COMMENT '消费者',
    entity_no VARCHAR(64) NOT NULL COMMENT '售价及资产主体',
    store_no VARCHAR(64) NOT NULL COMMENT '销售门店',
    goods_no VARCHAR(64) NOT NULL COMMENT '原商品',
    sku_no VARCHAR(64) NOT NULL COMMENT '原SKU',
    template_version_no VARCHAR(64) NOT NULL COMMENT '固定pay定义版本',
    unit_price_minor BIGINT NOT NULL COMMENT '原单件售价；多权益行不得重复统计收入',
    currency VARCHAR(8) NOT NULL COMMENT '币种',
    rule_snapshot JSON NOT NULL COMMENT '原权益定义',
    snapshot_hash CHAR(64) NOT NULL COMMENT '固定定义摘要',
    paid_fact_no VARCHAR(64) NULL COMMENT '真实支付事实后仅单向固化',
    paid_at DATETIME(3) NULL COMMENT '真实付款时间，不用事件到达时间',
    version BIGINT NOT NULL DEFAULT 0 COMMENT 'BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建时间',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新时间',
    created_by VARCHAR(64) NOT NULL COMMENT '可信操作者',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_card_sale_snapshot (tenant_no,snapshot_no),
    UNIQUE KEY uk_card_sale_source (tenant_no,source_key),
    UNIQUE KEY uk_card_sale_unit (tenant_no,order_line_no,unit_index,entitlement_index),
    KEY ix_card_sale_order (tenant_no,order_no),
    CHECK (unit_index>0 AND entitlement_index>0 AND unit_price_minor>=0),
    CHECK ((paid_fact_no IS NULL AND paid_at IS NULL) OR (paid_fact_no IS NOT NULL AND paid_at IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='core不可变售卡来源；付款事实与订单同事务关联';

CREATE TABLE pay_ent_recon_run (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    recon_no VARCHAR(64) NOT NULL COMMENT '对账批次号',
    request_key VARCHAR(64) COLLATE utf8mb4_bin NOT NULL COMMENT '调度或人工发起幂等键',
    payload_hash CHAR(64) NOT NULL COMMENT '对账参数指纹',
    entity_no VARCHAR(64) NOT NULL COMMENT '授权商家；ALL仅全域运营可用',
    axis VARCHAR(16) NOT NULL COMMENT 'ISSUANCE/RIGHTS/HOLD/MONEY',
    currency VARCHAR(8) NULL COMMENT 'MONEY必须分币种',
    biz_date DATE NOT NULL COMMENT '本地市场日',
    market_zone VARCHAR(64) NOT NULL COMMENT 'IANA时区',
    status VARCHAR(16) NOT NULL COMMENT 'RUNNING/COMPLETED/FAILED',
    scan_cursor VARCHAR(512) NULL COMMENT '重启续扫游标',
    checked_count BIGINT NOT NULL DEFAULT 0 COMMENT '已检查量',
    diff_count BIGINT NOT NULL DEFAULT 0 COMMENT '差异量',
    started_at DATETIME(3) NOT NULL COMMENT 'UTC开始',
    completed_at DATETIME(3) NULL COMMENT 'UTC完成',
    version BIGINT NOT NULL DEFAULT 0 COMMENT 'BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建时间',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新时间',
    created_by VARCHAR(64) NOT NULL COMMENT '可信操作者',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_ent_recon_no (tenant_no,recon_no),
    UNIQUE KEY uk_ent_recon_request (tenant_no,request_key),
    KEY ix_ent_recon_query (tenant_no,entity_no,biz_date,axis,id),
    CHECK (checked_count>=0 AND diff_count>=0 AND diff_count<=checked_count),
    CHECK (axis IN ('ISSUANCE','RIGHTS','HOLD','MONEY')),
    CHECK (axis<>'MONEY' OR currency IS NOT NULL),
    CHECK (status IN ('RUNNING','COMPLETED','FAILED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='pay分量纲对账批次；只记录差异不自动调平';

CREATE TABLE pay_ent_recon_diff (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    diff_no VARCHAR(64) NOT NULL COMMENT '差异号',
    recon_no VARCHAR(64) NOT NULL COMMENT '同域批次号',
    entity_no VARCHAR(64) NOT NULL COMMENT '实际差异主体',
    resource_no VARCHAR(64) NOT NULL COMMENT '账户或权益业务号',
    diff_kind VARCHAR(32) NOT NULL COMMENT '差异原因码',
    expected_snapshot JSON NOT NULL COMMENT '内部应有事实，不能直接回传页面',
    actual_snapshot JSON NOT NULL COMMENT '内部实有事实，不能直接回传页面',
    exception_no VARCHAR(64) NULL COMMENT '受控恢复关联原异常',
    status VARCHAR(16) NOT NULL COMMENT 'OPEN/ACKNOWLEDGED/RESOLVED',
    resolution_note VARCHAR(500) NULL COMMENT '处理证据，不允许余额调平',
    version BIGINT NOT NULL DEFAULT 0 COMMENT 'BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建时间',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新时间',
    created_by VARCHAR(64) NOT NULL COMMENT '可信操作者',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_ent_recon_diff (tenant_no,diff_no),
    UNIQUE KEY uk_ent_recon_resource (tenant_no,recon_no,resource_no,diff_kind),
    KEY ix_ent_recon_diff_query (tenant_no,entity_no,recon_no,status),
    CHECK (status IN ('OPEN','ACKNOWLEDGED','RESOLVED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='pay对账差异事实；恢复始终指向原操作';

