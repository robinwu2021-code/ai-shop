CREATE TABLE ent_template (
    id BIGINT NOT NULL AUTO_INCREMENT COMMENT '内部主键',
    tenant_no VARCHAR(32) NOT NULL COMMENT '租户',
    template_no VARCHAR(64) NOT NULL COMMENT '模板号，保留迁移映射',
    entity_no VARCHAR(64) NOT NULL COMMENT '商家或平台主体',
    title VARCHAR(100) NOT NULL COMMENT '标题',
    kind VARCHAR(24) NOT NULL COMMENT 'ORDER_COUPON/STORE_EXCHANGE/PAID_CARD',
    funder VARCHAR(16) NOT NULL COMMENT 'MERCHANT/PLATFORM',
    status VARCHAR(16) NOT NULL COMMENT 'DRAFT/ACTIVE/PAUSED/ENDED',
    current_version_no VARCHAR(64) NULL COMMENT '当前发布版本',
    draft_snapshot JSON NOT NULL COMMENT '可编辑草稿规则，发布时复制为不可变版本',
    archived_at DATETIME(3) NULL COMMENT '归档时间',
    version BIGINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity乐观锁',
    deleted TINYINT NOT NULL DEFAULT 0 COMMENT '对齐BaseEntity，账务事实禁止删除',
    created_at DATETIME(3) NOT NULL COMMENT 'UTC创建',
    updated_at DATETIME(3) NOT NULL COMMENT 'UTC更新',
    created_by VARCHAR(64) NOT NULL COMMENT '操作者或系统任务',
    updated_by VARCHAR(64) NOT NULL COMMENT '最后操作者',
    PRIMARY KEY (id),
    UNIQUE KEY uk_template (tenant_no,template_no),
    KEY ix_ent_templates (tenant_no,entity_no,kind,status,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='支付权益模板管理头';

