CREATE TABLE sv_campaign (
    id BIGINT NOT NULL AUTO_INCREMENT,
    tenant_no VARCHAR(32) NOT NULL,
    campaign_no VARCHAR(32) NOT NULL,
    entity_no VARCHAR(32) NOT NULL,
    name VARCHAR(100) NOT NULL,
    status VARCHAR(16) NOT NULL,
    current_version_no VARCHAR(32) NULL,
    revision INT NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_campaign (tenant_no,campaign_no),
    KEY ix_entity_status (tenant_no,entity_no,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='活动头';

