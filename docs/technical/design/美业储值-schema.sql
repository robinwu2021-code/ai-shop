CREATE TABLE sv_campaign_budget (
    id BIGINT NOT NULL AUTO_INCREMENT,
    tenant_no VARCHAR(32) NOT NULL,
    version_no VARCHAR(32) NOT NULL,
    quota_limit BIGINT NULL,
    quota_held BIGINT NOT NULL DEFAULT 0,
    quota_used BIGINT NOT NULL DEFAULT 0,
    bonus_limit_minor BIGINT NULL,
    bonus_held_minor BIGINT NOT NULL DEFAULT 0,
    bonus_used_minor BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_budget (tenant_no,version_no),
    CHECK (quota_held>=0 AND quota_used>=0 AND bonus_held_minor>=0 AND bonus_used_minor>=0),
    CHECK (quota_limit IS NULL OR quota_held+quota_used<=quota_limit),
    CHECK (bonus_limit_minor IS NULL OR bonus_held_minor+bonus_used_minor<=bonus_limit_minor)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='预算与名额锁定行，NULL上限表示不限';

CREATE TABLE sv_participation (
    id BIGINT NOT NULL AUTO_INCREMENT,
    tenant_no VARCHAR(32) NOT NULL,
    version_no VARCHAR(32) NOT NULL,
    user_no VARCHAR(32) NOT NULL,
    held_count INT NOT NULL DEFAULT 0,
    used_count INT NOT NULL DEFAULT 0,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uk_participation (tenant_no,version_no,user_no),
    CHECK (held_count>=0 AND used_count>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='并发限购计数，每活动版本与用户一行';

