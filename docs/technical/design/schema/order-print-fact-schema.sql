-- 订单所有者新增设计表，不属于打印模块；仅设计，未执行迁移。
CREATE TABLE ord_print_fact (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  tenant_no VARCHAR(32) NOT NULL,
  entity_no VARCHAR(32) NOT NULL,
  store_no VARCHAR(32) NOT NULL,
  print_fact_no VARCHAR(32) NOT NULL,
  order_no VARCHAR(32) NOT NULL,
  sub_order_no VARCHAR(32) NOT NULL,
  source_fact_key VARCHAR(64) NOT NULL COMMENT '支付确认事实+子单等规范身份摘要，不含scene',
  receipt_intent_key VARCHAR(64) NULL COMMENT '同一次收据意图只能分配一个收据scene',
  biz_revision VARCHAR(64) NOT NULL,
  scene VARCHAR(32) NOT NULL,
  trigger_type VARCHAR(32) NOT NULL,
  payload_schema_version INT NOT NULL,
  source_occurred_at DATETIME(3) NOT NULL,
  snapshot JSON NOT NULL COMMENT '子单自身商品/金额/收款分配快照，不能存整单其他店明细',
  snapshot_hash VARCHAR(64) NOT NULL,
  printability VARCHAR(16) NOT NULL COMMENT 'READY / BLOCKED，事实已留存不等于可渲染',
  block_code VARCHAR(64) NULL,
  diagnostics JSON NOT NULL COMMENT '不支持金额组成等脱敏诊断，不伪造默认金额',
  revision BIGINT NOT NULL DEFAULT 0,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  UNIQUE KEY uk_ord_print_fact_no (tenant_no, print_fact_no),
  UNIQUE KEY uk_ord_print_fact_source (tenant_no, entity_no, store_no, source_fact_key),
  UNIQUE KEY uk_ord_print_receipt_intent (tenant_no, entity_no, store_no, receipt_intent_key),
  KEY idx_ord_print_fact_order (tenant_no, entity_no, order_no, sub_order_no),
  KEY idx_ord_print_fact_scan (tenant_no, entity_no, store_no, created_at, id)
) COMMENT='订单事务内冻结的不可变打印事实';
