-- 基础能力库 n_common：建库建表。由字段数据生成，不要手改。
-- 字段是草案；保留的表带上了原表里列都还在的索引，新建的表只有主键。

CREATE DATABASE IF NOT EXISTS `n_common` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE `n_common`;

CREATE TABLE `sys_role` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `role_code` varchar(32) NOT NULL COMMENT '角色编码，同一端内唯一',
  `name` varchar(32) NOT NULL COMMENT '角色展示名',
  `end_code` varchar(8) NOT NULL COMMENT '所属端：OPS 运营端 / BIZ 商家端 / MP 小程序端',
  `builtin` tinyint NOT NULL COMMENT '是否平台预置角色：1 预置不可删 / 0 自定义',
  `wildcard` tinyint NOT NULL COMMENT '是否通配角色（超管）：1 拥有全部权限码，判权时直接放行 / 0 按授予的功能点判',
  `entity_no` varchar(32) DEFAULT NULL COMMENT '自定义该角色的商家主体编号；空 = 平台角色',
  `sort` int NOT NULL COMMENT '列表展示顺序',
  `tenant_no` varchar(32) NOT NULL COMMENT '租户编号',
  `deleted` tinyint NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 = 正常，1 = 已删除',
  `version` int NOT NULL DEFAULT 0 COMMENT '乐观锁版本号，每次修改加 1',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_role` (`end_code`, `role_code`, `entity_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='运营端角色：运营端角色';

