  `access` varchar(16) NOT NULL COMMENT '扫描得到的放行方式：PUBLIC 免登录 / LOGIN 登录即可 / POINT 需权限码 / DEFER 交由服务内判',
  `rule_text` varchar(1000) DEFAULT NULL COMMENT '权限码的与或表达式（给人读）；access=POINT 时有值',
