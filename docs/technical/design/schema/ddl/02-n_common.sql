  `app_version` varchar(32) DEFAULT NULL COMMENT '最近一次写入该行的应用版本',
  `adjusted_access` varchar(16) DEFAULT NULL COMMENT '人工调整后的放行方式（取值同 access）；空 = 用 access',
  `adjusted_rule` varchar(1000) DEFAULT NULL COMMENT '人工调整后的权限表达式，可写带范围的码；adjusted_access=POINT 时必填',
  `adjusted_by` varchar(32) DEFAULT NULL COMMENT '做调整的操作人',
  `adjusted_at` datetime DEFAULT NULL COMMENT '调整时间',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_api_resource` (`end_code`, `method`, `pattern`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='接口资源：每个接口属于哪个端、要不要登录';

