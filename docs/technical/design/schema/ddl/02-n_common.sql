CREATE TABLE `sys_api_resource` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `end_code` varchar(16) NOT NULL COMMENT '接口所属端：ops / biz / mp',
  `method` varchar(8) NOT NULL COMMENT 'HTTP 方法；* 表示不限',
  `pattern` varchar(255) NOT NULL COMMENT '接口地址模式，如 /ops/payments/refunds/{payRefundNo}/review',
  `source` varchar(16) NOT NULL COMMENT '登记来源：SCAN 启动扫描本进程入口 / MANUAL 人工录入的微服务接口',
  `location` varchar(64) NOT NULL COMMENT '接口所在位置：LOCAL 本进程或目标服务名',
