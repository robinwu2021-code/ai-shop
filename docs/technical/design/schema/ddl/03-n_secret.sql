-- 密钥库 n_secret：建库建表。由字段数据生成，不要手改。
-- 字段是草案；保留的表带上了原表里列都还在的索引，新建的表只有主键。

CREATE DATABASE IF NOT EXISTS `n_secret` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE `n_secret`;

CREATE TABLE `sec_key` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `tenant_no` varchar(32) DEFAULT NULL COMMENT '租户编号',
  `key_alias` varchar(64) DEFAULT NULL COMMENT '密钥别名，供业务表引用和人识别，唯一',
  `namespace` varchar(24) DEFAULT NULL COMMENT '命名空间：PAY / LOGISTICS / INVENTORY / NOTIFY / PRINT / PLATFORM',
  `name` varchar(128) DEFAULT NULL COMMENT '名称（给人看，这把钥匙给了谁）',
  `owner_type` varchar(24) DEFAULT NULL COMMENT '归属类型：PAY_MERCHANT 收款商户调渠道 / CHANNEL_PLATFORM 渠道平台公钥 / PARTNER_APP 第三方应用 / INTERNAL_APP 内部系统 / TERMINAL 刷卡机 / PRINTER 云打印机 / OPS_STAFF 运营人员接口密钥 / PROVIDER 其他外部服务商',
  `owner_id` bigint DEFAULT NULL COMMENT '归属对象 id（同库或存量引用）',
  `owner_no` varchar(32) DEFAULT NULL COMMENT '归属对象业务编号（跨库引用用它），如开放应用号、运营 staff_no、打印机编号',
  `counterparty` varchar(32) DEFAULT NULL COMMENT '对端系统码：NEWEBPAY / LINEPAY / PAYBY / WECHAT / ALIPAY / KUAIDI100 / YITEPAY 等',
  `external_account_ref` varchar(100) DEFAULT NULL COMMENT '对端账户标识，如渠道商户号 MID',
  `direction` varchar(24) DEFAULT NULL COMMENT '使用方向：OUTBOUND 我方调外部 / INBOUND 外部调我方时验证 / COUNTERPARTY_VERIFY 验对端响应与回调',
  `key_usage` varchar(24) DEFAULT NULL COMMENT '用途：SIGN 签名 / VERIFY 验签 / HMAC / ENCRYPT 加解密 / MTLS 双向证书 / API_KEY 接口密钥 / ACCESS_TOKEN 访问令牌',
  `algorithm` varchar(32) DEFAULT NULL COMMENT '算法：HMAC_SHA256 / RSA_SHA256 / AES_256_GCM / ECDSA_P256 等',
  `material_type` varchar(24) DEFAULT NULL COMMENT '材料类型：SYMMETRIC_SECRET / PRIVATE_KEY / PUBLIC_KEY / CERTIFICATE / COMPOSITE（如蓝新 HashKey+HashIV）/ TOKEN',
  `access_level` varchar(16) DEFAULT NULL COMMENT '接口密钥的权限级别：READ 只读 / WRITE 读写（运营人员接口密钥用）',
  `env` varchar(24) DEFAULT NULL COMMENT '环境：SANDBOX / PRODUCTION，生产密钥永不进入沙箱',
  `status` varchar(10) DEFAULT NULL COMMENT '状态：DRAFT 草稿 / ACTIVE 生效 / SUSPENDED 暂停 / REVOKED 吊销 / EXPIRED 过期',
  `current_version` int DEFAULT NULL COMMENT '当前生效版本号；0 = 尚无',
  `sec_key_policy_id` bigint DEFAULT NULL COMMENT '适用策略 sec_key_policy.id；空 = 按命名空间 + 归属类型 + 环境取默认',
  `origin_ref` varchar(96) DEFAULT NULL COMMENT '密钥的来源单据，如进件单号（蓝新进件返回的商户密钥）',
  `evidence_ref` varchar(255) DEFAULT NULL COMMENT '登记或核验证明的文件引用',
  `expires_at` datetime(3) DEFAULT NULL COMMENT '当前版本到期时间（证书有效期或策略最长使用期取早者）',
  `last_used_at` datetime(3) DEFAULT NULL COMMENT '最近使用时间（异步刷新）',
  `use_count` bigint DEFAULT NULL COMMENT '累计使用次数（异步累加，近似值）',
  `deleted` tinyint NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 = 正常，1 = 已删除',
  `version` int NOT NULL DEFAULT 0 COMMENT '乐观锁版本号，每次修改加 1',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  KEY `idx_sec_key_1` (`status`, `expires_at`),
  KEY `idx_sec_key_2` (`counterparty`, `status`),
  KEY `uk_sec_key_1` (`namespace`, `owner_type`, `owner_id`, `direction`, `key_usage`, `env`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='密钥：属于谁、做什么用、当前哪一版；渠道凭据、开放应用的签名密钥、运营人员的接口密钥、打印与通知的凭据都是其中一种';

CREATE TABLE `sec_key_version` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `sec_key_id` bigint DEFAULT NULL COMMENT '所属密钥 sec_key.id',
  `version_index` int DEFAULT NULL COMMENT '版本号，从 1 起；交易冻结的是这个号',
  `status` varchar(10) DEFAULT NULL COMMENT '版本状态：DRAFT 已录入 / VERIFIED 测试通过 / ACTIVE 当前 / ROTATING 重叠期仍可用 / RETIRED 仅验旧签与在途单 / QUERY_ONLY 仅查询 / REVOKED 立即失效',
  `active_key` varchar(32) DEFAULT NULL COMMENT 'ACTIVE 时等于 sec_key_id，保证一把密钥同一时刻只有一个生效版本',
  `sec_secret_blob_id` bigint DEFAULT NULL COMMENT '私密材料的密文 sec_secret_blob.id（对称密钥、私钥、令牌）',
  `secret_hash` char(64) DEFAULT NULL COMMENT '只需比对不需还原的密钥（运营接口密钥、AppSecret）的哈希；不存明文',
  `public_material` text NULL COMMENT '公钥或证书 PEM（可公开，不加密）',
  `fingerprint` varchar(64) DEFAULT NULL COMMENT '材料指纹，唯一可回显的信息',
  `external_key_id` varchar(64) DEFAULT NULL COMMENT '外部密钥标识：微信平台证书序列号、PayBy 公钥 ID、接入方 key id',
  `source` varchar(24) DEFAULT NULL COMMENT '来源：GENERATED 平台生成 / UPLOADED 人工录入 / FETCHED 从对端下载 / ONBOARDING 进件返回',
  `storage_tier` varchar(8) DEFAULT NULL COMMENT '存放等级：L1 配置明文 / L2 库 + 注入主密钥 / L3 库 + KMS 主密钥 / L4 外部密钥服务 / L5 KMS·HSM 不可导出',
  `display_prefix` varchar(16) DEFAULT NULL COMMENT '只用于显示的前缀，如 sk_live_ / sk_test_，不参与运算',
  `valid_from` datetime(3) DEFAULT NULL COMMENT '生效起（证书 notBefore）',
  `valid_to` datetime(3) DEFAULT NULL COMMENT '生效止（证书 notAfter 或策略最长使用期）',
  `entered_by` varchar(32) DEFAULT NULL COMMENT '录入或生成人',
  `verified_by` varchar(32) DEFAULT NULL COMMENT '测试核验人',
  `verified_at` datetime(3) DEFAULT NULL COMMENT '测试调用通过时间',
  `verify_evidence` varchar(128) DEFAULT NULL COMMENT '测试调用证据引用，如 PAY:pay_channel_call_log:123',
  `enabled_by` varchar(32) DEFAULT NULL COMMENT '启用人，必须不同于录入人',
  `enabled_at` datetime(3) DEFAULT NULL COMMENT '启用时间',
  `overlap_until` datetime(3) DEFAULT NULL COMMENT '轮换后旧版本仍可用至',
  `retired_at` datetime(3) DEFAULT NULL COMMENT '退役时间',
  `revoked_by` varchar(32) DEFAULT NULL COMMENT '吊销人',
  `revoked_at` datetime(3) DEFAULT NULL COMMENT '吊销时间',
  `revoke_reason` varchar(255) DEFAULT NULL COMMENT '吊销原因（泄露、离职、商户解约等）',
  `deleted` tinyint NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 = 正常，1 = 已删除',
  `version` int NOT NULL DEFAULT 0 COMMENT '乐观锁版本号，每次修改加 1',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  KEY `idx_sec_key_version_1` (`sec_key_id`, `status`),
  KEY `idx_sec_key_version_2` (`external_key_id`),
  KEY `idx_sec_key_version_3` (`status`, `valid_to`),
  KEY `uk_sec_key_version_1` (`sec_key_id`, `version_index`),
  KEY `uk_sec_key_version_2` (`active_key`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='密钥的版本：每次轮换一版';

CREATE TABLE `sec_secret_blob` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `blob_no` varchar(32) DEFAULT NULL COMMENT '密文句柄号，业务方（如渠道对接的证书）引用它',
  `tenant_no` varchar(32) DEFAULT NULL COMMENT '租户编号',
  `namespace` varchar(24) DEFAULT NULL COMMENT '命名空间，同 sec_master_key.namespace',
  `purpose` varchar(24) DEFAULT NULL COMMENT '用途：KEY_MATERIAL 密钥材料 / SENSITIVE_FIELD 敏感字段（证件号、银行账号）/ CERTIFICATE 证书',
  `owner_type` varchar(24) DEFAULT NULL COMMENT '归属对象类型：KEY_VERSION / ONBOARDING_MATERIAL / CIM_CONNECTION 等',
  `owner_id` bigint DEFAULT NULL COMMENT '归属对象 id（sec_key_version.id 等同库对象）',
  `owner_ref` varchar(64) DEFAULT NULL COMMENT '跨库归属对象编号，如渠道连接号、进件材料号',
  `env` varchar(24) DEFAULT NULL COMMENT '环境：SANDBOX / PRODUCTION',
  `cipher_text` text NULL COMMENT 'AES-256-GCM 密文（Base64，含 IV 与认证标签）',
  `data_key_cipher` varchar(512) DEFAULT NULL COMMENT '被主密钥包裹的数据密钥',
  `sec_master_key_id` bigint DEFAULT NULL COMMENT '包裹所用主密钥 sec_master_key.id',
  `algorithm` varchar(32) DEFAULT NULL COMMENT '加密算法，如 AES-256-GCM',
  `aad_sha256` char(64) DEFAULT NULL COMMENT '附加认证数据摘要，密文被挪到别的行即解密失败',
  `status` varchar(10) DEFAULT NULL COMMENT '密文状态：ACTIVE 可用 / REVOKED 已作废',
  `rewrapped_at` datetime(3) DEFAULT NULL COMMENT '最近一次主密钥轮换后重新包裹的时间',
  `deleted` tinyint NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 = 正常，1 = 已删除',
  `version` int NOT NULL DEFAULT 0 COMMENT '乐观锁版本号，每次修改加 1',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  KEY `idx_sec_secret_blob_1` (`namespace`, `owner_type`, `owner_id`),
  KEY `idx_sec_secret_blob_2` (`sec_master_key_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='密文：加密后的密钥、凭据内容';

CREATE TABLE `sec_master_key` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `kms_key_id` varchar(128) NOT NULL COMMENT 'KMS 密钥 id 或环境注入别名（是名字，不是密钥）',
  `provider` varchar(24) NOT NULL COMMENT '主密钥来源：ENV 部署注入 / KMS 云 KMS / HSM 硬件',
  `namespace` varchar(24) NOT NULL COMMENT '命名空间：PAY / LOGISTICS / INVENTORY / NOTIFY / PLATFORM，每域一套主密钥',
  `env` varchar(24) NOT NULL COMMENT '环境：SANDBOX / PRODUCTION，两套主密钥必须不同',
  `status` varchar(10) NOT NULL COMMENT '状态：ACTIVE 用于新加密 / DEC_ONLY 只解密 / RETIRED 已无密文引用',
  `active_key` varchar(48) DEFAULT NULL COMMENT 'ACTIVE 时等于 namespace|env，保证每命名空间每环境只有一个生效主密钥',
  `activated_at` datetime(3) DEFAULT NULL COMMENT '启用时间',
  `rotated_at` datetime(3) DEFAULT NULL COMMENT '被新主密钥替换的时间',
  `retired_at` datetime(3) DEFAULT NULL COMMENT '退役时间（全部密文已重新包裹）',
  `deleted` tinyint NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 = 正常，1 = 已删除',
  `version` int NOT NULL DEFAULT 0 COMMENT '乐观锁版本号，每次修改加 1',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_sec_master_key_1` (`kms_key_id`),
  UNIQUE KEY `uk_sec_master_key_2` (`active_key`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='主密钥：加密其他密钥用';

CREATE TABLE `sec_key_policy` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `namespace` varchar(24) NOT NULL COMMENT '命名空间',
  `owner_type` varchar(24) NOT NULL COMMENT '归属类型：PAY_MERCHANT / CHANNEL_PLATFORM / PARTNER_APP / INTERNAL_APP / TERMINAL / PRINTER / OPS_STAFF / PROVIDER',
  `env` varchar(24) NOT NULL COMMENT '环境：SANDBOX / PRODUCTION',
  `max_age_days` int NOT NULL COMMENT '版本最长使用天数；0 = 不强制，以证书有效期为准',
  `warn_before_days` int NOT NULL COMMENT '到期前多少天提醒',
  `overlap_days` int NOT NULL COMMENT '轮换重叠期：新版本启用后旧版本仍可用的天数',
  `dual_control` tinyint(1) NOT NULL COMMENT '启用、吊销是否需要两人：1 需要',
  `verify_before_enable` tinyint(1) NOT NULL COMMENT '启用前是否必须测试调用通过：1 必须',
  `reveal_on_issue_only` tinyint(1) NOT NULL COMMENT '平台生成的密钥明文是否只在发放时展示一次：1 是',
  `deleted` tinyint NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 = 正常，1 = 已删除',
  `version` int NOT NULL DEFAULT 0 COMMENT '乐观锁版本号，每次修改加 1',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_sec_key_policy_1` (`namespace`, `owner_type`, `env`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='密钥策略：多久轮换、是否双人控制';

CREATE TABLE `sec_key_event` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `sec_key_id` bigint NOT NULL COMMENT '密钥 sec_key.id',
  `sec_key_version_id` bigint DEFAULT NULL COMMENT '版本 sec_key_version.id；密钥级事件为空',
  `event_type` varchar(24) NOT NULL COMMENT '事件类型：CREATED 创建 / MATERIAL_ADDED 录入材料 / VERIFIED 测试通过 / VERIFY_FAILED 测试失败 / ENABLED 启用 / ROTATION_STARTED 开始轮换 / RETIRED 退役 / REVOKED 吊销 / SUSPENDED 暂停 / RESUMED 恢复 / EXPIRING_SOON 即将到期 / EXPIRED 已到期 / REWRAPPED 重新包裹',
  `operator_type` varchar(24) NOT NULL COMMENT '操作者类型：OPS 运营 / BIZ 商家 / SYSTEM 系统任务',
  `operator_no` varchar(32) NOT NULL COMMENT '操作人编号',
  `approval_ref` varchar(128) DEFAULT NULL COMMENT '两人复核证据：复核或审批单号引用',
  `reason` varchar(255) DEFAULT NULL COMMENT '原因',
  `client_ip` varchar(64) DEFAULT NULL COMMENT '操作来源 IP',
  `occurred_at` datetime(3) NOT NULL COMMENT '发生时间',
  `deleted` tinyint NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 = 正常，1 = 已删除',
  `version` int NOT NULL DEFAULT 0 COMMENT '乐观锁版本号，每次修改加 1',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  KEY `idx_sec_key_event_1` (`sec_key_id`, `occurred_at`),
  KEY `idx_sec_key_event_2` (`event_type`, `occurred_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='密钥事件：生成、启用、轮换、吊销';

