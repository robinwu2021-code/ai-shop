-- 任务库 n_job：建库建表。由字段数据生成，不要手改。
-- 字段是草案；保留的表带上了原表里列都还在的索引，新建的表只有主键。

CREATE DATABASE IF NOT EXISTS `n_job` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE `n_job`;

CREATE TABLE `job_definition` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `job_name` varchar(64) NOT NULL COMMENT '任务名，唯一',
  `display_name` varchar(64) NOT NULL COMMENT '任务展示名',
  `description` varchar(255) DEFAULT NULL COMMENT '任务说明',
  `handler_name` varchar(64) NOT NULL COMMENT '执行处理器名',
  `target` varchar(16) NOT NULL COMMENT '执行目标：LOCAL 本进程 / HTTP 调用微服务',
  `params` text NULL COMMENT '任务参数 JSON',
  `cron` varchar(64) NOT NULL COMMENT '执行周期 cron 表达式',
  `enabled` tinyint NOT NULL COMMENT '是否启用：1 启用 / 0 停用',
  `timeout_sec` int NOT NULL COMMENT '单次运行超时秒数',
  `lock_at_most_sec` int NOT NULL COMMENT '单次运行最长占用时长（秒），超过视为卡死可被重跑',
  `manual_trigger` tinyint NOT NULL COMMENT '是否允许运营手动触发：1 允许',
  `log_every_run` tinyint NOT NULL COMMENT '是否每次运行都写运行记录：1 是 / 0 只记失败与有产出的',
  `source` varchar(8) NOT NULL COMMENT '定义来源：CODE 代码声明 / OPS 运营录入',
  `missing` tinyint NOT NULL COMMENT '代码里已找不到该任务：1 是，只标记不删',
  `owner_module` varchar(32) DEFAULT NULL COMMENT '负责模块',
  `trigger_requested_at` datetime DEFAULT NULL COMMENT '运营请求手动触发的时间，worker 读到后执行',
  `last_triggered_at` datetime DEFAULT NULL COMMENT '最近一次手动触发被执行的时间',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  KEY `idx_job_def_handler` (`handler_name`),
  UNIQUE KEY `uk_job_def_name` (`job_name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='任务定义：任务定义';

CREATE TABLE `job_run` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `job_name` varchar(64) DEFAULT NULL COMMENT '任务名，每任务一行',
  `last_run_at` datetime DEFAULT NULL COMMENT '最近一次开始运行时间',
  `last_status` varchar(10) DEFAULT NULL COMMENT '最近一次结果：OK 成功 / FAILED 失败 / TIMEOUT 超时 / SKIPPED 跳过',
  `duration_ms` bigint DEFAULT NULL COMMENT '最近一次耗时（毫秒）',
  `detail` varchar(500) DEFAULT NULL COMMENT '最近一次做了什么，如「投出 12 条」「关单 3 单」',
  `error` varchar(500) DEFAULT NULL COMMENT '最近一次失败原因',
  `consecutive_failures` int DEFAULT NULL COMMENT '连续失败次数',
  `run_count` bigint DEFAULT NULL COMMENT '累计运行轮数',
  `next_run_at` datetime DEFAULT NULL COMMENT '下次计划运行时间',
  `running` tinyint DEFAULT NULL COMMENT '是否正在运行：1 是',
  `current_run_id` varchar(40) DEFAULT NULL COMMENT '正在运行的那次运行号，指向 job_log.run_id',
  `running_instance` varchar(255) DEFAULT NULL COMMENT '正在运行它的实例标识（主机名）',
  `running_since` datetime(3) DEFAULT NULL COMMENT '本次开始占用的时间',
  `running_until` datetime(3) DEFAULT NULL COMMENT '本次占用最长到何时，到点后其他实例可接手',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  KEY `uk_job_run_name` (`job_name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='任务现状：任务现状';

CREATE TABLE `job_log` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `run_id` varchar(40) DEFAULT NULL COMMENT '运行号，唯一',
  `job_name` varchar(64) DEFAULT NULL COMMENT '任务名',
  `tenant_no` varchar(32) DEFAULT NULL COMMENT '租户编号；平台级任务为空',
  `run_type` varchar(32) DEFAULT NULL COMMENT '运行类别：SCHEDULED 定时任务 / CATALOG_SYNC 渠道商品同步 / AVAILABILITY_PUBLISH 渠道可售发布 / CATALOG_SNAPSHOT 目录快照 / MEDIA_PURGE 图片回收',
  `trigger_type` varchar(16) DEFAULT NULL COMMENT '触发方式：SCHEDULE 定时 / MANUAL 人工 / EVENT 事件触发 / RECOVERY 补偿',
  `scope_type` varchar(16) DEFAULT NULL COMMENT '处理范围类型：STORE 门店 / CONNECTION 渠道连接 / ENTITY 主体；全平台为空',
  `entity_no` varchar(32) DEFAULT NULL COMMENT '处理范围所属商家主体编号',
  `scope_no` varchar(32) DEFAULT NULL COMMENT '处理范围编号，如门店号、渠道连接号',
  `source_ref` varchar(128) DEFAULT NULL COMMENT '触发来源引用，如触发的事件号',
  `biz_date` date DEFAULT NULL COMMENT '处理的业务日期',
  `operator_no` varchar(32) DEFAULT NULL COMMENT '人工触发的操作人',
  `operator_name` varchar(64) DEFAULT NULL COMMENT '人工触发的操作人姓名快照',
  `started_at` datetime DEFAULT NULL COMMENT '开始时间',
  `finished_at` datetime DEFAULT NULL COMMENT '结束时间',
  `duration_ms` bigint DEFAULT NULL COMMENT '耗时（毫秒）',
  `status` varchar(10) DEFAULT NULL COMMENT '结果：QUEUED 排队 / RUNNING 运行中 / OK 成功 / PARTIAL 部分成功 / FAILED 失败',
  `total_count` int DEFAULT NULL COMMENT '本次应处理条数',
  `success_count` int DEFAULT NULL COMMENT '成功条数',
  `failed_count` int DEFAULT NULL COMMENT '失败条数',
  `total_bytes` bigint DEFAULT NULL COMMENT '处理的数据量（字节），如回收的图片总大小',
  `result_ref` varchar(256) DEFAULT NULL COMMENT '产出引用，如快照文件、外部发布证据',
  `detail` varchar(500) DEFAULT NULL COMMENT '这一轮做了什么',
  `error_code` varchar(32) DEFAULT NULL COMMENT '失败错误码',
  `error` varchar(500) DEFAULT NULL COMMENT '失败原因',
  `next_recovery_at` datetime(3) DEFAULT NULL COMMENT '失败后计划补偿时间',
  `worker_instance` varchar(32) DEFAULT NULL COMMENT '执行实例标识',
  `http_status` int DEFAULT NULL COMMENT '调用微服务时对方返回的 HTTP 状态',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`),
  KEY `idx_job_log_name_time` (`job_name`, `started_at`),
  KEY `idx_job_log_started` (`started_at`),
  KEY `uk_job_log_run` (`run_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='运行记录：每次运行一行';

CREATE TABLE `job_cursor` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
  `tenant_no` varchar(32) DEFAULT NULL COMMENT '租户编号',
  `job_name` varchar(64) DEFAULT NULL COMMENT '所属任务名，指向 job_definition.job_name',
  `scope_type` varchar(16) DEFAULT NULL COMMENT '游标范围类型：GLOBAL 全局 / STORE 门店 / SOURCE 来源 / QUEUE 队列',
  `scope_no` varchar(128) DEFAULT NULL COMMENT '游标范围编号，如门店号、来源类型、队列名；GLOBAL 为空',
  `entity_no` varchar(32) DEFAULT NULL COMMENT '范围所属商家主体编号',
  `store_no` varchar(32) DEFAULT NULL COMMENT '范围所属门店编号',
  `watermark_seq` bigint DEFAULT NULL COMMENT '按序号推进时已处理到的序号',
  `watermark_at` datetime(3) DEFAULT NULL COMMENT '按时间推进时已处理到的时间点',
  `watermark_no` varchar(200) DEFAULT NULL COMMENT '按业务号推进时已处理到的最后一个编号，如子订单号',
  `overlap_seconds` int DEFAULT NULL COMMENT '每次回看的重叠秒数，防止漏掉迟到的数据',
  `last_full_scan_at` datetime(3) DEFAULT NULL COMMENT '最近一次全量扫描时间',
  `last_success_at` datetime(3) DEFAULT NULL COMMENT '最近一次成功推进时间',
  `last_error_code` varchar(32) DEFAULT NULL COMMENT '最近一次推进失败的错误码',
  `status` varchar(10) DEFAULT NULL COMMENT '游标状态：ACTIVE 正常推进 / PAUSED 暂停 / FAILED 失败待处理',
  `version` int NOT NULL DEFAULT 0 COMMENT '乐观锁版本号，每次修改加 1',
  `created_at` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `created_by` varchar(32) DEFAULT NULL COMMENT '创建人',
  `updated_at` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间，每次修改自动更新',
  `updated_by` varchar(32) DEFAULT NULL COMMENT '更新人',
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='任务游标：任务游标';
