/**
 * 微信「小程序购物订单」跳回详情页时带的是**支付单号**，不是订单号。
 *
 * 平台侧的规则是：订单详情 path 里写 `${商品订单号}`，微信把它替换成
 * 预下单时填的 `out_trade_no`。而我们的 `out_trade_no` 不总等于订单号 ——
 * 一笔单关掉重试会换号，第二次起带后缀：
 *
 * ```
 * ORD123      第一次
 * ORD123-2    重试
 * ORD123-3    再重试
 * ```
 *
 * （规则在 `PaymentLedgerServiceImpl.open` 的注释里，后缀从 -2 起。）
 *
 * 不还原的话，**付款重试过的那些单从微信点进来是一片空** ——
 * 外壳还在、标题也对，只是什么都拉不到，看起来像后端挂了。
 * 而「能把订单找回来」正是这个功能存在的全部理由。
 */
export function orderNoOf(raw: string | undefined | null): string {
  /*
   * 只去掉**结尾**的 `-数字`。订单号自身是 `BizKey` 生成的纯数字串、不含短横，
   * 所以这个还原不会误伤真订单号 —— 一旦哪天订单号规则变了带上短横，
   * order-no.test.ts 里那条「真订单号原样返回」会先红。
   */
  return (raw || "").replace(/-\d+$/, "");
}
