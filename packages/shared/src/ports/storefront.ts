// 端能力：C 端**门面上允许出现什么**。
//
// 与其它 port 不同，这里的差异不是「这个端做不做得到」，而是
// **「这个端的商店/应用市场允不允许它出现」** —— 同一份代码，
// 在 App 与 H5 上是正常功能，在小程序里会让整包过不了审。
//
// 放这儿而不是 `FEATURES`：那张表是**产品还没上线**的开关（积分、卡包、群发），
// 一期不上就是三端都不上。而这一条是**上了，但某个端不许露** ——
// 两件事混在一张表里，下次有人想「把积分开出来」会连带把这条也翻了。
//
// **页面不写 `#ifdef`**（规范约束），只问这里。

/**
 * 「商家入驻」入口能不能出现。
 *
 * <p><b>小程序上不出现。</b>微信按类目审小程序：以自营类目提交的包里出现
 * 「招商 / 入驻 / 商家申请」这类内容，会被判为**平台型经营**而驳回 ——
 * 平台型要另外的资质（见 [小程序上线指南](../../../../docs/technical/design/小程序上线指南.md) §一）。
 *
 * <p>入口藏起来而不是把代码摘掉：申请表、后端接口、运营端的审核流程都还在，
 * 拿到平台类目之后改这一处就露出来，不用重新走一遍发布。
 *
 * <p>⚠️ **不要把它挪进 `FEATURES` 顺手关成 false** —— 那样 App 与 H5 上
 * 这个入口也一起没了，而那两个端从来没有这个限制。
 */
export function merchantApplyVisible(): boolean {
  // #ifdef MP-WEIXIN
  return false;
  // #endif
  // #ifndef MP-WEIXIN
  return true;
  // #endif
}
