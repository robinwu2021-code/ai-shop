import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createPortal } from '../app.mjs';

test('live Markdown, nested Chinese navigation, relative links, SEO and deletion', { timeout: 15000 }, async (t) => {
  const dir = await mkdtemp(path.join(tmpdir(), 'neargo-docs-'));
  await mkdir(path.join(dir, '支付', '退款'), { recursive: true });
  await mkdir(path.join(dir, '支付', 'images'));
  await writeFile(path.join(dir, '支付', 'images', 'flow.svg'), '<svg xmlns="http://www.w3.org/2000/svg"><title>流程图</title></svg>');
  await writeFile(path.join(dir, 'index.md'), '# 接入首页');
  const app = createPortal({ contentDir: dir, siteUrl: 'http://developers.neargo.example' });
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await rm(dir, { recursive: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const get = async (route) => { const r = await fetch(base + route); return { status: r.status, body: decodeURI((await r.text()).replaceAll('&#x2F;', '/')) }; };
  assert.match((await get('/')).body, /接入首页/);
  const file = path.join(dir, '支付', '退款', '接入.md');
  await writeFile(file, '---\nTitle: 退款接入\nDescription: 退款文档摘要\n---\n# 退款接入\n\n第一版正文\n\n[签名](../签名.md#规则)\n\n![示意](../images/flow.svg)\n\n## 参数\n\n| 名称 | 说明 |\n| --- | --- |\n| orderNo | 订单号 |\n');
  await writeFile(path.join(dir, '支付', '签名.md'), '# 签名规则');
  let page = await get('/' + encodeURI('支付/退款/接入'));
  assert.equal(page.status, 200);
  assert.match(page.body, /第一版正文/);
  assert.match(page.body, /<title>退款接入/);
  assert.match(page.body, /name="description" content="退款文档摘要"/);
  assert.match(page.body, /rel="canonical"/);
  assert.match(page.body, /href="[^" ]*签名#规则"/);
  assert.match(page.body, /<table>/);
  const link = page.body.match(/href="([^"]*签名#规则)"/)[1];
  const linked = await fetch(new URL(link, base + '/支付/退款/接入'));
  assert.equal(linked.status, 200);
  assert.match(await linked.text(), /签名规则/);
  assert.match((await get('/' + encodeURI('支付/images/flow.svg'))).body, /流程图/);
  assert.equal((await get('/missing.js')).status, 404);
  assert.equal((await get('/' + encodeURI('支付/签名/edit'))).status, 404);
  assert.match(page.body, /支付/);
  assert.match(page.body, /退款/);
  assert.match(page.body, /href="[^" ]*支付\/退款\/接入"/);
  await writeFile(file, '# 修改后标题\n\n第二版正文');
  assert.match((await get('/' + encodeURI('支付/退款/接入'))).body, /第二版正文/);
  const map = await get('/sitemap.xml');
  assert.equal(map.status, 200);
  assert.match(map.body, /<loc>http:\/\/developers.neargo.example\/<\/loc>/);
  assert.doesNotMatch(map.body, /https:|\/index<\/loc>/);
  await writeFile(path.join(dir, '支付', 'v1.0.md'), '# 版本文档');
  const version = await get('/' + encodeURI('支付/v1.0'));
  assert.equal(version.status, 200);
  assert.match(version.body, /版本文档/);
  assert.match(version.body, /http:\/\/developers.neargo.example\/支付\/v1.0/);
  assert.match(map.body, /http:\/\/developers.neargo.example/);
  assert.match((await get('/robots.txt')).body, /Sitemap: http:\/\/developers.neargo.example\/sitemap.xml/);
  assert.match((await get('/?search=' + encodeURIComponent('第二版'))).body, /class="result"/);
  await rm(file);
  assert.equal((await get('/' + encodeURI('支付/退款/接入'))).status, 404);
  assert.doesNotMatch((await get('/')).body, /支付\/退款\/接入/);
  assert.equal((await get('/missing')).status, 404);
});
