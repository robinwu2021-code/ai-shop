def cell(value):
    return str(value).replace('|', '&#124;').replace('\n', '<br>')


def anchor(name):
    return 'table-' + name.replace('_', '-')


def source_fields():
    result = {}
    for m in re.finditer(r'^### [3-7]\.\d+ `([^`]+)` [^\n]+\n\n字段：([^\n]+)', SOURCE.read_text(), re.M):
        result[m[1]] = [x.split()[0] for x in re.findall(r'`([^`]+)`', m[2])]
    return result


def keys(table):
    line = table.get('constraints_markdown', '').split('\n')[0]
    return re.findall(r'`\(([^`]+)\)`', line.split('索引')[0]) if line.startswith('唯一键') else []


def validate(data):
    tables = data['tables']; by = {t['name']: t for t in tables}
    assert len(tables) == len(by) == 33, '必须恰好33张候选表'
    source = source_fields()
    assert set(source) == set(by), '设计真源表清单不一致'
    common = data['common_field_names']
    assert common == ['id','tenant_no','created_at','updated_at','created_by','updated_by','version','deleted'], '通用字段必须与设计真源/BaseEntity一致'
    for name, table in by.items():
        names = [f['name'] for f in table['fields']]
        assert len(names) == len(set(names)), f'{name}有重复字段'
        assert names == common + source[name], f'{name}业务字段或通用字段覆盖不一致'
        for f in table['fields']:
            for k in ['name','type','label','write_source','description','design_basis']:
                assert f.get(k), f'{name}.{f["name"]}缺少{k}'
            assert isinstance(f['nullable'], bool)
            assert re.fullmatch(r'(BIGINT|INT|TINYINT|DATETIME|TEXT|JSON|VARCHAR\(\d+\))',f['type']), f['type']
    all_entities = dict(by); all_entities.update({x['name']:x for x in data['existing_tables']})
    for r in data['relations']:
        for entity, cols in [(r['parent'],r['parent_key']),(r['child'],r['child_key'])]:
            assert entity in all_entities, f'关系端点不存在：{entity}'
            if entity in by:
                fields = {f['name'] for f in by[entity]['fields']}
                assert all(x.strip() in fields for x in cols.split(',')), f'{entity}.{cols}不存在'
        assert r['kind'] in ('key','conditional'), '多态/JSON来源不能伪装成确定逻辑键关系'
    assert len({t['domain'] for t in tables}) == 5
    assert sum(len(t['fields']) - len(common) for t in tables) == 357, '业务字段必须为337+20=357'
    assert sum(len(t['fields']) for t in tables) == 621, '展开字段必须为357+33*8=621'
    assert sum(t['domain']=='reliability' for t in tables) == 4, '可靠性域必须为4张'
    assert len(data['existing_tables']) == 7, '保留既有表必须为7张'
    return by, all_entities


def mermaid(entities, relations):
    # 别名兼容ER图中英文表名；字段列表仅显示主键/自然键/关联键，完整字段见字典。
    out = ['%% Generated by scripts/gen-industry-plan-mall-docs.py; design only, not production DDL.',
           '%% All natural keys and references include tenant_no. JSON/polymorphic provenance is not an FK.',
           'erDiagram', '    direction LR']
    for name, table in entities.items():
        label = table['label'].replace('"','')
        out.append(f'    {name}["{name} · {label}"] {{')
        fields = {'id':'BIGINT','tenant_no':'VARCHAR_32'}
        if 'fields' in table:
            key_names = set()
            for k in keys(table):key_names.update(x.strip() for x in k.split(','))
            for r in relations:
                if r['parent'] == name:key_names.update(x.strip() for x in r['parent_key'].split(','))
                if r['child'] == name:key_names.update(x.strip() for x in r['child_key'].split(','))
            for f in table['fields']:
                if f['name'] in key_names:
                    fields[f['name']] = re.sub(r'[()]','_',f['type']).rstrip('_')
        elif table.get('key'):fields[table['key']] = 'BIGINT' if table['key']=='id' else 'VARCHAR_64'
        for f,typ in fields.items():
            tag = ' PK' if f=='id' else ''
            out.append(f'        {typ} {f}{tag}')
        out.append('    }')
    for r in relations:
        left, right = r['cardinality'].split(' → ')
        edge_left = '|o' if left=='0..1' else '||'
        edge_right = 'o|' if right=='0..1' else 'o{'
        style = '..' if r['kind']=='conditional' else '--'
        label = f"tenant_no + {r['parent_key']} = {r['child_key']}"
        if r['note']:label += '; '+r['note']
        out.append(f'    {r["parent"]} {edge_left}{style}{edge_right} {r["child"]} : "{label}"')
    return '\n'.join(out)+'\n'


class Svg:
    def __init__(self,width,height,title):
        self.out=[f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-label="{html.escape(title)}">',
                  f'<title>{html.escape(title)}</title>',
                  '<defs><marker id="arrow" markerWidth="10" markerHeight="8" refX="9" refY="4" orient="auto"><path d="M0,0 L10,4 L0,8" fill="#50657c"/></marker></defs>',
                  f'<rect width="{width}" height="{height}" fill="#f5f7fb"/>']
    def rect(self,x,y,w,h,fill='#fff',stroke='#d9e1ec',radius=12):
        self.out.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{radius}" fill="{fill}" stroke="{stroke}"/>')
    def text(self,x,y,txt,size=18,fill='#24364b',weight='normal',align='start'):
        self.out.append(f'<text x="{x}" y="{y}" font-family="{FONT}" font-size="{size}" fill="{fill}" font-weight="{weight}" text-anchor="{align}">{html.escape(txt)}</text>')
    def arrow(self,x1,y1,x2,y2,dashed=False):
        dash=' stroke-dasharray="6 5"' if dashed else ''
        self.out.append(f'<path d="M{x1} {y1} L{x2} {y2}" fill="none" stroke="#50657c" stroke-width="2" marker-end="url(#arrow)"{dash}/>')
    def finish(self):return '\n'.join(self.out+['</svg>'])+'\n'


