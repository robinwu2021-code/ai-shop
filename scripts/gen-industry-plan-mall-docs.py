def outputs(data,all_entities):
    result={DOC:document(data)}
    result[DIAGRAMS/'industry-plan-mall-global.mmd']=mermaid(all_entities,data['relations'])
    result[DIAGRAMS/'industry-plan-mall-global.svg']=overview_svg(data,all_entities)
    for i,d in enumerate(data['domains']):
        tables=[t for t in data['tables'] if t['domain']==d['key']]
        names={t['name'] for t in tables}
        # 每条关系按引用方所属域恰好归档一次。既有表引用除外，收入目录域。
        relations=[r for r in data['relations'] if r['child'] in names or (d['key']=='catalog' and r['child'] not in {t['name'] for t in data['tables']})]
        entity_names=names|{r['parent'] for r in relations}|{r['child'] for r in relations}
        entities={n:all_entities[n] for n in all_entities if n in entity_names}
        prefix='industry-plan-mall-'+d['key']
        result[DIAGRAMS/(prefix+'.mmd')]=mermaid(entities,relations)
        result[DIAGRAMS/(prefix+'.svg')]=domain_svg(d,tables,relations,all_entities,i)
    return result


def verify_links(doc,products):
    ids=set(re.findall(r'<a id="([^"]+)"',doc))
    # GitHub/Markdown中文标题自动锚点；字段导航使用显式ASCII锚点。
    for h in re.findall(r'^#{1,6} (.+)$',doc,re.M):
        ids.add(re.sub(r'[^\w\-\u4e00-\u9fff ]','',h.lower()).replace(' ','-'))
    for link in re.findall(r'!?\[[^\]]*\]\(([^)]+)\)',doc):
        path,sep,frag=link.partition('#')
        if not path:
            assert frag in ids, f'内部锚点不存在：{link}'
        elif not re.match(r'https?://',path):
            dest=(DOC.parent/path).resolve()
            assert dest.exists() or dest in products,f'本地链接目标不存在：{link}'


def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    data=json.loads(SCHEMA.read_text());by,all_entities=validate(data)
    products=outputs(data,all_entities)
    verify_links(products[DOC],products)
    for path,content in products.items():
        if path.suffix=='.svg':
            tree=ET.fromstring(content)
            texts=' '.join(tree.itertext())
            expect=data['tables'] if path.name.endswith('global.svg') else [t for t in data['tables'] if t['domain'] in path.stem]
            for table in expect:assert table['name'] in texts, f'SVG遗漏{table["name"]}'
        elif path.suffix=='.mmd':
            assert content.count('{') >= content.count('}') # 字段块以外的o{为ER多端符号
        if args.check:
            assert path.exists() and path.read_text()==content,f'产物未生成或落后于JSON：{path.relative_to(ROOT)}'
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content)
    print(('CHECK OK' if args.check else 'GENERATED')+f": 33 tables; {sum(len(t['fields']) for t in by.values())} expanded fields; {len(data['relations'])} relations; {len(products)} artifacts")

