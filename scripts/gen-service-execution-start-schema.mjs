#!/usr/bin/env node
// Renders only the forward ACK migration and its runtime descriptor. No database IO.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = path => JSON.parse(readFileSync(resolve(root, path), 'utf8'));
const basePath = 'backend/shop-core/src/main/resources/META-INF/shop/manual-service-execution-schema.json';
const truth = 'backend/shop-core/src/main/schema/service-execution-start-schema.json';
const resource = 'backend/shop-core/src/main/resources/META-INF/shop/service-execution-start-schema.json';
const migration = 'backend/shop-app/src/main/resources/db/migration/V668__service_execution_start_ack.sql';
const hash = value => createHash('sha256').update(value).digest('hex');
const identifier = value => {
  if (!/^[a-z][a-z0-9_]{0,63}$/.test(value)) throw new Error('Invalid schema identifier');
  return value;
};
function checksum(sql) {
  let crc = 0xffffffff;
  for (const byte of Buffer.from(sql.replace(/^\uFEFF/, '').split(/\r\n|\n|\r/).join(''))) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) | 0;
}

/** The changes manifest is authoritative; the base descriptor remains frozen and is never regenerated here. */
export function render(source, base) {
  if (source.schemaVersion !== 1 || ![668, 669].includes(source.platformVersion) || source.owner !== 'shop-core/primary'
      || source.baseMigrationSha256 !== base.migrationSha256) throw new Error('ACK base/schema drift');
  const tables = structuredClone(base.tables);
  const statements = [];
  for (const change of source.changes) {
    const table = tables.find(table => table.name === identifier(change.name));
    if (!table) throw new Error('Unknown ACK table');
    for (const column of change.addedColumns) {
      identifier(column.name);
      if (table.columns.some(value => value.name === column.name)
          || !/^(?:var)?char\([1-9][0-9]*\)$/.test(column.type)
          || !['ascii', 'utf8mb4'].includes(column.charset)
          || !['ascii_bin', 'utf8mb4_bin'].includes(column.collation) || !column.nullable) {
        throw new Error('Invalid ACK column');
      }
      statements.push(`ALTER TABLE ${table.name} ADD COLUMN ${column.name} ${column.type.toUpperCase()}`
        + ` CHARACTER SET ${column.charset} COLLATE ${column.collation} NULL`);
      table.columns.push(column);
    }
    for (const [name, columns] of Object.entries(change.addedUnique)) {
      if (table.unique[identifier(name)] || columns.some(c => !table.columns.some(v => v.name === c))) {
        throw new Error('Invalid ACK unique key');
      }
      statements.push(`ALTER TABLE ${table.name} ADD UNIQUE KEY ${name} (${columns.join(', ')})`);
      table.unique[name] = columns;
    }
    for (const [name, expression] of Object.entries(change.addedChecks)) {
      if (table.checks[identifier(name)]) throw new Error('Duplicate ACK check');
      statements.push(`ALTER TABLE ${table.name} ADD CONSTRAINT ${name} CHECK (${expression})`);
      table.checks[name] = expression;
    }
    for (const [name, expression] of Object.entries(change.replacedChecks)) {
      if (!table.checks[identifier(name)]) throw new Error('Missing replaced ACK check');
      statements.push(`ALTER TABLE ${table.name} DROP CHECK ${name}`);
      statements.push(`ALTER TABLE ${table.name} ADD CONSTRAINT ${name} CHECK (${expression})`);
      table.checks[name] = expression;
    }
  }
  const triggers = source.triggers.map(trigger => {
    identifier(trigger.name); identifier(trigger.table);
    if (trigger.timing !== 'BEFORE' || trigger.event !== 'UPDATE') throw new Error('Invalid ACK trigger');
    return `DELIMITER $$\nCREATE TRIGGER ${trigger.name} ${trigger.timing} ${trigger.event} ON ${trigger.table}`
      + `\nFOR EACH ROW\n${trigger.body}$$\nDELIMITER ;`;
  });
  const generator = source.platformVersion === 668 ? 'start' : 'completion';
  const sql = `-- Generated by scripts/gen-service-execution-${generator}-schema.mjs; do not edit.\n`
    + (source.platformVersion === 668
      ? '-- Actual resource acknowledgement only; no historical effects or human service are backfilled.\n\n'
      : '-- Records only new original completions; historical service and payment facts are not backfilled.\n\n')
    + statements.map(value => `${value};`).join('\n\n') + '\n\n' + triggers.join('\n\n') + '\n';
  const descriptor = {
    schemaVersion: 1, platformVersion: source.platformVersion, owner: source.owner,
    migrationScript: source.migrationScript ?? 'V668__service_execution_start_ack.sql', migrationSha256: hash(sql),
    flywayChecksum: checksum(sql), baseMigrationSha256: base.migrationSha256,
    ownerIdentity: base.ownerIdentity, tables, triggers: source.triggers,
    postTriggers: [...(base.postTriggers ?? base.triggers), ...source.triggers], alterStatements: statements,
    statementHashes: statements.map(hash), changes: source.changes,
  };
  return { sql, descriptor };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
const rendered = render(read(truth), read(basePath));
for (const [path, content] of [[migration, rendered.sql], [resource, JSON.stringify(rendered.descriptor, null, 2) + '\n']]) {
  if (process.argv.includes('--check')) {
    if (readFileSync(resolve(root, path), 'utf8') !== content) throw new Error(`Stale generated file: ${path}`);
  } else writeFileSync(resolve(root, path), content);
}
}
