// This supplementary contract is generated from live Java mappings/Jackson DTOs, not the existing UI mocks.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const quote = JSON.stringify;
export function renderType(schema = {}) {
    if (Object.hasOwn(schema, 'const')) return quote(schema.const);
    if (schema.$ref) {
        if (!schema.$ref.startsWith('#/components/schemas/')) throw new Error('Only local DTO references are supported');
        return schema.$ref.slice('#/components/schemas/'.length);
    }
    if (schema.enum) return schema.enum.map(quote).join(' | ') || 'never';
    if (schema.anyOf || schema.oneOf) return [...new Set((schema.anyOf ?? schema.oneOf).map(renderType))].join(' | ');
    if (schema.allOf) return schema.allOf.map(s => `(${renderType(s)})`).join(' & ');
    if (Array.isArray(schema.type)) return schema.type.map(type => renderType({ ...schema, type })).join(' | ');
    switch (schema.type) {
        case 'null': return 'null';
        case 'integer': case 'number': return 'number';
        case 'boolean': return 'boolean';
        case 'string': return 'string';
        case 'array': return `Array<${renderType(schema.items)}>`;
        case 'object': {
            if (schema.properties) {
                const required = new Set(schema.required ?? []);
                return `{ ${Object.entries(schema.properties).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0).map(([name, value]) =>
                    `${quote(name)}${required.has(name) ? '' : '?'}: ${renderType(value)};`).join(' ')} }`;
            }
            if (schema.additionalProperties === false) return 'Record<string, never>';
            return `Record<string, ${schema.additionalProperties === true ? 'unknown' : renderType(schema.additionalProperties)}>`;
        }
        case undefined: return 'unknown';
        default: throw new Error(`Unsupported JSON schema type ${schema.type}`);
    }
}
export function validateSpec(spec) {
    if (spec.openapi !== '3.1.0') throw new Error('Expected OpenAPI 3.1');
    const definitions = spec.components?.schemas ?? {};
    function visit(value) {
        if (!value || typeof value !== 'object') return;
        if (value.$ref && !Object.hasOwn(definitions, value.$ref.slice('#/components/schemas/'.length))) {
            throw new Error(`Missing DTO ${value.$ref}`);
        }
        Object.values(value).forEach(visit);
    }
    visit(spec);
    const ids = new Set();
    for (const [path, methods] of Object.entries(spec.paths ?? {})) for (const [method, operation] of Object.entries(methods)) {
        if (ids.has(operation.operationId)) throw new Error(`Duplicate operation ${operation.operationId}`);
        ids.add(operation.operationId);
        const expected = [...path.matchAll(/\{([^}]+)}/g)].map(m => m[1]).sort();
        const actual = (operation.parameters ?? []).filter(p => p.in === 'path' && p.required).map(p => p.name).sort();
        if (quote(expected) !== quote(actual)) throw new Error(`Path parameters differ: ${method} ${path}`);
        if (!operation.responses?.['200']?.content?.['application/json']?.schema) throw new Error(`Missing response ${path}`);
    }
    if (ids.size < 50) throw new Error('Incomplete public contract inventory');
}
function parameters(operation, location) {
    const selected = (operation.parameters ?? []).filter(parameter => parameter.in === location);
    if (selected.length === 0) return 'Record<string, never>';
    return renderType({ type: 'object', properties: Object.fromEntries(selected.map(p => [p.name, p.schema])),
        required: selected.filter(p => p.required).map(p => p.name) });
}
export function renderContracts(spec) {
    validateSpec(spec);
    const lines = ['// GENERATED by scripts/gen-entitlement-backend-contracts.mjs. Do not edit.',
        '// Covers the selected Java backend routes; existing UI clients are unchanged.',
        '// Contextual business checks and constructors remain authoritative; dynamic JSON is unknown.',
        '// Monetary integers use minor units. Validate safe integer ranges before arithmetic.', ''];
    for (const [name, schema] of Object.entries(spec.components.schemas).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
        lines.push(`export type ${name} = ${renderType(schema)};`, '');
    }
    lines.push('export interface EntitlementBackendOperations {');
    const routes = [];
    for (const [path, methods] of Object.entries(spec.paths).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
        for (const [method, operation] of Object.entries(methods).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
            lines.push(`  ${quote(operation.operationId)}: {`,
                `    method: ${quote(method.toUpperCase())};`, `    path: ${quote(path)};`,
                `    query: ${parameters(operation, 'query')};`, `    headers: ${parameters(operation, 'header')};`,
                `    pathParams: ${parameters(operation, 'path')};`);
            const request = operation.requestBody;
            if (request) lines.push(`    body${request.required ? '' : '?'}: ${renderType(request.content['application/json'].schema)};`);
            lines.push(`    response: ${renderType(operation.responses['200'].content['application/json'].schema)};`, '  };');
            routes.push({ operationId: operation.operationId, method: method.toUpperCase(), path });
        }
    }
    lines.push('}', '', `export const ENTITLEMENT_BACKEND_ROUTES = ${quote(routes)} as const;`, '');
    return lines.join('\n');
}
function sorted(value) {
    if (Array.isArray(value)) return value.map(sorted);
    if (value && typeof value === 'object') return Object.fromEntries(Object.keys(value).sort().map(k => [k, sorted(value[k])]));
    return value;
}
function main() {
    if (!process.argv.includes('--from-spec')) {
        const result = spawnSync('mvn', ['-o', '-f', 'backend/pom.xml', '-pl', 'shop-app', '-am',
            '-Dtest=EntitlementApiContractCoverageTest', '-Dsurefire.failIfNoSpecifiedTests=false', 'test'],
        { cwd: root, env: process.env, stdio: 'inherit' });
        if (result.error) throw result.error;
        if (result.status !== 0) throw new Error(`Java contract extraction failed (${result.status})`);
    }
    const spec = sorted(JSON.parse(readFileSync(resolve(root, 'backend/shop-app/target/entitlement-backend.openapi.json'), 'utf8')));
    const outputs = new Map([
        ['docs/api/entitlement-backend.openapi.json', JSON.stringify(spec, null, 2) + '\n'],
        ['packages/shared/src/generated/entitlement-backend.ts', renderContracts(spec)],
    ]);
    for (const [relative, text] of outputs) {
        const path = resolve(root, relative);
        if (process.argv.includes('--check')) {
            if (readFileSync(path, 'utf8') !== text) throw new Error(`Stale backend contract: ${relative}`);
        } else {
            mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, text);
        }
    }
    console.log(`Backend contract verified: ${Object.values(spec.paths).reduce((n, methods) => n + Object.keys(methods).length, 0)} operations, ${Object.keys(spec.components.schemas).length} DTO schemas.`);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
